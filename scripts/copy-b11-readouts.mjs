#!/usr/bin/env node
// Copies what the Readouts pane and its "Work backward from readings" door need from the 2D app, so no number, word or step is retyped (parity plan section 2).
//   src/ui/tests/readouts/copied/display-state.copied.js   display-state.js whole (createShownState: the page's shown readings, the critically damped follow the tiles and bars glide on)
// Usage: node scripts/copy-b11-readouts.mjs --from <2D checkout> [--check]    (--check writes nothing and fails when a file would change)
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';

const args = process.argv.slice(2);
const flag = (n) => { const i = args.indexOf(n); return i >= 0 ? args[i + 1] : null; };
const from = flag('--from') ?? process.env.PPS_2D_REPO;
const check = args.includes('--check');
if (!from || !existsSync(`${from}/src/ui/display-state.js`)) { console.error('usage: copy-b11-readouts.mjs --from <2D checkout>'); process.exit(2); }
let commit = 'unknown';
try { commit = execFileSync('git', ['-C', from, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim(); } catch { /* not a checkout */ }

const dir = new URL('../src/ui/tests/readouts/copied/', import.meta.url);
mkdirSync(dir, { recursive: true });
const changed = [];
const put = (name, text) => {
  const url = new URL(name, dir);
  if (existsSync(url) && readFileSync(url, 'utf8') === text) return;
  changed.push(name);
  if (!check) writeFileSync(url, text);
};
const HEAD = (what) => `// GENERATED by scripts/copy-b11-readouts.mjs from the 2D app at ${commit.slice(0, 8)} (${what}). Do not edit; run the script again.\n`;
const read = (p) => readFileSync(`${from}/${p}`, 'utf8');

/** Import specifiers: the 2D engine copy becomes this repo's, the 2D helpers named in `map` become their 3D twins; anything else is an error. */
function rewrite(name, src, map) {
  return src.replace(/(from\s*|import\s*)'([^']+)'/g, (m, kw, spec) => {
    if (!spec.startsWith('.')) return m;
    const eng = /^\.\.\/engine\/(core|portal)\/(.+)$/.exec(spec);
    if (eng) return `${kw}'../../../../engine/hales/${eng[1]}/${eng[2]}'`;
    if (map[spec]) return `${kw}'${map[spec]}'`;
    throw new Error(`${name}.js imports '${spec}', which is not in the map`);
  });
}
const WHOLE = [
  ['display-state', {}],
];
for (const [n, map] of WHOLE) put(`${n}.copied.js`, HEAD(`${n}.js`) + rewrite(n, read(`src/ui/${n}.js`), map));

if (changed.length) { console.log(`${check ? 'would change' : 'wrote'}: ${changed.join(', ')}`); if (check) process.exit(1); } else console.log('src/ui/tests/readouts/copied is current');
