#!/usr/bin/env node
// Batch B13b (decks H to P): copies the 2D decks whose ids run from H to P into the 3D app, verbatim, by script.
//
//   node scripts/port-decks-hp.mjs --from <2D checkout> [--check] [--numbers]
//
// Writes src/decks/hp/data/<id>.copied.ts (every field of every slide as the 2D deck has it: words, model fields, tool, tiles, camera name…),
// src/decks/hp/regions.copied.ts (the 2D camera regions), and src/decks/hp/ids.copied.ts (the decks, in the 2D menu order).
// --check writes nothing and exits 1 when a copied file differs from what the 2D checkout gives (the unit test runs it when a 2D checkout is
// at hand). --numbers also writes tests/fixtures/decks-hp-numbers.json: the 2D engine's reading of every tile on every slide, which the
// number test replays through the 3D app's pinned engine. Words are never retyped: change the 2D deck, run this again.

import { writeFileSync, mkdirSync, readFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { bavenoEdits } from './baveno-edits.mjs';
import { pathToFileURL, fileURLToPath } from 'node:url';
import { resolve, dirname, join } from 'node:path';
import { execFileSync } from 'node:child_process';

const here = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(here, '../src/decks/hp');
const FIXTURE = resolve(here, '../tests/fixtures/decks-hp-numbers.json');

/** The decks this batch owns: every 2D deck id from H to P (the batch split of docs/parity-plan.md: A to G, H to P, R to W). The rule is the id, not the title. */
export const IN_RANGE = (id) => /^[h-p]/i.test(id);

/** Model fields of a slide (decks.js withOverview, tests/deck-states.js): the ones that change the patient. */
const MODEL = ['preset', 'presetDays', 'params', 'action', 'days'];

function clean(v, where) {
  // plain data only: a function or a symbol in a deck would be lost by a JSON copy, which is the kind of silent change this script exists to stop
  return JSON.parse(JSON.stringify(v, (k, x) => {
    if (typeof x === 'function' || typeof x === 'symbol') throw new Error(`${where}.${k} is a ${typeof x}, which a copy cannot keep`);
    if (x === undefined) return null;
    return x;
  }));
}

export function extractDeck(d) {
  const { slides, ...rest } = d;
  return clean({ ...rest, slides: slides.map((s, i) => clean(s, `${d.id}.slides[${i}]`)) }, d.id);
}

export function render(deck, source) {
  const json = bavenoEdits(JSON.stringify(deck, null, 1));
  const hash = createHash('sha256').update(json).digest('hex').slice(0, 12);
  return `// @generated by scripts/port-decks-hp.mjs from ${source}. Do not edit: run the script again.
// The 2D deck, every field as it is there. The 3D fields (camera shot, lens, features a slide needs) are derived in src/decks/hp/plan.ts, never written here.
// content hash ${hash}
import type { CopiedDeck } from '../types.ts';

export const DECK: CopiedDeck = ${json};

export const DECK_HASH = '${hash}';
`;
}

export async function load2D(root) {
  await import(pathToFileURL(resolve(root, 'tests/dom-shim.js')).href);
  const decks = await import(pathToFileURL(resolve(root, 'src/ui/decks.js')).href);
  const cams = await import(pathToFileURL(resolve(root, 'src/ui/cam-frame.js')).href);
  let commit = 'unknown';
  try { commit = execFileSync('git', ['-C', resolve(root), 'rev-parse', '--short=10', 'HEAD'], { encoding: 'utf8' }).trim(); } catch { /* not a git checkout */ }
  return { DECKS: decks.DECKS, REGIONS: decks.REGIONS, CIRC_REGIONS: cams.CIRC_REGIONS, commit, root: resolve(root) };
}

export function files(two, source) {
  const mine = two.DECKS.filter((d) => IN_RANGE(d.id));
  const out = new Map();
  for (const d of mine) out.set(`data/${d.id}.copied.ts`, render(extractDeck(d), source));
  out.set('regions.copied.ts', `// @generated by scripts/port-decks-hp.mjs from ${source}. Do not edit: run the script again.
// The 2D camera regions (anatomy world units, x 300 to 1120, y 0 to 920) and the Circuit view's (circuit units): a slide's \`cam\` names one.
export const REGIONS: Record<string, readonly [number, number, number, number]> = ${JSON.stringify(two.REGIONS)};
export const CIRC_REGIONS: Record<string, readonly [number, number, number, number]> = ${JSON.stringify(two.CIRC_REGIONS)};
`);
  out.set('ids.copied.ts', `// @generated by scripts/port-decks-hp.mjs from ${source}. Do not edit: run the script again.
// The decks of batch B13b, in the 2D app's order, with the names the 2D menu and the deck tab use.
export const HP_DECKS: readonly { id: string; short: string; head: string; topic: string; slides: number }[] = ${JSON.stringify(mine.map((d) => ({ id: d.id, short: d.short, head: d.head, topic: d.topic, slides: d.slides.length })), null, 1)};
`);
  return out;
}

/** The 2D engine's reading of every tile on every slide of my decks (one 'sequence' per deck, as the 2D presenter runs it). */
export async function numbers(two) {
  const { deckStates } = await import(pathToFileURL(resolve(two.root, 'tests/deck-states.js')).href);
  const { withOverview } = await import(pathToFileURL(resolve(two.root, 'src/ui/decks.js')).href);
  const { valueText } = await import(pathToFileURL(resolve(two.root, 'src/ui/callout-math.js')).href);
  const { cutText, TILE } = await import(pathToFileURL(resolve(two.root, 'src/ui/table-marks.js')).href);
  const out = {};
  for (const d of two.DECKS.filter((x) => IN_RANGE(x.id))) {
    const shown = withOverview(d);                 // the outline is slide 0 of the chain, as in the app
    const fps = await deckStates(shown);
    const at = (id) => fps[shown.slides.findIndex((s) => s.id === id)];
    out[d.id] = shown.slides.map((s, i) => ({ s, i })).filter(({ s }) => s.id !== 'outline' && s.id !== 'check').map(({ s, i }) => {
      // the line's braces as the 2D card prints them (presenter-words.js rich: a reading, whole, at another slide, a cut-off, a typed number)
      const tokens = [];
      for (const m of `${s.line} ${s.vignette || ''}`.matchAll(/\{([^}]+)\}/g)) {
        const b = m[1]; let t;
        if (TILE[b]) t = valueText(b, fps[i]);
        else if (/^(\w+):0$/.test(b) && TILE[b.split(':')[0]]) t = valueText(b.split(':')[0], fps[i], true);
        else if (/^(\w+)@([\w-]+)$/.test(b) && TILE[b.split('@')[0]]) t = valueText(b.split('@')[0], at(b.split('@')[1]));
        else if (/^[<>≥≤]=?/.test(b)) t = cutText(b);
        else t = b;
        tokens.push([m[0], t]);
      }
      return { id: s.id, fp: scalars(fps[i]), tokens };
    });
  }
  return out;
}

/** Every number a slide's words or tiles can read: the scalar finite readings of the fingerprint, to 6 significant digits. */
export function scalars(fp) {
  const o = {};
  for (const [k, v] of Object.entries(fp || {})) if (typeof v === 'number' && Number.isFinite(v)) o[k] = Number(v.toPrecision(6));
  return o;
}

async function main() {
  const args = process.argv.slice(2);
  const at = args.indexOf('--from');
  if (at < 0 || !args[at + 1]) { console.error('usage: node scripts/port-decks-hp.mjs --from <2D checkout> [--check] [--numbers]'); process.exit(2); }
  const two = await load2D(args[at + 1]);
  const source = `src/ui/decks/*.js of qaddodi/portal-pressure-simulator at ${two.commit}`;
  const map = files(two, source);
  const body = (t) => t.split('\n').filter((l) => !l.startsWith('// @generated')).join('\n');
  if (args.includes('--check')) {
    let bad = 0;
    for (const [name, text] of map) {
      const f = join(OUT, name);
      if (!existsSync(f) || body(readFileSync(f, 'utf8')) !== body(text)) { console.error(`src/decks/hp/${name} differs from the 2D app: run scripts/port-decks-hp.mjs again`); bad++; }
    }
    if (bad) process.exit(1);
    console.log(`${map.size} copied files match the 2D app`);
    return;
  }
  mkdirSync(join(OUT, 'data'), { recursive: true });
  for (const [name, text] of map) writeFileSync(join(OUT, name), text);
  console.log(`wrote ${map.size} files to src/decks/hp (2D at ${two.commit})`);
  if (args.includes('--numbers')) {
    const t0 = Date.now();
    const n = await numbers(two);
    mkdirSync(dirname(FIXTURE), { recursive: true });
    writeFileSync(FIXTURE, JSON.stringify({ from: two.commit, decks: n }) + '\n');
    console.log(`wrote ${FIXTURE} (${Object.values(n).reduce((a, r) => a + r.length, 0)} slides, ${Math.round((Date.now() - t0) / 1000)} s)`);
  }
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) { await main(); process.exit(0); }
