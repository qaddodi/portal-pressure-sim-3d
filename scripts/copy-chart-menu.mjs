#!/usr/bin/env node
// Copies the pure half of the 2D app's treatment-menu chart (src/ui/tool-menu.js: the ten treatments and what each changes, which are offered to a patient, the steps the worker runs,
// the dots, the PPG's rating colour, the dot's size and the chart's geometry) into src/ui/charts/menu/menu-pure.generated.js, line for line. What is cut is the drawing (the svg builder,
// the glide) and the presenter's cache of the worker's results; the imports are pointed at this app's own copies of the files they name.
//
//   node scripts/copy-chart-menu.mjs --from <2D checkout at the pin> [--check]
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const here = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(here, '../src/ui/charts/menu/menu-pure.generated.js');
const arg = (n) => { const i = process.argv.indexOf(n); return i > 0 ? process.argv[i + 1] : null; };
const from = arg('--from');
if (!from) { console.error('usage: node scripts/copy-chart-menu.mjs --from <2D checkout at the pin> [--check]'); process.exit(2); }
let sha = 'b3058ef392';
try { sha = execFileSync('git', ['-C', from, 'rev-parse', '--short=10', 'HEAD'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim(); } catch { /* not a git checkout */ }

/** The text from the line holding `start` up to (not with) the line holding `end`. */
function slice(text, start, end) {
  const a = text.indexOf(start), b = text.indexOf(end);
  if (a < 0 || b < 0 || b < a) throw new Error(`markers not found: ${start} … ${end}`);
  return text.slice(text.lastIndexOf('\n', a) + 1, text.lastIndexOf('\n', b) + 1);
}
const t = readFileSync(join(from, 'src/ui/tool-menu.js'), 'utf8');
const imports = [
  "import { RATE } from '../../deck/from2d/table-marks.js';",
  "import { SEV_OF_RATE } from '../../../engine/hales/portal/pressure-cuts.js';",
  "import { leftScale, xDomain, xAxisRow, xAxisName, fmtTick, placeDotNames, placeWord, namesCrowded, cutsOf } from '../curve/curve-pure.generated.js';",
  "import { SURGICAL_BY_ID } from '../../../scene/procedures/copied/surgical-shunts.js';",
  "import { procLabel } from '../../../scene/procedures/copied/procedure-names.js';",
].join('\n');
const text = `// @generated by scripts/copy-chart-menu.mjs from the 2D app's src/ui/tool-menu.js at ${sha}. Do not edit; run the script again.
// @ts-nocheck (the 2D app's own code, kept as it is: the drawing half is src/ui/charts/menu/frame.ts)
${imports}
${slice(t, 'const CV_MIN = 12;', '// Each deck\'s menus, kept once worked out')}
${slice(t, '/** The chart\'s geometry for a card', '/** The drawing: { svg, G }.')}`;
if (process.argv.includes('--check')) {
  if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== text) { console.error(`differs: ${OUT}`); process.exit(1); }
  console.log('menu-pure.generated.js is current'); process.exit(0);
}
mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, text);
console.log(`wrote ${OUT}`);
