#!/usr/bin/env node
// Copies what the Doppler pane (Tests > Doppler, B11) needs from the 2D app's doppler.js, so no word, range or judgement is retyped (parity plan section 2).
// doppler.js is one 1,600-line closure around DOM and WebGL, so the pure parts are cut out by line markers and wrapped:
//   src/ui/tests/doppler/copied/doppler-tables.copied.js   the probes (vessel, name, kind, usual range), the stent notes, the resistive-index words, the settings words, the tiles' hover words, `num`
//   src/ui/tests/doppler/copied/doppler-reading.copied.js  `createReading(env)`: the reading (3 s mean, peak, trough, the median beat), the stent's gates, the vessel's usual range and `interpret` (the words after the number)
//   src/ui/tests/doppler/copied/gate-factors.copied.js     gate-factors.js whole
//   src/ui/tests/doppler/copied/doppler-gl.copied.js        the trace's display pass shader (the noise floor and the wall filter), spliced with the line shader by spectrum-gl.ts
//   src/ui/tests/doppler/copied/doppler-colours.copied.js  the colour maps' tokens (--dop-*) and the display modes (dopplerColor.js), the probe's beam angle (dop-probe.js)
// Usage: node scripts/copy-b11-doppler.mjs --from <2D checkout> [--check]    (--check writes nothing and fails when a file would change)
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { loadOrder } from './copy-2d-css.mjs';

const args = process.argv.slice(2);
const flag = (n) => { const i = args.indexOf(n); return i >= 0 ? args[i + 1] : null; };
const from = flag('--from') ?? process.env.PPS_2D_REPO;
const check = args.includes('--check');
if (!from || !existsSync(`${from}/src/ui/doppler.js`)) { console.error('usage: copy-b11-doppler.mjs --from <2D checkout>'); process.exit(2); }
let commit = 'unknown';
try { commit = execFileSync('git', ['-C', from, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim(); } catch { /* not a checkout */ }

const dir = new URL('../src/ui/tests/doppler/copied/', import.meta.url);
mkdirSync(dir, { recursive: true });
const changed = [];
const put = (name, text) => {
  const url = new URL(name, dir);
  if (existsSync(url) && readFileSync(url, 'utf8') === text) return;
  changed.push(name);
  if (!check) writeFileSync(url, text);
};
const HEAD = (what) => `// GENERATED by scripts/copy-b11-doppler.mjs from the 2D app at ${commit.slice(0, 8)} (${what}). Do not edit; run the script again.\n`;
const read = (p) => readFileSync(`${from}/${p}`, 'utf8');

const src = read('src/ui/doppler.js').split('\n');
const at = (re, k0 = 0) => { const i = src.findIndex((l, k) => k >= k0 && re.test(l)); if (i < 0) throw new Error(`doppler.js has no line for ${re}`); return i; };
const lines = (a, b) => src.slice(a, b + 1);
/** the line at `re`, and the ones after it up to and including the first that matches `end` */
const block = (re, end, k0 = 0) => { const a = at(re, k0); let b = a; while (!end.test(src[b])) b++; return lines(a, b); };

// ── the tables ──
const iTables0 = at(/^const EI = Object\.fromEntries/), iTables1 = at(/^\} \/\/ Start at 6 s/);
const skip0 = at(/^const FADE_KEYS/), skip1 = at(/^const SURF_LOST/);   // (the ?perf surfaces' words and the fade's keyframes: DOM and the GPU monitor, not copied)
const tables = [...lines(iTables0, skip0 - 1), ...lines(skip1 + 1, iTables1),
  ...lines(at(/^const PAD_L = 12/), at(/^const PAD_L = 12/)), ...lines(at(/^const MINUS = /), at(/^const MINUS = /)),
  ...block(/^const STAT_TITLE = \{/, /^\};/), ...lines(at(/^const num = /), at(/^const num = /))];
const segs = block(/^  const SEGS = /, /\];\s*$/);
put('doppler-tables.copied.js', HEAD('doppler.js, the probes, notes and settings words') + [
  `import { EDGES, stentCourse } from '../../../../engine/hales/portal/topology.js';`,
  `import { PROBE_NORMAL } from '../../../../scene/lenses/vel-normal.copied.js';`,
  `import { fmt } from '../../copied/num.copied.js';`,
  `import { THETA } from './doppler-colours.copied.js';`,
  ...tables.map((l) => l.replace(/^const (EI|STENT_OUT|PROBES|RI_TEXT|GATE_NAME|RANGE_NOTES|REDUCTION_NOTE|GATE_KINDS|NOTE_TAIL|PROBES_BY_ID|PI_TEXT|SWEEP_SECONDS|SETTINGS|PAD_L|MINUS|STAT_TITLE|num)\b/, 'export const $1').replace(/^function rangeNoteOf/, 'export function rangeNoteOf').replace(/^const (probeName|NOTE_BACK)\b/, 'export const $1')),
  `export const SEGS = ${segs.join('\n').replace(/^\s*const SEGS = /, '').replace(/;\s*$/, '')};`,
].join('\n') + '\n');

// ── the reading, wrapped as a factory over the closure state it reads ──
const rd0 = at(/^  \/\/ ── Reading ──/), rd1 = at(/^  \/\/ A tile value: the number/) - 1;
const beat = block(/^  const BEAT_MAX = 16/, /beatT = new Float64Array/);
const facs = lines(at(/^  const facs = gateFactors\(\)/), at(/^  const facs = gateFactors\(\)/));
const hold = lines(at(/^  const HOLD_AFTER = SETTLE/), at(/^  const HOLD_AFTER = SETTLE/));
let body = lines(rd0, rd1).join('\n');
// (doppler.js reads the store's parameters and the chosen gate; the pane hands them in)
body = body.replace(/store\.get\(\)\.params/g, 'env.params()').replace(/store\.get\(\)\.dopGate/g, 'env.dopGate()');
if (/store\./.test(body)) throw new Error('doppler.js reading still reads the store somewhere else');
put('doppler-reading.copied.js', HEAD('doppler.js, reading() to say()') + [
  `import { EDGES, dopplerK, stentReadsOf, stentGate } from '../../../../engine/hales/portal/topology.js';`,
  `import { gateKindsFromParams, reductionJet, kindOf } from '../../../../engine/hales/portal/stent-geom.js';`,
  `import { stentStill } from '../../../../engine/hales/portal/flow-cuts.js';`,
  `import { velNormal, judgeFlow } from '../../../../scene/lenses/vel-normal.copied.js';`,
  `import { pulsatility } from '../../copied/doppler-marks.copied.js';`,
  `import { gateFactors } from './gate-factors.copied.js';`,
  `import { clamp } from '../../copied/num.copied.js';`,
  `import { EI, STENT_OUT, PROBES, RI_TEXT, GATE_KINDS, NOTE_BACK, NOTE_SLOW, NOTE_NOT_EXPECTED, REDUCTION_NOTE, rangeNoteOf, SEGS } from './doppler-tables.copied.js';`,
  ``,
  `/** The Doppler's reading of the record it is handed. env: { params(): the patient's parameters, dopGate(): 'proximal' | 'mid' | 'distal' | 'site' | null }. The closure state doppler.js keeps (the record, the beat times, the frame, the probe...) is set by sync(). */`,
  `export function createReading(env) {`,
  `  let buf = [], beatN = 0, probe = null, frame = null, gi = -1, effOk = false, heldTo = null, invert = false;`,
  ...beat, ...facs, ...hold.map((l) => l.replace(/^(\s*)const HOLD_AFTER = SETTLE;.*$/, '$1// (HOLD_AFTER is below the reading, once SETTLE is known)')),
  body,
  `  const HOLD_AFTER = SETTLE;   // s of the settled signal recorded before the scale fits it (and the reading reads only it)`,
  `  return {`,
  `    reading, interpret, meta, normalOf, svMm, stentReads, shownReads, stentStopped, gateOf, gateIndex, gateKinds, gateFactor, isStentProbe, pol, medianBeat, facs, EFF, SEEN, HOLD_AFTER, SETTLE,`,
  `    /** the record and state a reading reads (the record's array is kept by the caller and may grow between calls) */`,
  `    sync(s) { buf = s.buf; beatN = s.beatN; probe = s.probe; frame = s.frame; gi = s.gi; heldTo = s.heldTo; invert = !!s.invert; },`,
  `    get effOk() { return effOk; },`,
  `    beatT,`,
  `  };`,
  `}`,
].join('\n') + '\n');

// ── gate-factors.js whole ──
put('gate-factors.copied.js', HEAD('gate-factors.js') + read('src/ui/gate-factors.js'));

// ── the colour maps and modes ──
const tokens = read('styles/tokens.css');
const tok = (n) => { const m = new RegExp(`--${n}:\\s*([^;]+);`).exec(tokens); if (!m) throw new Error(`tokens.css has no --${n}`); return m[1].trim(); };
const rgb = (css) => {
  let m = /^rgb\(\s*(\d+),\s*(\d+),\s*(\d+)\s*\)$/.exec(css);
  if (m) return [+m[1], +m[2], +m[3]];
  m = /^#([0-9a-f]{6})$/i.exec(css);
  if (m) return [0, 2, 4].map((i) => parseInt(m[1].slice(i, i + 2), 16));
  throw new Error(`cannot read the colour ${css}`);
};
const colour = read('src/ui/dopplerColor.js');
const modes = /export const DOPPLER_MODES = \[[\s\S]*?\n\];/.exec(colour)?.[0];
if (!modes) throw new Error('dopplerColor.js has no DOPPLER_MODES');
const angle = /ANGLE:\s*(\d+)/.exec(read('src/ui/dop-probe.js'))?.[1];
if (!angle) throw new Error('dop-probe.js has no ANGLE');
put('doppler-colours.copied.js', HEAD('dopplerColor.js, styles/tokens.css --dop-*, dop-probe.js ANGLE') + [
  `// The beam-to-flow angle (the spectral header's θ, the figure probe's angle), degrees.`,
  `export const THETA = ${angle};`,
  modes,
  `// The maps' colours, 0 to 255 (tokens.css --dop-*; the same in every look).`,
  `export const MAP = { TOWARD: [${rgb(tok('dop-toward'))}], AWAY: [${rgb(tok('dop-away'))}], VAR_TOWARD: [[${rgb(tok('dop-var-toward'))}], [${rgb(tok('dop-var-toward-turb'))}]], VAR_AWAY: [[${rgb(tok('dop-var-away'))}], [${rgb(tok('dop-var-away-turb'))}]], WHITE: [${rgb(tok('dop-bright'))}] };`,
  ...[/^const smooth = .*$/m, /^const SOFT = .*$/m].map((re) => (re.exec(colour) ?? [''])[0]).filter(Boolean).map((l) => l.replace(/^const /, 'export const ')),
  `import { clamp01 } from '../../copied/num.copied.js';`,
  /\/\*\* Colour for one instant[\s\S]*?\n\}\n/.exec(colour)[0].replace(/map\(\)/g, 'MAP'),
  /\/\*\* Softened, brightness-modulated[\s\S]*?\n\}\n/.exec(colour)[0].replace(/map\(\)\.WHITE/g, 'MAP.WHITE'),
].join('\n') + '\n');
// ── the trace's display pass (doppler-gl.js FS): the noise floor and the wall filter's dark band, laid over the spectrum's lines ──
const glSrc = read('src/ui/doppler-gl.js');
const displayFs = /^const FS = `([\s\S]*?)`;/m.exec(glSrc)?.[1];
if (!displayFs || !/floorAt/.test(displayFs)) throw new Error('doppler-gl.js has no display shader FS');
put('doppler-gl.copied.js', HEAD('doppler-gl.js, the display pass FS') + [
  `// The trace's picture: the spectrum ring, the noise floor over it and the wall filter's dark band (2D draws it in the chart drawer's context, one fragment a pixel).`,
  `// The 3D app draws the lines in the same pass (spectrum-gl.ts splices doppler-synth's shader into this one: no ring), so a line's pixels are the 2D ones.`,
  `export const DISPLAY_FS = \`${displayFs}\`;`,
].join('\n') + '\n');
// ── the Tests card's Doppler rules: 2D's `.instrument-workspace` rules for the report, the tiles, the usual-range gauge and the switches, re-scoped to the 3D Tests card ──
// (2D scopes the dock card's look to `.instrument-workspace` (and `.float-ui`); the 3D card is `.t-card`, so each such selector is rewritten with the same number of classes, which keeps the
// rules' order of strength: `.instrument-workspace.float-ui` becomes `.t-card.t-card`. Layout of the dock (the side card, the phone's sheet, the presenter's cards, the box's size) is left out:
// the Tests card lays the monitor out itself, doppler.css. The rules that are not scoped to the dock apply as they stand, from the 2D stylesheets loaded whole.)
const KEEP_TOK = /\.dop-(modes|mode-opt|btns|inv|tint|stats|speed|range|track|band|mark|ticks|vel|dir|pattern|seg|g-)|\.dop-report \.dop-stats|\.instrument-view\.dop \.dop-stats/;
const DROP_TOK = /\.side\b|#app|\.pz|thumb|\.sheet|\.has-tool|data-kind|presenting|dock-pane|panel-open|instrument-focus|\.dop-box|\.dop-main|\.dop-head|\.dop-vessel|\.dop-sweep|\.dop-note|\.nat\b/;
function splitTop(sel, ch) { const out = []; let d = 0, a = 0; for (let i = 0; i < sel.length; i++) { const c = sel[i]; if (c === '(' || c === '[') d++; else if (c === ')' || c === ']') d--; else if (c === ch && d === 0) { out.push(sel.slice(a, i)); a = i + 1; } } out.push(sel.slice(a)); return out.map((x) => x.trim()).filter(Boolean); }
function topRules(text) {
  const rules = []; let i = 0;
  while (i < text.length) {
    if (text.startsWith('/*', i)) { const e = text.indexOf('*/', i); i = e < 0 ? text.length : e + 2; continue; }
    if (/\s/.test(text[i])) { i++; continue; }
    const b = text.indexOf('{', i); if (b < 0) break;
    let d = 1, j = b + 1; while (j < text.length && d) { if (text[j] === '{') d++; else if (text[j] === '}') d--; j++; }
    rules.push([text.slice(i, b).trim(), text.slice(b + 1, j - 1).trim()]);
    i = j;
  }
  return rules;
}
const rescope = (sel) => sel.replace(/\.instrument-workspace\.float-ui/g, '.t-card.t-card').replace(/\.instrument-workspace/g, '.t-card');
const cssOut = [];
for (const f of loadOrder(read('index.html'))) {
  for (const [sel, body] of topRules(read(`styles/${f}`))) {
    if (sel.startsWith('@')) continue;
    const parts = splitTop(sel, ',').filter((p) => /\.instrument-workspace/.test(p) && KEEP_TOK.test(p) && !DROP_TOK.test(p));
    if (parts.length) cssOut.push(`${parts.map(rescope).join(', ')} { ${body} }   /* ${f} */`);
  }
}
put('doppler-2d.copied.css', `/* GENERATED by scripts/copy-b11-doppler.mjs from the 2D app at ${commit.slice(0, 8)} (styles/*.css: the dock card's Doppler rules, .instrument-workspace re-scoped to .t-card). Do not edit; run the script again. */\n${cssOut.join('\n')}\n`);
if (changed.length) { console.log(`${check ? 'would change' : 'wrote'}: ${changed.join(', ')}`); if (check) process.exit(1); }
else console.log('src/ui/tests/doppler/copied is current');
