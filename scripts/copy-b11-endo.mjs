#!/usr/bin/env node
// Copies what the Endoscopy pane needs from the 2D app, so no column, colour or word is retyped (parity plan section 2).
//   src/ui/tests/copied/endo-field.copied.js   the scope field's pure geometry cut out of endo-render.js: the four varix columns (makeColumns, centre), the height field and the
//                                              noise it uses. The 3D app draws the field as a cel-shaded vector frame on the charts' shared GPU drawer (it makes no shader of its own),
//                                              from the same columns the 2D shader and its CPU twin draw.
//   src/ui/tests/copied/endo-words.copied.js   the words of the Endoscopy card (instruments.js createEndoscopy, eus-ppg.js), cut by pattern; a pattern that finds nothing is an error.
//   src/ui/tests/copied/wall-geometry.copied.js  Wall mechanics' layout (wall-geometry.js, byte for byte but its one import): where the ring, the varix and every name go, from the names' ink.
//   src/ui/tests/endo/wall.copied.css          the Wall mechanics tiles' rules (styles/app-09-tests.css, the "Wall mechanics in the Tests card" block) with the 2D dock's selector prefix swapped for `.en-wall`.
//   src/ui/tests/copied/scope-tokens.copied.js the scope's colour tokens (styles/tokens.css :root: --scope-*, --endo-*, --red-wale), look-independent in 2D.
// Usage: node scripts/copy-b11-endo.mjs --from <2D checkout> [--check]    (--check writes nothing and fails when a file would change)
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';

const args = process.argv.slice(2);
const flag = (n) => { const i = args.indexOf(n); return i >= 0 ? args[i + 1] : null; };
const from = flag('--from') ?? process.env.PPS_2D_REPO;
const check = args.includes('--check');
if (!from || !existsSync(`${from}/src/ui/instruments.js`)) { console.error('usage: copy-b11-endo.mjs --from <2D checkout>'); process.exit(2); }
let commit = 'unknown';
try { commit = execFileSync('git', ['-C', from, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim(); } catch { /* not a checkout */ }
const dir = new URL('../src/ui/tests/copied/', import.meta.url);
mkdirSync(dir, { recursive: true });
const changed = [];
const put = (name, text) => {
  const url = new URL(name, dir);
  if (existsSync(url) && readFileSync(url, 'utf8') === text) return;
  changed.push(name);
  if (!check) writeFileSync(url, text);
};
const HEAD = (what) => `// GENERATED by scripts/copy-b11-endo.mjs from the 2D app at ${commit.slice(0, 8)} (${what}). Do not edit; run the script again.\n`;
const read = (p) => readFileSync(`${from}/${p}`, 'utf8');

// ── the field's geometry: endo-render.js from `const TAU` up to the pixel loop's record (SEEN) ──
{
  const lines = read('src/ui/endo-render.js').split('\n');
  const a = lines.findIndex((l) => /^const TAU = /.test(l)), b = lines.findIndex((l) => /^const SEEN = /.test(l));
  if (a < 0 || b < 0 || b < a) throw new Error('endo-render.js: the field block moved');
  let body = lines.slice(a, b).join('\n');
  body = body
    .replace(/^const (TAU|T|NCOL|COLS|sstep|wrapPi) /gm, 'export const $1 ')
    .replace(/^function (h2|nz|rnd|makeColumns|centre|field)\b/gm, 'export function $1');
  for (const n of ['TAU', 'T', 'NCOL', 'COLS', 'sstep', 'wrapPi', 'h2', 'nz', 'makeColumns', 'centre', 'field']) if (!new RegExp(`export (const|function) ${n}\\b`).test(body)) throw new Error(`endo-render.js: no ${n}`);
  put('endo-field.copied.js', HEAD(`endo-render.js lines ${a + 1}-${b}`) + body + '\n');
}

// ── the words ──
{
  const ins = read('src/ui/instruments.js'), eus = read('src/ui/eus-ppg.js');
  const grab = (src, re, what) => { const m = re.exec(src); if (!m) throw new Error(`no ${what}`); return m[1]; };
  const W = {
    position: grab(ins, /class: 'endo-pos' \}, '([^']+)'\)/, 'the position caption'),
    gradeTip: grab(ins, /class: 'endo-g', title: '([^']+)'/, 'the grade tip'),
    redTip: grab(ins, /class: 'endo-chip endo-red', title: '([^']+)'/, 'the stigmata tip'),
    noBand: grab(ins, /bandBtn\.title = noVx \? '([^']+)'/, 'the band button without varices'),
    viewAria: grab(ins, /h\('canvas', \{ role: 'img', 'aria-label': '([^']+)' \}\);\n  box\.append\(cv\);\n  const view = 'eso'/, 'the picture label'),
    switchAria: grab(read('src/ui/dock.js'), /class: 'pressure-switch', role: 'group', 'aria-label': '(Endoscopy view)'/, 'the view switch label'),
    eusIdle: grab(eus, /const IDLE = '([^']+)'/, 'the EUS-PPG idle line'),
    eusBusy: grab(eus, /toast\('([^']+)'\)/, 'the EUS-PPG busy line'),
    eusAria: grab(eus, /'aria-label': '(Measure EUS-PPG on the anatomy)'/, 'the EUS-PPG button label'),
  };
  // the five tiles' names (and the small words after two of them), the stigmata's words, the Band button's icon-less label comes from procLabel('band')
  const tiles = /item\('endo-chip', h\('dt', \{\}, '([^']+)', h\('span', \{ class: 'endo-dt-x' \}, '([^']+)'\)\), bands\),\s*h\('div', \{ class: 'endo-g'[^\n]*h\('dt', \{\}, '([^']+)'\), grade\),\s*item\('endo-tile', h\('dt', \{\}, '([^']+)'\), diam\),\s*item\('endo-tile', h\('dt', \{\}, '([^']+)', h\('span', \{ class: 'endo-dt-x' \}, '([^']+)'\)\), wall\),\s*h\('div', \{ class: 'endo-chip endo-red'[^\n]*h\('dt', \{\}, '([^']+)'\), red\)/.exec(ins);
  if (!tiles) throw new Error('no endoscopy tiles');
  W.tiles = { bands: tiles[1], bandsX: tiles[2], grade: tiles[3], diameter: tiles[4], wall: tiles[5], wallX: tiles[6], stigmata: tiles[7] };
  W.red = { word: grab(ins, /set\(redWord, redV === 'None' \? redV : '([^']+)'\)/, 'the red wale word'), more: grab(ins, /set\(redMore, redV === 'None' \? '' : '([^']+)'\)/, 'the cherry spots words'), none: grab(ins, /const redV = !vx\.present \? '([^']+)'/, 'the none word') };
  W.measure = grab(eus, /class: 'hvpg-procs-k' \}, '([^']+)'\)/, 'the Measure word');
  W.eusName = grab(eus, /h\('span', \{\}, '(EUS-PPG)'\)/, 'the EUS-PPG button word');
  W.eusKeys = [...eus.matchAll(/\['(pv|hv|ppg)', '([^']+)'\]/g)].map((m) => [m[1], m[2]]);
  if (W.eusKeys.length !== 3) throw new Error('no EUS-PPG readings');
  W.eusSite = grab(eus, /const TECHNIQUE = `\$\{IDLE\} ([^$]+?) \$\{EUS_SITE_NOTE\}/, 'the EUS-PPG technique line');
  const done = /`\$\{hvpgWord\(rd\.ppg, true\)\}([^$]*)\$\{word\(rd\.pv\)\}([^$]*)\$\{word\(rd\.hv\)\}([^$]*)\$\{word\(rd\.ppg\)\}([^`]*)`/.exec(eus);
  if (!done) throw new Error('no EUS-PPG result line');
  W.eusDone = done.slice(1, 5);
  const last = /`Last EUS-PPG \$\{word\(rd\.ppg\)\}([^$]*)\$\{word\(rd\.pv\)\}([^$]*)\$\{word\(rd\.hv\)\}([^`]*)`/.exec(eus);
  if (!last) throw new Error('no EUS-PPG last line');
  W.eusLast = last.slice(1, 4);
  const dock = read('src/ui/dock.js');
  const sw = /\[\['scope', '([^']+)'\], \['wall', '([^']+)'\]\]/.exec(dock);
  if (!sw) throw new Error('no endoscopy view switch');
  W.views = [['scope', sw[1]], ['wall', sw[2]]];
  // the three pressures of a lesson slide (the readings option): the tiles that join the list after the wall
  W.pressures = [...ins.matchAll(/class: 'endo-tile endo-pr', title: '([^']+)' \}, h\('dt', \{\}, '([^']+)'\)/g)].map((m) => ({ name: m[2], title: m[1] }));
  if (W.pressures.length !== 3) throw new Error('no three pressure tiles');
  // Wall mechanics (instruments.js createVarixWall): its caption, the tiles' names (long and short), units and the stress's sentences
  {
    const a = ins.indexOf('export function createVarixWall'), b = ins.indexOf('// ── Ascites (L2c)');
    if (a < 0 || b < a) throw new Error('instruments.js: createVarixWall moved');
    const w = ins.slice(a, b);
    const g = (re, what) => { const m = re.exec(w); if (!m) throw new Error(`createVarixWall: no ${what}`); return m.slice(1); };
    const [aria] = g(/role: 'img', 'aria-label': '([^']+)'/, 'the picture label');
    const [cap, formula] = g(/h\('span', \{ class: 'wall-cap' \}, '([^']+)'\), '([^']+)'\)\);/, 'the caption');
    const [lawName] = g(/item\('endo-g wall-law', h\('dt', \{\}, '([^']+)'\)/, 'the law tile');
    const [stressLong, stressShort] = g(/item\('endo-stress', name\('([^']+)', '([^']+)'\)/, 'the stress tile');
    const [dpLong, dpShort] = g(/item\('endo-tile', name\('([^']+)', '([^']+)'\), ptm\)/, 'the ΔP tile');
    const [radius] = g(/item\('endo-tile', h\('dt', \{\}, '([^']+)'\), rad\)/, 'the radius tile');
    const [wallName] = g(/item\('endo-tile', h\('dt', \{\}, '([^']+)'\), wal\)/, 'the wall tile');
    const [idxLong, idxShort] = g(/item\('endo-tile', name\('([^']+)', '([^']+)'\), idx\)/, 'the index tile');
    const [uP, uR, uW] = g(/const ptm = num\('([^']*)'\), rad = num\('([^']*)'\), wal = num\('([^']*)'\)/, 'the units');
    const [ofWord] = g(/h\('span', \{ class: 'wall-of' \}, '([^']+)'\)/, 'the share word');
    const [above] = g(/share > 1 \? '([^']+)'/, 'the above-threshold sentence');
    const note = g(/h\('div', \{ class: 'ctl-sub' \}, '([^']+)' \+ WALL_MEANING\)/, 'the note')[0];
    const tear = /const tearTxt = intCache\(\(n\) => `\$\{n\}([^`]+)`\)/.exec(ins);
    if (!tear) throw new Error('instruments.js: no tearTxt');
    const names = /const WALL_NAMES = \[([^\]]+)\]/.exec(ins);
    if (!names) throw new Error('createVarixWall: no WALL_NAMES');
    W.wall = { aria, cap, formula, lawName, stress: [stressLong, stressShort], dp: [dpLong, dpShort], radius, wall: wallName, index: [idxLong, idxShort], units: [uP, uR, uW], of: ofWord, above, tear: tear[1], note, names: names[1].split(',').map((x) => x.trim().replace(/'/g, '')) };
  }
  put('endo-words.copied.js', HEAD('instruments.js createEndoscopy, eus-ppg.js, dock.js') + `export const ENDO_WORDS = ${JSON.stringify(W, null, 2)};\n`);
}

// ── Wall mechanics' layout ──
{
  const src = read('src/ui/wall-geometry.js');
  if (!/import \{ clamp \} from '\.\/num\.js';/.test(src)) throw new Error('wall-geometry.js: its import moved');
  put('wall-geometry.copied.js', HEAD('wall-geometry.js') + src.replace("from './num.js'", "from './num.copied.js'"));
}
// ── Wall mechanics' tile rules, scoped to the 3D pane ──
{
  const css = read('styles/app-09-tests.css');
  const a = css.indexOf('/* Wall mechanics in the Tests card'), b = css.indexOf('/* Doppler report:');
  if (a < 0 || b < a) throw new Error('app-09-tests.css: the Wall mechanics block moved');
  const PFX = '.instrument-workspace .dock-pane[data-pane="endoscopy"] > .wall-view';
  const block = css.slice(a, b).split(PFX).join('.en-wall');
  if (block.includes('.instrument-workspace')) throw new Error('app-09-tests.css: a Wall mechanics rule has another prefix');
  const url = new URL('../endo/wall.copied.css', dir);
  const text = `/* GENERATED by scripts/copy-b11-endo.mjs from the 2D app at ${commit.slice(0, 8)} (styles/app-09-tests.css, Wall mechanics block; the dock's selector prefix is .en-wall here). Do not edit; run the script again. */\n${block}`;
  if (!(existsSync(url) && readFileSync(url, 'utf8') === text)) { changed.push('endo/wall.copied.css'); if (!check) writeFileSync(url, text); }
}

// ── the colour tokens ──
{
  const css = read('styles/tokens.css');
  const want = ['red-wale', 'scope-bg', 'scope-balloon-hi', 'scope-balloon-lo', 'scope-blood-pool', 'scope-blood-pool-edge', 'scope-blood-jet', 'scope-blood-fresh', 'scope-blood-pool-top', 'scope-blood-haze', 'scope-rim',
    'endo-mucosa', 'endo-mucosa-deep', 'endo-zline', 'endo-vessels', 'endo-varix-small', 'endo-varix', 'endo-crest', 'endo-band-halo', 'endo-band', 'endo-light-near', 'endo-light-far', 'endo-glint', 'endo-lumen'];
  const out = {};
  for (const n of want) {
    const m = new RegExp(`--${n}:\\s*([^;]+);`).exec(css);
    if (!m) throw new Error(`tokens.css has no --${n}`);
    out[n] = m[1].trim();
  }
  put('scope-tokens.copied.js', HEAD('styles/tokens.css') + `export const SCOPE_TOKENS = ${JSON.stringify(out, null, 2)};\n`);
}

if (check) { if (changed.length) { console.error(`out of date: ${changed.join(', ')}`); process.exit(1); } console.log('src/ui/tests/copied endo files are current'); }
else console.log(changed.length ? `wrote ${changed.join(', ')}` : 'endo files are current');
