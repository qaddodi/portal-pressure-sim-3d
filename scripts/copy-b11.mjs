#!/usr/bin/env node
// Copies what the Tests and instruments need from the 2D app, so no number, word or curve is retyped (parity plan section 2: words and numbers come from the 2D source).
//   src/ui/tests/copied/*.copied.js   the 2D app's pure instrument modules (the HVPG clock, the trace tape and lanes, the Doppler's window and marks, banding, the scope's columns
//                                     and sizes, the EUS lens rule, the readouts' tile table…), byte for byte except the import specifiers, which point at this repo's copies.
//   src/ui/tests/copied/dock-tiles.copied.js  the readout tiles (TILES, GROUPS) cut out of dock.js: their scales, cut-offs, status words and why ids.
//   src/ui/tests/copied/dock-words.copied.js  the Tests tabs' order and names (dock.js SHORT, TINY, ORDER).
// Usage: node scripts/copy-b11.mjs --from <2D checkout> [--check]    (--check writes nothing and fails when a file would change)
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';

const args = process.argv.slice(2);
const flag = (n) => { const i = args.indexOf(n); return i >= 0 ? args[i + 1] : null; };
const from = flag('--from') ?? process.env.PPS_2D_REPO;
const check = args.includes('--check');
if (!from || !existsSync(`${from}/src/ui/dock.js`)) { console.error('usage: copy-b11.mjs --from <2D checkout>'); process.exit(2); }
let commit = 'unknown';
try { commit = execFileSync('git', ['-C', from, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim(); } catch { /* not a checkout */ }

/** The 2D files that are copied whole (src/ui/<name>.js → src/ui/tests/copied/<name>.copied.js). Each must be free of the DOM and of other 2D files outside this list. */
export const FILES = [
  'hvpg-clock', 'motion', 'glide-clock', 'ease', 'num',
  'doppler-synth', 'dopplerWindow', 'doppler-marks',
  'band-settle', 'band-ease', 'band-ring', 'balloon-eso', 'rx-bands',
  'scope-lens-rule', 'endo-size', 'endo-columns', 'endo-motion',
  'trace-lanes', 'trace-tape', 'trace-labels', 'trace-room', 'trace-callouts-math',
  'pressure-along', 'hvpg-balloon', 'ekg', 'drop-front',
  'instrument-aria', 'vital-read', 'table-marks', 'lymph-day', 'dock-vars',
].filter((n) => n !== 'trace-callouts-math');
const SLICES = {
  // endo-motion.js reads the bleed's strength from blood.js (1,000 lines of the 2D figure's blood): only its two lines are taken.
  'blood-slice': { file: 'blood', lines: [/^export const BLEED_STEADY\b/, /^export const bleedPulse\b/, /^export const poolFill\b/] },
};

const dir = new URL('../src/ui/tests/copied/', import.meta.url);
mkdirSync(dir, { recursive: true });
const changed = [];
const put = (name, text) => {
  const url = new URL(name, dir);
  if (existsSync(url) && readFileSync(url, 'utf8') === text) return;
  changed.push(name);
  if (!check) writeFileSync(url, text);
};
const HEAD = (what) => `// GENERATED by scripts/copy-b11.mjs from the 2D app at ${commit.slice(0, 8)} (${what}). Do not edit; run the script again.\n`;
const read = (p) => readFileSync(`${from}/${p}`, 'utf8');
const NOT = new Set(FILES);

/** Import specifiers: the 2D engine copy becomes this repo's, a neighbour in the list becomes its copied twin; anything else is an error (the file is not pure). */
function rewrite(name, src) {
  return src.replace(/(from\s*|import\s*)'([^']+)'/g, (m, kw, spec) => {
    if (!spec.startsWith('.')) return m;
    const eng = /^\.\.\/engine\/(core|portal)\/(.+)$/.exec(spec);
    if (eng) return `${kw}'../../../engine/hales/${eng[1]}/${eng[2]}'`;
    const loc = /^\.\/([\w-]+)\.js$/.exec(spec);
    if (loc && NOT.has(loc[1])) return `${kw}'./${loc[1]}.copied.js'`;
    const sl = loc && Object.entries(SLICES).find(([, v]) => v.file === loc[1]);
    if (sl) return `${kw}'./${sl[0]}.copied.js'`;
    throw new Error(`${name}.js imports '${spec}', which is not in the copy list (add it, or the file is not pure)`);
  });
}
for (const n of FILES) put(`${n}.copied.js`, HEAD(`${n}.js`) + rewrite(n, read(`src/ui/${n}.js`)));
for (const [n, s] of Object.entries(SLICES)) {
  const lines = read(`src/ui/${s.file}.js`).split('\n');
  const take = s.lines.map((re) => { const l = lines.find((x) => re.test(x)); if (!l) throw new Error(`${s.file}.js has no line for ${re}`); return l; });
  put(`${n}.copied.js`, HEAD(`${s.file}.js, ${take.length} lines`) + take.join('\n') + '\n');
}

// ── dock.js: the readout tiles and the tab names ──
const dock = read('src/ui/dock.js').split('\n');
const lineOf = (re, from0 = 0) => { const i = dock.findIndex((l, k) => k >= from0 && re.test(l)); if (i < 0) throw new Error(`dock.js has no line for ${re}`); return i; };
const block = (startRe) => { const a = lineOf(startRe); let b = a; while (!/^\];/.test(dock[b])) b++; return dock.slice(a, b + 1).join('\n'); };
const one = (re) => dock[lineOf(re)];
const tiles = [
  `import { TILE } from './table-marks.copied.js';`,
  `import { wallShare, WALL_MEANING } from '../../../engine/hales/portal/wall-read.js';`,
  `import { HVPG_CUTS, PPG_CUTS, PV_CUTS, hvpgSev, ppgSev, pvSev, HVPG_WORDS, PPG_WORDS, PV_WORDS } from '../../../engine/hales/portal/pressure-cuts.js';`,
  `// (dock.js reads the measured HVPG from its store; the 3D app sets \`hooks.lastHVPG\` from its own.)`,
  `export const hooks = { lastHVPG: () => null };`,
  `const store = { get: () => ({ lastHVPG: hooks.lastHVPG() }) };`,
  one(/^const vel = /),
  one(/^const ASCITES_WORDS = /),
  one(/^const fromTile = /),
  block(/^export const TILES = \[/),
  one(/^export const GROUPS = /),
].join('\n');
put('dock-tiles.copied.js', HEAD('dock.js TILES and GROUPS') + tiles + '\n');
const words = [
  one(/^  const SHORT = /).trim(), one(/^  const TINY = /).trim(), one(/^  const ORDER = /).trim(),
].map((l) => l.replace(/^const (\w+) =/, 'export const $1 =').replace(/\.filter\(\(id\) => byId\[id\]\)/, '')).join('\n');
put('dock-words.copied.js', HEAD('dock.js SHORT, TINY, ORDER') + words + '\n');

if (changed.length) { console.log(`${check ? 'would change' : 'wrote'}: ${changed.join(', ')}`); if (check) process.exit(1); } else console.log('src/ui/tests/copied is current');
