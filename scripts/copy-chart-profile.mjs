#!/usr/bin/env node
// Copies the pure part of the 2D pressure profile (src/ui/tool-profile.js: the stations, the zones, the name fit, the layout, the label placer, the
// pills, the line names, the brackets' fit, the red blocks; src/ui/curve-near.js: the monotone curve) into src/ui/charts/profile/*.generated.js, so the 3D
// chart lays out exactly as the 2D one does and no number is typed twice.
//
//   node scripts/copy-chart-profile.mjs --from <2D checkout> [--check]
//
// --check writes nothing and exits 1 when the files differ from what the 2D app would give. The DOM half of tool-profile.js (its SVG model, the glide, the
// card's measuring) is not copied: profile/frame.ts and ProfileCard.tsx draw the same pieces as a Frame.

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const here = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(here, '../src/ui/charts/profile');
const arg = (n) => { const i = process.argv.indexOf(n); return i > 0 ? process.argv[i + 1] : null; };
const from = arg('--from'), check = process.argv.includes('--check');
if (!from) { console.error('usage: node scripts/copy-chart-profile.mjs --from <2D checkout> [--check]'); process.exit(2); }

const read = (p) => readFileSync(join(from, 'src/ui', p), 'utf8');
/** The text of `t` from the line starting with `a` up to (not including) the line starting with `b`. */
function between(t, a, b, what) {
  const i = t.indexOf(a), j = t.indexOf(b, i + 1);
  if (i < 0 || j < 0) throw new Error(`${what}: marker not found (${i < 0 ? a : b})`);
  return t.slice(i, j);
}
let sha = 'unknown';
try { sha = execFileSync('git', ['-C', from, 'rev-parse', '--short=10', 'HEAD'], { encoding: 'utf8' }).trim(); } catch { /* not a git checkout */ }
const banner = (f) => `// @generated by scripts/copy-chart-profile.mjs from the 2D app's src/ui/${f} at ${sha}. Do not edit; run the script again.\n// @ts-nocheck\n`;

// the curve (the pressure line is a monotone cubic through the stations)
const near = read('curve-near.js');
const curve = banner('curve-near.js') + between(near, 'const DX = [], SL = [], TN = [];', '// The curve as a polyline, with err', 'curve-near.js');

// the stations, from anatomy.js PROFILE_PATHS[0]
const anat = read('anatomy.js');
const block = between(anat, 'export const PROFILE_PATHS = [', '];', 'anatomy.js');
const grab = (re, what) => { const m = block.match(re); if (!m) throw new Error(`anatomy.js: ${what} not found`); return m[1]; };
const nodes = grab(/nodes: (\[[^\]]*\])/, 'nodes'), names = grab(/names: (\{[^}]*\})/, 'names'), liver = grab(/liver: (\[[^\]]*\])/, 'liver');

const tp = read('tool-profile.js');
const A = between(tp, 'const PATH = PROFILE_PATHS[0];', '// (2 Nov 2026: the chart and the strips are models drawn on the GPU', 'tool-profile.js (layout)');
const B = between(tp, '/** (Legacy: the chart writes each value', 'const FADE_MS = D_SURFACE;', 'tool-profile.js (placers)');
const head = `import { monotoneSegs } from './curve-near.generated.js';
import { NODES } from '../../../engine/hales/portal/topology.js';
import { hvpgRate, ppgRate } from '../../../engine/hales/portal/pressure-cuts.js';
// (anatomy.js PROFILE_PATHS[0], the stations the Patients chart draws)
const PROFILE_PATHS = [{ id: 'main', nodes: ${nodes}, names: ${names}, liver: ${liver} }];
// (table-marks.js RATE: a reading's rating first, 'ok' | 'mid' | 'hi')
const RATE = { hvpg: (v) => [hvpgRate(v)], eus: (v) => [hvpgRate(v)], ppg: (v) => [ppgRate(v)] };
const one = (v) => (Math.round(v * 10) / 10).toFixed(1);
`;
const tail = `
export { PATH, NI, LIVER_NAMES, SPOKEN, AT_FP, ZONE_LOOK, RATE_OF, zoneLines, zoneW };
`;
const layout = banner('tool-profile.js') + head + A + B + tail;

const files = [[join(OUT, 'curve-near.generated.js'), curve], [join(OUT, 'layout.generated.js'), layout]];
let bad = 0;
for (const [p, t] of files) {
  if (check) { if (!existsSync(p) || readFileSync(p, 'utf8') !== t) { console.error(`differs: ${p}`); bad = 1; } continue; }
  mkdirSync(dirname(p), { recursive: true });
  writeFileSync(p, t);
  console.log(`wrote ${p}`);
}
process.exit(bad);
