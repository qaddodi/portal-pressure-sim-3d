#!/usr/bin/env node
// Copies the pure files of the 2D app that the small, timeline and ladder charts run on, as they are (imports pointed at this app's own copies):
//   allpatients-model.js  -> src/ui/charts/small/allpatients-model.generated.js   (the all-patients chart's numbers and layout)
//   smoothPath (tool-course.js, the one function, cut out whole) -> src/ui/charts/small/smooth.generated.js
//   cause-fit.js          -> src/ui/charts/ladder/cause-fit.generated.js          (a cell's cause stepping down beside the site)
//
//   node scripts/copy-chart-small.mjs [--from <2D checkout>] [--check]
// --check writes nothing and exits 1 when a file differs from what the 2D app would give.

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const here = dirname(fileURLToPath(import.meta.url));
const arg = (k, d) => { const i = process.argv.indexOf(k); return i > 0 ? process.argv[i + 1] : d; };
const two = resolve(arg('--from', '/home/claude/portal-pressure-simulator'));
const check = process.argv.includes('--check');
let sha = 'unknown';
try { sha = execFileSync('git', ['-C', two, 'rev-parse', '--short=10', 'HEAD'], { encoding: 'utf8' }).trim(); } catch { /* not a git checkout */ }

const src = (rel) => readFileSync(resolve(two, 'src/ui', rel), 'utf8');
const head = (rel, what = '') => `// @generated by scripts/copy-chart-small.mjs from the 2D app's src/ui/${rel}${what} at ${sha}. Do not edit; run the script again.\n// @ts-nocheck\n`;

/** The source of one top-level function, cut out whole (from `export function name` to its closing brace). */
function functionOf(text, name) {
  const at = text.indexOf(`export function ${name}(`);
  if (at < 0) throw new Error(`${name} not found`);
  let i = text.indexOf('{', text.indexOf(')', at)), depth = 0;
  for (; i < text.length; i++) { if (text[i] === '{') depth++; else if (text[i] === '}' && --depth === 0) break; }
  // the doc comment above it, when there is one
  const before = text.slice(0, at), c = before.lastIndexOf('\n\n'), doc = before.slice(c + 2);
  return (/^(\/\/|\/\*\*| \*)/.test(doc) ? doc : '') + text.slice(at, i + 1) + '\n';
}

/** One top-level statement (a function or a const), cut out whole with the comment lines just above it. Brackets are counted outside `//` comments. */
function statementOf(text, name) {
  const lines = text.split('\n'), re = new RegExp(`^(export )?(async )?(function |const )${name}\\b`);
  const a = lines.findIndex((l) => re.test(l));
  if (a < 0) throw new Error(`${name} not found`);
  let depth = 0, b = a, seen = false;
  for (; b < lines.length; b++) {
    const code = lines[b].replace(/\/\/.*$/, '');
    for (const ch of code) { if ('([{'.includes(ch)) { depth++; seen = true; } else if (')]}'.includes(ch)) depth--; }
    if (seen && depth <= 0 && (/[;}]\s*$/.test(code) || /^\}/.test(code))) break;
    if (!seen && /;\s*$/.test(code)) break;
  }
  let s = a;
  while (s > 0 && /^\s*(\/\/|\/\*\*| \*)/.test(lines[s - 1])) s--;
  return lines.slice(s, b + 1).join('\n') + '\n';
}
// The profile chart's pure part (tool-profile.js): the stations, a fingerprint's profile, the red blocks, the names' fit, the brace and a case's pills. The 2D file loads the
// page (svg-gl, frame, anatomy), so these are cut out by name and given the few things they stand on here (the main path's nodes and names, the rating of a pill).
const PROFILE_PARTS = ['LIVER_NAMES', 'BRACE_NAME', 'FULL_NAMES', 'SHORT_NAMES', 'TIGHT_NAMES', 'AT_FP', 'SPANS', 'NO_SPANS', 'STENTED', 'spansStented', 'hasStent', 'zoneSpans', 'BLOCK_FALL', 'blocksOf', 'blockSpan',
  'profileOf', 'NAME_GAP', 'nameFit', 'braceD', 'NUM_PAD', 'whole', 'pillReadings', 'ZONES'];
const profilePure = () => {
  const t = src('tool-profile.js');
  return head('tool-profile.js', ' (pure parts)') + `import { NODES } from '../../../engine/hales/portal/topology.js';
import { hvpgRate, ppgRate } from '../../../engine/hales/portal/pressure-cuts.js';
// (anatomy.js PROFILE_PATHS[0], the main path; the rating of a reading is table-marks.js RATE, whose first member is the cut-offs' rating)
const PATH = { id: 'main', nodes: ['INT', 'CONF', 'RPV', 'SIN_R', 'CV_R', 'RHV', 'IVCS', 'RA'],
  names: { INT: 'Intestine', CONF: 'Portal vein', RPV: 'Portal venule', SIN_R: 'Sinusoid', CV_R: 'Central vein', RHV: 'Hepatic vein', IVCS: 'IVC', RA: 'RA' }, liver: ['RPV', 'CV_R'] };
export const STATIONS = PATH.nodes;
export const PATH_NAMES = PATH.names;
const NI = Object.fromEntries(NODES.map((n, i) => [n.id, i]));
const RATE = { hvpg: (v) => [hvpgRate(v)], ppg: (v) => [ppgRate(v)], eus: (v) => [hvpgRate(v)] };
` + PROFILE_PARTS.map((n) => statementOf(t, n).replace(/^const /, 'export const ').replace(/^function /, 'export function ')).join('\n');
};

const files = [
  ['ladder/profile-pure.generated.js', profilePure()],
  ['small/allpatients-model.generated.js', head('allpatients-model.js') + src('allpatients-model.js')
    .replace("from './num.js'", "from '../looks2d/num.js'")
    .replace("from './table-marks.js'", "from '../tiles.generated.ts'")],
  ['small/smooth.generated.js', head('tool-course.js', ' (smoothPath)') + functionOf(src('tool-course.js'), 'smoothPath')],
  ['ladder/cause-fit.generated.js', head('cause-fit.js') + src('cause-fit.js')],
];

let bad = 0;
for (const [rel, text] of files) {
  const out = resolve(here, '../src/ui/charts', rel);
  if (check) { if (!existsSync(out) || readFileSync(out, 'utf8') !== text) { console.error(`differs: ${rel}`); bad++; } continue; }
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, text);
  console.log(`wrote ${rel}`);
}
process.exit(bad ? 1 : 0);
