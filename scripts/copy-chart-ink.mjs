#!/usr/bin/env node
// Copies the ink of Inter's glyphs (the GPU atlas's own record of where each glyph's pixels are) from the 2D app's src/ui/glyphs-inter.js into src/ui/charts/ink.generated.ts, so a
// chart's layout can ask where a word's ink really is (glyph-measure.js inkBox in 2D: the Wall mechanics picture places its names by their ink, not their line box). Printable ASCII
// and the Greek letters the charts name things with, at the weights the names use. A glyph's record is [advance (em), pen x, pen y (atlas px at BASE), ink: bands 2 atlas px tall, B64 first and last column + 1].
//
//   node scripts/copy-chart-ink.mjs --from <2D checkout> [--check]
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { execFileSync } from 'node:child_process';

const here = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(here, '../src/ui/charts/ink.generated.ts');
const WEIGHTS = [400, 500, 600, 700];
const GREEK = 'σΔ';

export async function buildInk(two) {
  const { GLYPHS, KERN, BASE } = await import(pathToFileURL(join(two, 'src/ui/glyphs-inter.js')).href);
  const chars = [...Array.from({ length: 95 }, (_, i) => String.fromCharCode(32 + i)), ...GREEK];
  const out = {};
  for (const w of WEIGHTS) {
    const glyphs = {}, kern = {};
    for (const ch of chars) if (GLYPHS[w][ch]) { const e = GLYPHS[w][ch]; glyphs[ch] = [e[0], e[5], e[6], e[7] || '']; }
    for (const [pair, k] of Object.entries(KERN[w])) if ([...pair].length === 2 && [...pair].every((c) => glyphs[c])) kern[pair] = k;
    out[w] = { glyphs, kern };
  }
  let sha = 'unknown';
  try { sha = execFileSync('git', ['-C', two, 'rev-parse', '--short=10', 'HEAD'], { encoding: 'utf8' }).trim(); } catch { /* not a git checkout */ }
  return `// @generated by scripts/copy-chart-ink.mjs from the 2D app's src/ui/glyphs-inter.js at ${sha}. Do not edit; run the script again.\n`
    + `/** the atlas's size a glyph's ink is recorded at (px) and the padding round each glyph (atlas px) */\nexport const INK_BASE = ${BASE}, INK_PAD = 9;\n`
    + `/** glyph: [advance (em), pen x, pen y (atlas px), ink bands (B64 pairs: first column, last + 1; each band 2 atlas px tall)] */\n`
    + `export const INK: Record<number, { glyphs: Record<string, readonly [number, number, number, string]>; kern: Record<string, number> }> = ${JSON.stringify(out)};\n`;
}

async function main() {
  const args = process.argv.slice(2), at = args.indexOf('--from');
  const two = at >= 0 ? args[at + 1] : process.env.PPS_2D_REPO;
  if (!two || !existsSync(join(two, 'src/ui/glyphs-inter.js'))) { console.error('usage: node scripts/copy-chart-ink.mjs --from <2D checkout> [--check]'); process.exit(2); }
  const text = await buildInk(resolve(two));
  if (args.includes('--check')) {
    const strip = (t) => t.replace(/ at [0-9a-f]{10}\./, '.');
    if (strip(existsSync(OUT) ? readFileSync(OUT, 'utf8') : '') !== strip(text)) { console.error('src/ui/charts/ink.generated.ts differs from the 2D app: run scripts/copy-chart-ink.mjs again'); process.exit(1); }
    console.log('chart ink matches the 2D app');
    return;
  }
  writeFileSync(OUT, text);
  console.log(`wrote ${OUT} (${text.length} bytes)`);
}
if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) await main();
