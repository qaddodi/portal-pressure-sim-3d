#!/usr/bin/env node
// Copies the word tables the 2D presenter typesets a slide's line with, so the 3D card sets the same words in the same pills
// (parity plan: "Words come from the 2D source, never retyped").
//
//   node scripts/copy-line-words.mjs --from <2D checkout> [--check]
//
// Reads <2D>/src/ui/presenter-words.js (TERMS: the first-mention bold words, KEYWORDS: a tile's words, AUTO_TERMS, BY_RATE, LENS_WORDS, LENS_TONE) and
// diseases.js (DISEASES), and writes src/ui/text/words2d.copied.ts. --check writes nothing and exits 1 when the copy differs from the 2D source.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { pathToFileURL, fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';
import { execFileSync } from 'node:child_process';
import vm from 'node:vm';
import { literalOf } from './copy-figure-targets.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(here, '../src/ui/text/words2d.copied.ts');
const arg = (n) => { const i = process.argv.indexOf(n); return i > 0 ? process.argv[i + 1] : null; };

export async function extract(root) {
  await import(pathToFileURL(`${root}/tests/dom-shim.js`).href);
  const words = await import(pathToFileURL(`${root}/src/ui/presenter-words.js`).href);
  const dz = await import(pathToFileURL(`${root}/src/ui/diseases.js`).href);
  const src = readFileSync(`${root}/src/ui/presenter-words.js`, 'utf8');
  const lit = (name) => vm.runInNewContext(`(${literalOf(src, name)})`, {});
  return { TERMS: lit('TERMS'), KEYWORDS: lit('KEYWORDS'), AUTO_TERMS: lit('AUTO_TERMS'), BY_RATE: [...literalOfSet(src, 'BY_RATE')], LENS_WORDS: words.LENS_WORDS, LENS_TONE: words.LENS_TONE, DISEASES: dz.DISEASES };
}
/** `const NAME = new Set([...])` → its items. */
function literalOfSet(text, name) {
  const m = new RegExp(`const\\s+${name}\\s*=\\s*new Set\\((\\[[^\\]]*\\])\\)`).exec(text);
  if (!m) throw new Error(`the 2D source has no Set "${name}" any more`);
  return vm.runInNewContext(m[1], {});
}
export function render(d, source) {
  const line = (name, type, v) => `export const ${name}: ${type} = ${JSON.stringify(v)};\n`;
  return `// @generated by scripts/copy-line-words.mjs from ${source}. Do not edit: run the script again.
// The words the 2D presenter typesets a line with (presenter-words.js TERMS, KEYWORDS, AUTO_TERMS, BY_RATE, LENS_WORDS, LENS_TONE; diseases.js DISEASES).
${line('TERMS_2D', 'readonly string[]', d.TERMS)}${line('KEYWORDS_2D', 'Readonly<Record<string, string>>', d.KEYWORDS)}${line('AUTO_TERMS_2D', 'readonly string[]', d.AUTO_TERMS)}${line('BY_RATE_2D', 'readonly string[]', d.BY_RATE)}${line('LENS_WORDS_2D', 'Readonly<Record<string, string>>', d.LENS_WORDS)}${line('LENS_TONE_2D', 'Readonly<Record<string, string>>', d.LENS_TONE)}${line('DISEASES_2D', 'readonly string[]', d.DISEASES)}`;
}
async function main() {
  const from = arg('--from') ?? process.env.PPS_2D_REPO;
  if (!from || !existsSync(`${from}/src/ui/presenter-words.js`)) { console.error('usage: node scripts/copy-line-words.mjs --from <2D checkout> [--check]'); process.exit(2); }
  const root = resolve(from);
  let commit = 'unknown';
  try { commit = execFileSync('git', ['-C', root, 'rev-parse', '--short=10', 'HEAD'], { encoding: 'utf8' }).trim(); } catch { /* not a git checkout */ }
  const text = render(await extract(root), `src/ui/presenter-words.js and diseases.js of qaddodi/portal-pressure-simulator at ${commit}`);
  const body = (t) => t.split('\n').filter((l) => !l.startsWith('// @generated')).join('\n');
  if (process.argv.includes('--check')) {
    if (!existsSync(OUT) || body(readFileSync(OUT, 'utf8')) !== body(text)) { console.error('src/ui/text/words2d.copied.ts differs from the 2D source: run scripts/copy-line-words.mjs again'); process.exit(1); }
    console.log('words2d.copied.ts matches the 2D app');
    return;
  }
  writeFileSync(OUT, text);
  console.log(`wrote ${OUT} (2D at ${commit})`);
}
if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) await main();
