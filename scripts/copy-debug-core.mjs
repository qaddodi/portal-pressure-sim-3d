#!/usr/bin/env node
// Copies the pure part of the 2D app's debug tools, so both apps write ONE report format and read each other's pastes
// (parity plan, batch B14; docs/debug.md section "One report format"):
//   src/ui/debug/core/finding.copied.js   one Finding and the adapters from every tool's shape       (2D src/ui/report/finding.js)
//   src/ui/debug/core/run.copied.js       the Run report, its text and JSON block, parse and compare   (report/run.js)
//   src/ui/debug/core/emit.copied.js      each runner's results as a Run report                        (report/emit.js)
//   src/ui/debug/core/packet.copied.js    the bug packet, its text and JSON block                      (packet/packet.js)
//   src/ui/debug/core/diff.copied.js      compare two screens and two lists of findings                (packet/diff.js)
//   src/ui/debug/core/press.copied.js     the chord and the long press on the PREVIEW pill            (packet/press.js)
//   src/ui/debug/core/short.copied.js     the short report Send feedback carries                       (packet/short.js)
//   src/ui/debug/core/history.copied.js   the motion recorder's history, packed                        (watch/history.js)
//   src/ui/debug/core/rules.copied.js     the self-check rules registry                                (selfcheck/rules.js)
//   src/ui/debug/core/registry.copied.js  the screen report's reader registry                          (screen/registry.js)
//   src/ui/debug/core/settle.copied.js    "is the page still busy?" and the wait for quiet             (screen/settle.js)
//   src/ui/debug/core/text.copied.js      the text form of a screen report                             (screen/text.js)
// Each is the 2D file with its import paths made flat; nothing else changes. The 3D tools (readers, rules, recorder) are written here against these.
// Usage: node scripts/copy-debug-core.mjs --from <2D checkout> [--check]    (--check writes nothing and fails when a file would change)
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { dirname } from 'node:path';
import { createHash } from 'node:crypto';

const args = process.argv.slice(2);
const flag = (n) => { const i = args.indexOf(n); return i >= 0 ? args[i + 1] : null; };
const from = flag('--from') ?? process.env.PPS_2D_REPO;
const check = args.includes('--check');
if (!from || !existsSync(`${from}/src/ui/report/finding.js`)) { console.error('usage: copy-debug-core.mjs --from <2D checkout> [--check]'); process.exit(2); }

export const FILES = [
  ['report/finding.js', 'finding'], ['report/run.js', 'run'], ['report/emit.js', 'emit'], ['packet/packet.js', 'packet'], ['packet/diff.js', 'diff'], ['packet/press.js', 'press'],
  ['packet/short.js', 'short'], ['watch/history.js', 'history'], ['selfcheck/rules.js', 'rules'], ['screen/registry.js', 'registry'], ['screen/settle.js', 'settle'], ['screen/text.js', 'text'],
];
const flat = Object.fromEntries(FILES.map(([src, name]) => [src.split('/').pop(), name]));

let commit = 'unknown';
try { commit = execFileSync('git', ['-C', from, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim(); } catch { /* not a checkout */ }
const changed = [], sums = {};
for (const [src, name] of FILES) {
  let text = readFileSync(`${from}/src/ui/${src}`, 'utf8');
  // every import of a copied sibling is made flat; an import of anything else is an error (the file would not be pure)
  text = text.replace(/from '([^']+)'/g, (m, p) => {
    const base = p.split('/').pop();
    if (!flat[base]) throw new Error(`${src} imports ${p}, which is not one of the copied files: it is not pure`);
    return `from './${flat[base]}.copied.js'`;
  });
  const out = new URL(`../src/ui/debug/core/${name}.copied.js`, import.meta.url);
  const body = `// GENERATED by scripts/copy-debug-core.mjs from the 2D app at ${commit.slice(0, 8)} (src/ui/${src}). Do not edit; run the script again.\n${text}`;
  sums[`${name}.copied.js`] = createHash('sha256').update(body).digest('hex');
  if (existsSync(out) && readFileSync(out, 'utf8') === body) continue;
  changed.push(`src/ui/debug/core/${name}.copied.js`);
  if (!check) { mkdirSync(dirname(out.pathname), { recursive: true }); writeFileSync(out, body); }
}
// The manifest holds one sha256 per copied file: tests/debug-core.test.ts fails a hand edit of a copy (the copies are never edited; the 2D app is).
const manifest = new URL('../src/ui/debug/core/MANIFEST.json', import.meta.url);
const text = `${JSON.stringify({ repository: 'qaddodi/portal-pressure-simulator', commit, files: sums }, null, 2)}\n`;
if (!existsSync(manifest) || readFileSync(manifest, 'utf8') !== text) { changed.push('src/ui/debug/core/MANIFEST.json'); if (!check) writeFileSync(manifest, text); }
if (check && changed.length) { console.error(`out of date: ${changed.join(', ')}\nrun: node scripts/copy-debug-core.mjs --from <2D checkout>`); process.exit(1); }
console.log(changed.length ? `${check ? 'would change' : 'wrote'}: ${changed.join(', ')}` : 'debug core copies are current');
