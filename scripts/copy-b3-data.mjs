#!/usr/bin/env node
// Copies what the vessels, blood and lenses need from the 2D app, so nothing is retyped (parity plan section 5: words come from the 2D source):
//   src/scene/lenses/tokens.copied.ts    every lens ramp and colour, per look (theme-tokens.js and styles/tokens.css)
//   src/scene/lenses/words.copied.ts     the lens names and lines of the Layers menu (main.js LENSES)
//   src/scene/vessels/paths.copied.ts    the anatomy's node places and vessel courses (anatomy.js), sampled to points, with its drawn / hidden sets
//   src/scene/lenses/vel-normal.copied.js  velNormal.js, import paths rewritten to this repo's engine copy
// Usage: node scripts/copy-b3-data.mjs --from <2D checkout> [--check]    (--check writes nothing and fails when a file would change)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { pathToFileURL } from 'node:url';

const args = process.argv.slice(2);
const flag = (n) => { const i = args.indexOf(n); return i >= 0 ? args[i + 1] : null; };
const from = flag('--from') ?? process.env.PPS_2D_REPO;
const check = args.includes('--check');
if (!from || !existsSync(`${from}/src/ui/anatomy.js`)) { console.error('usage: copy-b3-data.mjs --from <2D checkout>'); process.exit(2); }
const out = (p) => new URL(`../${p}`, import.meta.url);
let commit = 'unknown';
try { commit = execFileSync('git', ['-C', from, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim(); } catch { /* not a checkout */ }
const HEAD = (what) => `// GENERATED by scripts/copy-b3-data.mjs from the 2D app at ${commit.slice(0, 8)} (${what}). Do not edit; run the script again.\n`;
const changed = [];
function put(path, text) {
  const url = out(path);
  const same = existsSync(url) && readFileSync(url, 'utf8') === text;
  if (same) return;
  changed.push(path);
  if (!check) writeFileSync(url, text);
}
const read = (p) => readFileSync(`${from}/${p}`, 'utf8');

// ---------- tokens ----------
const { tokensOfLook, LOOK_IDS } = await import(pathToFileURL(`${from}/src/ui/theme-tokens.js`).href);
const css = read('styles/tokens.css');
const fixed = (name) => { const m = new RegExp(`--${name}:\\s*([^;]+);`).exec(css); if (!m) throw new Error(`token --${name} not in styles/tokens.css`); return m[1].trim(); };
const ramp = (text) => text.split(',').map((s) => { const [hex, pos] = s.trim().split(/\s+/); return [hex.toUpperCase(), Number(pos)]; });
const rgbHex = (s) => { const m = /rgb\((\d+),\s*(\d+),\s*(\d+)\)/.exec(s); return m ? '#' + [1, 2, 3].map((i) => Number(m[i]).toString(16).padStart(2, '0')).join('').toUpperCase() : s.toUpperCase(); };
const rampOf = (t, name) => ramp(t[`ramp-${name}`] ?? fixed(`ramp-${name}`));
const looks = {};
for (const id of LOOK_IDS) {
  const t = tokensOfLook(id);
  const hex = (name) => { const v = (t[name] ?? fixed(name)).trim(); if (!/^#[0-9a-fA-F]{6}$/.test(v)) throw new Error(`${id}: --${name} is not a plain hex (${v})`); return v.toUpperCase(); };
  looks[id] = {
    pressure: rampOf(t, 'pressure'), flow: rampOf(t, 'flow'), velocity: rampOf(t, 'velocity'), heat: rampOf(t, 'heat'), drop: rampOf(t, 'drop'), oxygen: rampOf(t, 'oxygen'),
    artery: hex('artery'), flowNormal: hex('flow-normal'), flowReversed: hex('flow-reversed'), trPv: hex('tr-pv'), trIvc: hex('tr-ivc'), trVar: hex('tr-var'),
  };
}
const shared = {
  deltaLow: fixed('delta-low').toUpperCase(), deltaMid: fixed('delta-mid').toUpperCase(), deltaHigh: fixed('delta-high').toUpperCase(),
  origin: ['smv', 'imv', 'spleen', 'artery', 'systemic'].map((o) => fixed(`origin-${o}`).toUpperCase()),
  firstPassRaw: fixed('fp-raw').toUpperCase(), firstPassClear: fixed('fp-clear').toUpperCase(),
  neutral: rgbHex(fixed('lens-neutral')),
  chevron: fixed('blood-chevron').toUpperCase(), chevronLight: fixed('blood-chevron-light').toUpperCase(), bloodInkLight: fixed('blood-ink-light').toUpperCase(),
  dye: fixed('blood-dye').toUpperCase(),
};
put('src/scene/lenses/tokens.copied.ts', `${HEAD('theme-tokens.js, styles/tokens.css')}export type Ramp = readonly (readonly [string, number])[];
export interface LensTokens {
  pressure: Ramp; flow: Ramp; velocity: Ramp; heat: Ramp; drop: Ramp; oxygen: Ramp;
  artery: string; flowNormal: string; flowReversed: string; trPv: string; trIvc: string; trVar: string;
}
export const LENS_TOKENS: Record<'light' | 'soft' | 'dark' | 'navy' | 'black', LensTokens> = ${JSON.stringify(looks, null, 1).replace(/\n\s*/g, ' ')};
/** Colours that do not change with the look (styles/tokens.css :root). origin = SMV, IMV, splenic vein, hepatic artery, systemic. */
export const LENS_SHARED = ${JSON.stringify(shared, null, 1).replace(/\n\s*/g, ' ')} as const;
`);

// ---------- lens words ----------
const main = read('src/ui/main.js');
const block = /const LENSES = \{([\s\S]*?)\n\};/.exec(main)?.[1];
if (!block) throw new Error('LENSES not found in main.js');
const lenses = [];
for (const line of block.split('\n')) {
  const m = /^\s*(\w+): \[('(?:[^'\\]|\\.)*'), ('(?:[^'\\]|\\.)*')/.exec(line);
  if (m) lenses.push([m[1], new Function(`return ${m[2]}`)(), new Function(`return ${m[3]}`)()]);
}
if (lenses.length !== 10) throw new Error(`expected 10 lenses in main.js, found ${lenses.length}`);
put('src/scene/lenses/words.copied.ts', `${HEAD('main.js LENSES')}/** [id, title, what it shows], in the Layers menu's order. */
export const LENS_WORDS: readonly (readonly [string, string, string])[] = ${JSON.stringify(lenses)};
`);

// ---------- vessel paths ----------
const anat = read('src/ui/anatomy.js');
const objectLiteral = (name) => {
  const start = anat.indexOf(`export const ${name} = {`);
  if (start < 0) throw new Error(`${name} not found`);
  let i = anat.indexOf('{', start), depth = 0, j = i;
  for (; j < anat.length; j++) { const c = anat[j]; if (c === '{') depth++; else if (c === '}' && --depth === 0) break; }
  return new Function(`return (${anat.slice(i, j + 1)})`)();
};
const setLiteral = (name) => {
  const m = new RegExp(`export const ${name} = new Set\\((\\[[\\s\\S]*?\\])\\);`).exec(anat);
  if (!m) throw new Error(`${name} not found`);
  return [...new Function(`return (${m[1]})`)()];
};
const NODE_POS = objectLiteral('NODE_POS');
const EDGE_PATH = objectLiteral('EDGE_PATH');
const num = (s) => s.match(/-?\d*\.?\d+(?:e-?\d+)?/gi).map(Number);
/** Samples an SVG path of M, L and C commands (all this app's courses are) to points, 8 steps a curve. */
function sample(d) {
  const toks = d.match(/[MLC]|-?\d*\.?\d+/g);
  const pts = [];
  let i = 0, cmd = '', cx = 0, cy = 0;
  while (i < toks.length) {
    if (/[MLC]/.test(toks[i])) cmd = toks[i++];
    if (cmd === 'M' || cmd === 'L') { cx = Number(toks[i++]); cy = Number(toks[i++]); pts.push([cx, cy]); }
    else if (cmd === 'C') {
      const [x1, y1, x2, y2, x3, y3] = toks.slice(i, i + 6).map(Number); i += 6;
      for (let s = 1; s <= 8; s++) {
        const t = s / 8, u = 1 - t;
        pts.push([u * u * u * cx + 3 * u * u * t * x1 + 3 * u * t * t * x2 + t * t * t * x3, u * u * u * cy + 3 * u * u * t * y1 + 3 * u * t * t * y2 + t * t * t * y3]);
      }
      cx = x3; cy = y3;
    } else throw new Error(`unsupported path command in ${d.slice(0, 30)}`);
  }
  return pts;
}
void num;
const round = (v) => Math.round(v * 10) / 10;
const paths = Object.fromEntries(Object.entries(EDGE_PATH).map(([id, d]) => [id, sample(d).map(([x, y]) => [round(x), round(y)])]));
const nodes = Object.fromEntries(Object.entries(NODE_POS).map(([id, [a]]) => [id, a]));
const sets = Object.fromEntries(['HIDDEN_EDGES', 'ANAT_HIDDEN', 'CONTEXT_EDGES', 'NEEDS_C3', 'IVC_EDGES', 'BACK_EDGES'].map((n) => [n, setLiteral(n)]));
const hiddenNodes = setLiteral('HIDDEN_NODES');
put('src/scene/vessels/paths.copied.ts', `${HEAD('anatomy.js NODE_POS, EDGE_PATH and the drawn/hidden sets')}// World units of the 2D anatomy (1400 x 1000, the patient's right on the viewer's left). Courses are sampled from the 2D app's SVG paths.
export const NODE_POS_2D: Record<string, readonly [number, number]> = ${JSON.stringify(nodes)};
export const EDGE_PATH_2D: Record<string, readonly (readonly [number, number])[]> = ${JSON.stringify(paths)};
export const HIDDEN_EDGES: ReadonlySet<string> = new Set(${JSON.stringify(sets.HIDDEN_EDGES)});
export const ANAT_HIDDEN: ReadonlySet<string> = new Set(${JSON.stringify(sets.ANAT_HIDDEN)});
export const CONTEXT_EDGES: ReadonlySet<string> = new Set(${JSON.stringify(sets.CONTEXT_EDGES)});
export const NEEDS_C3: ReadonlySet<string> = new Set(${JSON.stringify(sets.NEEDS_C3)});
export const IVC_EDGES: ReadonlySet<string> = new Set(${JSON.stringify(sets.IVC_EDGES)});
export const BACK_EDGES: ReadonlySet<string> = new Set(${JSON.stringify(sets.BACK_EDGES)});
export const HIDDEN_NODES: ReadonlySet<string> = new Set(${JSON.stringify(hiddenNodes)});
`);

// ---------- velNormal.js ----------
const vel = read('src/ui/velNormal.js')
  .replace("'../engine/portal/topology.js'", "'../../engine/hales/portal/topology.js'")
  .replace("'../engine/portal/flow-cuts.js'", "'../../engine/hales/portal/flow-cuts.js'")
  .replace("'../engine/portal/stent-geom.js'", "'../../engine/hales/portal/stent-geom.js'");
put('src/scene/lenses/vel-normal.copied.js', `${HEAD('velNormal.js')}${vel}`);

const sha = createHash('sha256').update(JSON.stringify(changed)).digest('hex').slice(0, 6);
if (check) { if (changed.length) { console.error(`out of date (${sha}): ${changed.join(', ')}`); process.exit(1); } console.log('copy-b3-data: up to date'); }
else console.log(changed.length ? `copy-b3-data: wrote ${changed.join(', ')}` : 'copy-b3-data: nothing changed');
