#!/usr/bin/env node
// Copies what the Tests card's "Along the circuit" chart (2D charts.js createProfile) needs from the 2D app, so no station, name, offset or word is retyped (parity plan section 2).
//   src/ui/tests/profile/copied/anatomy.copied.js   PROFILE_PATHS (the stations, the liver span, the HVPG and PPG brackets) and SHORT (the station names), cut out of anatomy.js
//   src/ui/tests/profile/copied/curve-near.copied.js  the monotone curve and its "how near is this box" tester (the label placement's eyes), byte for byte
//   src/ui/tests/profile/copied/consts.copied.js     the chart's constants and words, one line each as charts.js has them (label candidate offsets, dashes, strip columns,
//                                                    row heights, the note and the legend words), plus plot-look.js's rounded corner and util.js's axisTop
// Usage: node scripts/copy-b11-profile.mjs --from <2D checkout> [--check]    (--check writes nothing and fails when a file would change)
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';

const args = process.argv.slice(2);
const flag = (n) => { const i = args.indexOf(n); return i >= 0 ? args[i + 1] : null; };
const from = flag('--from') ?? process.env.PPS_2D_REPO;
const check = args.includes('--check');
if (!from || !existsSync(`${from}/src/ui/charts.js`)) { console.error('usage: copy-b11-profile.mjs --from <2D checkout>'); process.exit(2); }
let commit = 'unknown';
try { commit = execFileSync('git', ['-C', from, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim(); } catch { /* not a checkout */ }

const dir = new URL('../src/ui/tests/profile/copied/', import.meta.url);
mkdirSync(dir, { recursive: true });
const changed = [];
const put = (name, text) => {
  const url = new URL(name, dir);
  if (existsSync(url) && readFileSync(url, 'utf8') === text) return;
  changed.push(name);
  if (!check) writeFileSync(url, text);
};
const HEAD = (what) => `// GENERATED by scripts/copy-b11-profile.mjs from the 2D app at ${commit.slice(0, 8)} (${what}). Do not edit; run the script again.\n`;
const read = (p) => readFileSync(`${from}/${p}`, 'utf8');
const lines = (p) => read(p).split('\n');
const find = (ls, re, label, start = 0) => { const i = ls.findIndex((l, k) => k >= start && re.test(l)); if (i < 0) throw new Error(`${label}: no line for ${re}`); return i; };
/** From the line matching `re` to the first line after it that matches `endRe` (inclusive). */
const block = (ls, re, endRe, label) => { const a = find(ls, re, label); let b = a; while (!endRe.test(ls[b])) b++; return ls.slice(a, b + 1).join('\n'); };
const exported = (l) => l.replace(/^\s*const /, 'export const ');

// ── anatomy.js: the path and the names ──
{
  const ls = lines('src/ui/anatomy.js');
  const paths = block(ls, /^export const PROFILE_PATHS = \[/, /^\];/, 'PROFILE_PATHS');
  const short = block(ls, /^export const SHORT = \{/, /^\};/, 'SHORT');
  put('anatomy.copied.js', HEAD('anatomy.js: PROFILE_PATHS and SHORT') + `import { hvpgSev, ppgSev } from '../../../../engine/hales/portal/pressure-cuts.js';\n${paths}\n${short}\n`);
}
// ── curve-near.js: whole (pure) ──
put('curve-near.copied.js', HEAD('curve-near.js') + read('src/ui/curve-near.js'));
// ── charts.js constants, plot-look.js, util.js axisTop ──
{
  const ch = lines('src/ui/charts.js');
  const one = (re) => exported(ch[find(ch, re, 'charts.js')]);
  const out = [
    one(/^const ARTERIAL = /), one(/^const NO_DASH = /), one(/^const CAND_KX = /), one(/^const CAND_DY = /), one(/^const LIVER_AT = /), one(/^const C30 = /),
    one(/^\s*const STRIP = /), one(/^\s*const PLOT_MIN = /), one(/^\s*const BAND_PLOT_MIN = /), one(/^\s*const AT_SHOWN = /),
  ];
  // the words under the chart (createProfile): the legend's names and the note
  const noteLine = ch[find(ch, /const note = h\('div', \{ class: 'sub' \}, '/, 'note')];
  const note = /, '((?:[^'\\]|\\.)*)'\);/.exec(noteLine)[1];
  out.push(`export const NOTE = '${note}';`);
  const lg = block(ch, /const legend = h\('div', \{ class: 'legend-inline' \}/, /Your prediction'\)\);/, 'legend');
  const names = [...lg.matchAll(/\}\),? ?'([^']+)'\)/g)].map((m) => m[1]);
  out.push(`export const LEGEND = ${JSON.stringify(names)};   // now, healthy, snapshot A, your prediction (the last two show with a compared moment and a prediction)`);
  const pl = lines('src/ui/plot-look.js');
  out.push(exported(pl[find(pl, /^export const PLOT_R = /, 'PLOT_R')]).replace(/^export export/, 'export'));
  out.push(pl[find(pl, /^export const plotR = /, 'plotR')]);
  const ut = lines('src/ui/util.js');
  out.push(ut[find(ut, /^export const axisTop = /, 'axisTop')]);
  put('consts.copied.js', HEAD('charts.js, plot-look.js, util.js: the chart\'s constants') + out.join('\n') + '\n');
}

if (check && changed.length) { console.error(`out of date: ${changed.join(', ')} (run scripts/copy-b11-profile.mjs --from <2D checkout>)`); process.exit(1); }
console.log(changed.length ? `${check ? 'would change' : 'wrote'}: ${changed.join(', ')}` : 'src/ui/tests/profile/copied is current');
