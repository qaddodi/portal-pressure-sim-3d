// Lifts the 2D app's Details face (the inspector's panel for a selected vessel, compartment or organ) from a checkout of the 2D app, never retyped:
//   src/ui/action/details.generated.ts   the vessels' About words (ABOUT_EDGE), each organ's kicker, title, About words, stat names and Why? metric (ORGAN_ABOUT), and
//                                        the panel's own few words, each checked to still be in inspector.js
//   tests/fixtures/details-2d.json       what the panel's readings say for six patients (the organs' stat lambdas run as 2D wrote them; the vessels' and compartments'
//                                        stats are the 2D formulas of edgePanel and nodePanel, over the 2D app's own readings), the oracle tests/action-details.test.ts holds the port to
// Usage: node scripts/gen-details.mjs --from <2D checkout>
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createCore } from '../src/engine/hales/host/worker-core.js';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const argv = process.argv.slice(2);
const from = resolve(argv[argv.indexOf('--from') + 1] || '../portal-pressure-simulator');
const at = (p) => pathToFileURL(resolve(from, p)).href;
await import(at('tests/dom-shim.js'));
const src = readFileSync(resolve(from, 'src/ui/inspector.js'), 'utf8');
const { readings } = await import(at('src/ui/inspector.js'));
const { store } = await import(at('src/ui/store.js'));
// (The frames are this repository's engine's, so the indices are its topology's: the 2D app's own file is read for words only.)
const { EDGES, NODES, dMinOf } = await import(pathToFileURL(resolve(root, 'src/engine/hales/portal/topology.js')).href);
const { dopplerVel } = await import(pathToFileURL(resolve(root, 'src/scene/lenses/vel-normal.copied.js')).href);   // (the 2D velNormal.js, copied; it reads the topology by index)
const { liveBalance } = await import(at('src/ui/balance-hold.js'));
const { clamp } = await import(at('src/ui/util.js'));

// ── words ──
const block = (name, open, close) => {
  const a = src.indexOf(`const ${name} = ${open}`);
  if (a < 0) throw new Error(`2D no longer has ${name}`);
  const b = src.indexOf(close, a);
  return src.slice(a + `const ${name} = `.length, b + close.length - (close === '\n};' || close === '\n  };' ? 1 : 0));
};
const aboutSrc = block('ABOUT_EDGE', '{', '\n};');
const organSrc = block('ORGAN_ABOUT', '{', '\n  };');
const EI = Object.fromEntries(EDGES.map((e, i) => [e.id, i])), NI = Object.fromEntries(NODES.map((n, i) => [n.id, i]));
const Pof = (f) => f.Pf || f.P, Qof = (f) => f.Qf || f.Q;
const cachedText = (c, key, make, v, a, b) => make(key, v, a, b);
const pltMake = (n) => `${(n * 1000).toLocaleString('en-US')}/µL`;
const { numText, pressText, lpmText, newCell } = readings;
let hidden = null;
const hiddenNow = () => hidden;
const mk = (code) => new Function('Pof', 'NI', 'pressText', 'numText', 'lpmText', 'cachedText', 'pltMake', 'hiddenNow', 'liveBalance', `return (${code});`)(Pof, NI, pressText, numText, lpmText, cachedText, pltMake, hiddenNow, liveBalance);
const ABOUT_EDGE = new Function(`return (${aboutSrc});`)();
const ORGAN = mk(organSrc);

const WORDS = { change: 'Change this vessel from its card on the figure.', aboutEdge: 'About this vessel', about: 'About', connections: 'Connected vessels', doppler: 'Doppler here', why: 'Why this value?',
  back: 'Back', compartment: 'Compartment', dirWarn: 'Stagnant', dirRev: 'Reversed flow', dirOk: 'Physiological direction' };
for (const [k, v] of Object.entries(WORDS)) if (!src.includes(`'${v}'`)) throw new Error(`2D no longer says '${v}' (${k})`);
// the edge panel's stat names and the compartment's, each checked in the source
const EDGE_STATS = ['Pressure drop', 'Flow', 'Velocity', 'Diameter', 'Resistance', 'Recruitment', 'Healthy flow'], NODE_STATS = ['Pressure', 'Healthy', 'External pressure (Δ)', 'Transmural'];
for (const s of [...EDGE_STATS, ...NODE_STATS]) if (!src.includes(`'${s}'`)) throw new Error(`2D no longer has the stat '${s}'`);
if (!src.includes('`In · ${fromN.label}`') || !src.includes('`Out · ${toN.label}`')) throw new Error('2D no longer names the In and Out stats so');

const organs = {};
for (const [id, o] of Object.entries(ORGAN)) organs[id] = { kicker: o[0], title: o[1], about: o[2], stats: o[3].map((s) => s[0]), why: o[4] };
const organIds = Object.keys(ORGAN);
const gen = `// GENERATED by scripts/gen-details.mjs from the 2D app (qaddodi/portal-pressure-simulator, src/ui/inspector.js). Do not edit.
// The Details face's words: what a vessel, an organ and a compartment say about themselves, as the 2D inspector says them.
export const WORDS = ${JSON.stringify(WORDS, null, 2)} as const;
export const EDGE_STATS = ${JSON.stringify(EDGE_STATS)} as const;
export const NODE_STATS = ${JSON.stringify(NODE_STATS)} as const;
export const ABOUT_EDGE: Record<string, string> = ${JSON.stringify(ABOUT_EDGE, null, 2)};
export const ORGAN_ABOUT: Record<string, { kicker: string; title: string; about: string; stats: readonly string[]; why: string }> = ${JSON.stringify(organs, null, 2)};
`;
writeFileSync(resolve(root, 'src/ui/action/details.generated.ts'), gen);

// ── the readings, for six patients ──
const PRESETS = ['healthy', 'cirr-decomp', 'pvt-acute', 'cirr-decomp-tips', 'budd-chiari', 'gastric-varix'];
const EDGE_IDS = ['PV_TRUNK', 'SMV_CONF', 'SV_CONF', 'RHV_IVC', 'IVCS_RA', 'A_HEP', 'A_HR', 'SIN_RR', 'C1a', 'C1b', 'C3', 'C5', 'C8', 'TIPS', 'DIPS', 'S_PC', 'REX', 'LGV_CONF', 'PVH_R', 'CAUD'];
const NODE_IDS = ['CONF', 'RA', 'VAR', 'AO', 'SIN_R', 'SPL'];
const edgeStats = (id, f, healthy) => {
  const e = EDGES[EI[id]], k = EI[id], iFrom = NI[e.from], iTo = NI[e.to], isColl = e.kind === 'collateral';
  const c = () => newCell();
  const R = Math.abs(Qof(f)[k]) > 1e-3 ? numText(c(), (Pof(f)[iFrom] - Pof(f)[iTo]) / (Qof(f)[k] * 0.06), 2, ' WU') : '∞';
  const q = Qof(f)[k], ref = healthy?.Q?.[k] ?? 1;
  const dir = Math.abs(q) < 0.05 ? 'Stagnant' : q < -Math.max(0.12, 0.02 * Math.abs(ref)) ? 'Reversed flow' : 'Physiological direction';
  return { dir,
    In: pressText(c(), Pof(f)[iFrom]), Out: pressText(c(), Pof(f)[iTo]), 'Pressure drop': numText(c(), Pof(f)[iFrom] - Pof(f)[iTo], 1, ' mmHg'), Flow: readings.flowText(c(), Qof(f)[k] * 0.06),
    Velocity: numText(c(), Math.abs(dopplerVel(f, k)), 1, ' cm/s'), Diameter: numText(c(), f.D[k], 1, ' mm'), Resistance: R,
    last: isColl ? numText(c(), clamp(((f.slow.dEff?.[id] ?? f.slow.d[id]) - dMinOf(e)) / (e.dMax - dMinOf(e)), 0, 1) * 100, 0, '%') : (healthy?.Q?.[k] != null ? lpmText(c(), healthy.Q[k] * 0.06) : '—') };
};
const nodeStats = (id, f, healthy) => {
  const iN = NI[id], c = () => newCell(), v = healthy?.P?.[iN];
  return { Pressure: pressText(c(), Pof(f)[iN]), Healthy: v != null ? numText(c(), v, 1, ' mmHg') : '—', 'External pressure (Δ)': numText(c(), f.ext[iN], 1, ' mmHg'), Transmural: numText(c(), f.P[iN] - f.ext[iN], 1, ' mmHg') };
};
const out = { generatedFrom: '2D inspector.js: ORGAN_ABOUT lambdas as written; edgePanel and nodePanel formulas', presets: PRESETS, edges: EDGE_IDS, nodes: NODE_IDS, organs: organIds, patients: {} };
const frames = [];
const core = createCore((m) => frames.push(m));
await core.handle({ type: 'init' }); await core.handle({ type: 'run', running: false });
for (const id of PRESETS) {
  frames.length = 0;
  await core.handle({ type: 'preset', id, reqId: 1 });
  await core.handle({ type: 'healthyProfile', reqId: 2 });
  const h = frames.find((m) => m.type === 'healthy'), f0 = frames.filter((m) => m.type === 'frame').pop(), pl = frames.find((m) => m.type === 'presetLoaded');
  const rec0 = { params: pl.params, healthy: { P: Array.from(h.P), Q: Array.from(h.Q) },
    frame: { P: Array.from(f0.P), Pf: Array.from(f0.Pf), Q: Array.from(f0.Q), Qf: Array.from(f0.Qf), D: Array.from(f0.D), ext: Array.from(f0.ext), metrics: f0.metrics, slow: f0.slow, bands: f0.bands ?? 0 } };
  const back = JSON.parse(JSON.stringify(rec0));
  const f = { ...back.frame, P: Float32Array.from(back.frame.P), Pf: Float32Array.from(back.frame.Pf), Q: Float32Array.from(back.frame.Q), Qf: Float32Array.from(back.frame.Qf), D: Float32Array.from(back.frame.D), ext: Float32Array.from(back.frame.ext) };
  const healthy = { P: back.healthy.P, Q: back.healthy.Q };
  store.set({ params: back.params, healthy, frame: f });
  const rec = { params: back.params, healthy: back.healthy, frame: back.frame, organs: {}, edges: {}, nodes: {} };
  for (const [oid, o] of Object.entries(ORGAN)) rec.organs[oid] = o[3].map(([, fn]) => String(fn(f, newCell())));
  for (const eid of EDGE_IDS) rec.edges[eid] = edgeStats(eid, f, healthy);
  for (const nid of NODE_IDS) rec.nodes[nid] = nodeStats(nid, f, healthy);
  out.patients[id] = rec;
}
core.dispose();
writeFileSync(resolve(root, 'tests/fixtures/details-2d.json'), JSON.stringify(out));
console.log(`details.generated.ts written; details-2d.json: ${organIds.length} organs, ${EDGE_IDS.length} vessels, ${NODE_IDS.length} compartments, ${PRESETS.length} patients`);
