#!/usr/bin/env node
// Copies the 2D app's sinusoid view into the 3D app, so nothing is retyped (atlas look plan WP7: "the sinusoid, lifted from 2D's shader"):
//   src/scene/sinusoid/traffic.copied.js   createGeom(env) (the lumen's and Disse's width as the shader draws them) and createTraffic(env) (sinusoid-view.js "What moves": the albumin that
//                                          rides in the stream, crosses the open fenestrae and is turned back at a sealed wall, and the sprite list), wrapped over the closure state
//   src/scene/sinusoid/fen-place.copied.js  2D's placeFenDisse (the Fenestrae pill's and the Space of Disse's places on a wide screen), over layout.ts
//   src/scene/sinusoid/palette.copied.js   createPalette(env) (sinusoid-view.js palette(): every colour the shader takes, from the look's tokens and the model)
// Usage: node scripts/copy-sinusoid.mjs --from <2D checkout> [--check]    (--check writes nothing and fails when a file would change)
// The 3D keeps 2D's placement hash (src/scene/sinusoid/layout.ts, tests/scene-sinusoid-layout.test.ts holds values taken from the 2D file), so pores, cells and nuclei the traffic
// meets are the ones the shader draws.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { execFileSync } from 'node:child_process';

const args = process.argv.slice(2);
const flag = (n) => { const i = args.indexOf(n); return i >= 0 ? args[i + 1] : null; };
const from = flag('--from') ?? process.env.PPS_2D_REPO;
const check = args.includes('--check');
if (!from || !existsSync(`${from}/src/ui/sinusoid-gl.js`)) { console.error('usage: copy-sinusoid.mjs --from <2D checkout>'); process.exit(2); }
let commit = 'unknown';
try { commit = execFileSync('git', ['-C', from, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim(); } catch { /* not a checkout */ }
const dir = new URL('../src/scene/sinusoid/', import.meta.url);
const changed = [];
const put = (name, text) => {
  const url = new URL(name, dir);
  if (existsSync(url) && readFileSync(url, 'utf8') === text) return;
  changed.push(name);
  if (!check) writeFileSync(url, text);
};
const HEAD = (what, js = false) => `// GENERATED by scripts/copy-sinusoid.mjs from the 2D app at ${commit.slice(0, 8)} (${what}). Do not edit; run the script again.\n${js ? '// @ts-nocheck\n' : ''}`;
const read = (p) => readFileSync(`${from}/${p}`, 'utf8');
const fail = (m) => { console.error(`copy-sinusoid: ${m}`); process.exit(1); };

/** `text` with `a` replaced by `b`, which must be there exactly once (a change in the 2D file that moves it stops the copy, never goes unnoticed). */
function swap(text, a, b, what) {
  const i = text.indexOf(a);
  if (i < 0 || text.indexOf(a, i + 1) >= 0) fail(`${what}: expected exactly one of ${JSON.stringify(a.slice(0, 70))}`);
  return text.slice(0, i) + b + text.slice(i + a.length);
}

// ── the JavaScript of sinusoid-view.js, by line markers ──
const sv = read('src/ui/sinusoid-view.js').split('\n');
const at = (re, k0 = 0) => { const i = sv.findIndex((l, k) => k >= k0 && re.test(l)); if (i < 0) fail(`sinusoid-view.js has no line for ${re}`); return i; };
const lines = (a, b) => sv.slice(a, b + 1);

// the widths the shader draws and the traffic follows
const g0 = at(/^  const halfW = /), g1 = at(/^  const hepIn = /, g0);
put('traffic.copied.js', `${HEAD('sinusoid-view.js: the widths and the traffic', true)}// env: S (the state, eased: lum, pinch, col, por, v, filt ...), geo ({ xs, xk, pores: [up, down] }), VW ({ vis: [from, to] µm }), model ({ lyProt }), UM, rng, clamp, lerp, smooth, poreOpenness.
export function createGeom(env) {
  const { S, geo, UM } = env;
${lines(g0, g1).join('\n')}
  return { halfW, disseW, wallIn, hepIn };
}

export function createTraffic(env) {
  const { S, geo, VW, model, rng, clamp, lerp, smooth, poreOpenness, halfW, wallIn, hepIn } = env;
${lines(at(/^  \/\/ ── What moves ──/), at(/^  \/\/ ── Labels ──/) - 1).join('\n')}
  return { stepMovers, sprites, pts, get flowX() { return flowX; }, get lymX() { return lymX; }, setDt(v) { spriteDt = v; } };
}
`);

// the colours
const p0 = at(/^  const rgb3 = /), p1 = at(/^  const LY = /), pf0 = at(/^  function palette\(dark\) \{/), pf1 = at(/^  const LYMPH = /, pf0) - 1;
const blend0 = at(/^  function blendRgb/), copy0 = at(/^  function copyRgb/);
put('palette.copied.js', `${HEAD('sinusoid-view.js: palette()', true)}// env: S, model ({ hide, P2 }), cssv(name, fallback) -> a token's text or null, rgb(text | [r,g,b]) -> [r, g, b] in 0..1, pressureColor(P) -> [r, g, b].
// \`bump()\` says the tokens changed (a new look): the next \`palette(dark)\` reads them all again.
export function createPalette(env) {
  const { S, model, cssv, rgb, pressureColor } = env;
  const lerp = (a, b, t) => a + (b - a) * t;
  let cssEpoch = 0, cssMiss = false;
${lines(blend0, blend0).join('\n')}
${lines(copy0, copy0).join('\n')}
${lines(p0, at(/^  \};/, p0)).join('\n')}
${lines(p1, p1 + 1).join('\n')}
${lines(pf0, pf1).join('\n')}
  const LYMPH = [0, 0, 0], TCELL = [0, 0, 0], TUNDER = [0, 0, 0];
  return { palette, PAL, bump() { cssEpoch++; } };
}
`);

// where the Fenestrae pill and the Space of Disse's name sit on a wide screen (fen-place.js): the same pure functions, over this folder's layout.ts
put('fen-place.copied.js', `${HEAD('fen-place.js: placeFenDisse', true)}${swap(read('src/ui/fen-place.js'), "import { underNucleus, poreOpenness } from './sinusoid-gl.js';", "import { underNucleus, poreOpenness } from './layout.ts';", 'fen-place import')}`);

// the leaders' dot as the 2D captions draw it (label-captions.js leadLook defaults: the dot's radius and ring width, the halo's radius, the leader's width; app-01-chrome.css .leader-dot: the stage's
// paper in the text-2 ring, .leader-dot-halo: the paper alone) and the small class table of the names (SV_TARGET), read out of the 2D text
{
  const cap = read('src/ui/label-captions.js'), m = /const leadLook = (\{[^}]*\});/.exec(cap);
  if (!m) fail('label-captions.js: leadLook moved');
  const look = new Function(`return ${m[1]};`)();
  for (const k of ['lw', 'r', 'rw', 'haloR']) if (typeof look[k] !== 'number') fail(`label-captions.js: leadLook.${k} is not a number`);
  const css = read('styles/app-01-chrome.css');
  const dot = /\.leader-dot \{([^}]*)\}/.exec(css)?.[1], halo = /\.leader-dot-halo \{([^}]*)\}/.exec(css)?.[1];
  if (!dot || !halo || !/fill: var\(--stage-bg\)/.test(dot) || !/stroke: var\(--text-2\)/.test(dot) || !/stroke-width: 1\.3/.test(dot) || !/fill: var\(--stage-bg\)/.test(halo)) fail('app-01-chrome.css: .leader-dot / .leader-dot-halo changed');
  put('lead-look.copied.ts', `${HEAD('label-captions.js leadLook, app-01-chrome.css .leader-dot')}/** The leader's width, the dot's radius and ring width, and the halo's radius (CSS px, as the stage draws them at any zoom). The dot: the stage's paper, ringed in --text-2; the halo: the paper alone. */
export const LEAD_LOOK = { lineWidth: ${look.lw}, dotR: ${look.r}, ringWidth: ${look.rw}, haloR: ${look.haloR} } as const;
`);
}

if (changed.length) {
  if (check) { console.error(`copy-sinusoid: out of date: ${changed.join(', ')}. Run: node scripts/copy-sinusoid.mjs --from <2D checkout>`); process.exit(1); }
  console.log(`copy-sinusoid: wrote ${changed.join(', ')} (2D at ${commit.slice(0, 8)})`);
} else console.log('copy-sinusoid: up to date');
