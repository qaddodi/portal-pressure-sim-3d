#!/usr/bin/env node
// Lifts the 2D app's own stylesheets, byte for byte, so every piece of DOM the 3D app shares with the 2D one (cards, the presenter pill, the wallet,
// the shell's bars, menus and sheets, the glass) is styled by the 2D app's rules, not by a copy written from memory (owner, 19 Nov 2026: "the UI
// doesn't look like the 2D version yet"; the coordinator's rule: lift the 2D rules and markup unchanged, rewire only the hooks).
//
//   node scripts/copy-2d-css.mjs --from <2D checkout> [--check]
//
// Writes src/ui/css2d/<file>.css (unchanged), src/ui/css2d/index.css (the files' @imports in the 2D load order, as index.html links them),
// src/ui/css2d/SOURCE.json (the 2D commit and a hash per file) and src/ui/brand/icons/*.png (the sprites the CSS names with url("../brand/icons/…")).
// Never edit a copied file: change the 2D repo and run this again. tests/css2d-copy.test.ts fails on a hand edit.

import { readFileSync, writeFileSync, mkdirSync, copyFileSync, existsSync, readdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { resolve, dirname } from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(here, '../src/ui/css2d');
const ICONS = resolve(here, '../src/ui/brand/icons');
const sha = (buf) => createHash('sha256').update(buf).digest('hex').slice(0, 16);

/** The 2D stylesheets in the order index.html links them (fonts.css is the 3D app's own). */
export function loadOrder(indexHtml) {
  return [...indexHtml.matchAll(/<link rel="stylesheet" href="styles\/([\w.-]+\.css)"/g)].map((m) => m[1]);
}

function main() {
  const args = process.argv.slice(2);
  const at = args.indexOf('--from');
  if (at < 0 || !args[at + 1]) { console.error('usage: node scripts/copy-2d-css.mjs --from <2D checkout> [--check]'); process.exit(2); }
  const root = resolve(args[at + 1]);
  const order = loadOrder(readFileSync(resolve(root, 'index.html'), 'utf8'));
  if (order.length < 10) throw new Error(`read only ${order.length} stylesheets from the 2D index.html`);
  let commit = 'unknown';
  try { commit = execFileSync('git', ['-C', root, 'rev-parse', '--short=10', 'HEAD'], { encoding: 'utf8' }).trim(); } catch { /* not a checkout */ }
  const files = {};
  for (const f of order) files[f] = readFileSync(resolve(root, 'styles', f));
  const index = `/* @generated by scripts/copy-2d-css.mjs from qaddodi/portal-pressure-simulator at ${commit}. The 2D app's stylesheets, in its load order. Do not edit. */\n${order.map((f) => `@import "./${f}";`).join('\n')}\n`;
  const source = { source: `qaddodi/portal-pressure-simulator at ${commit}`, order, hashes: Object.fromEntries(order.map((f) => [f, sha(files[f])])), icons: {} };
  const icons = readdirSync(resolve(root, 'brand/icons')).filter((f) => f.endsWith('.png'));
  for (const f of icons) source.icons[f] = sha(readFileSync(resolve(root, 'brand/icons', f)));
  const text = `${JSON.stringify(source, null, 1)}\n`;
  if (args.includes('--check')) {
    const strip = (t) => t.replace(/"source": "[^"]*"/, '');
    const now = existsSync(resolve(OUT, 'SOURCE.json')) ? readFileSync(resolve(OUT, 'SOURCE.json'), 'utf8') : '';
    if (strip(now) !== strip(text)) { console.error('src/ui/css2d differs from the 2D app: run scripts/copy-2d-css.mjs again'); process.exit(1); }
    console.log('css2d matches the 2D app');
    return;
  }
  mkdirSync(OUT, { recursive: true }); mkdirSync(ICONS, { recursive: true });
  for (const f of order) writeFileSync(resolve(OUT, f), files[f]);
  writeFileSync(resolve(OUT, 'index.css'), index);
  writeFileSync(resolve(OUT, 'SOURCE.json'), text);
  for (const f of icons) copyFileSync(resolve(root, 'brand/icons', f), resolve(ICONS, f));
  console.log(`copied ${order.length} stylesheets and ${icons.length} icon sheets from the 2D app at ${commit}`);
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) main();
