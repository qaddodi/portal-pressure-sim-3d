#!/usr/bin/env node
// Copies the pure half of the 2D app's curve and course charts (src/ui/tool-curve.js, src/ui/tool-course.js: the sweep's steps, the series, the scales, the cut-offs,
// the word placing, the course's layout) into src/ui/charts/curve/*.generated.js, line for line. What is cut is only what draws on the page (the svg builder, the
// glide, the cache of the presenter's worker); the imports are pointed at this app's own copies of the files they name.
//
//   node scripts/copy-chart-curve.mjs --from <2D checkout> [--check]
//
// --check writes nothing and exits 1 when a file differs from what the 2D app would give.

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const here = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(here, '../src/ui/charts/curve');
const arg = (n) => { const i = process.argv.indexOf(n); return i > 0 ? process.argv[i + 1] : null; };
const from = arg('--from');
if (!from) { console.error('usage: node scripts/copy-chart-curve.mjs --from <2D checkout> [--check]'); process.exit(2); }

let sha = 'unknown';
try { sha = execFileSync('git', ['-C', from, 'rev-parse', '--short=10', 'HEAD'], { encoding: 'utf8' }).trim(); } catch { /* not a git checkout */ }
const read = (rel) => readFileSync(join(from, 'src/ui', rel), 'utf8');
const head = (rel) => `// @generated by scripts/copy-chart-curve.mjs from the 2D app's src/ui/${rel} at ${sha}. Do not edit; run the script again.\n// @ts-nocheck (the 2D app's own code, kept as it is: the drawing half is src/ui/charts/curve/frame.ts and course-frame.ts)\n`;

/** The text from the line holding `start` up to (not with) the line holding `end`. */
function slice(text, start, end) {
  const a = text.indexOf(start), b = text.indexOf(end);
  if (a < 0 || b < 0 || b < a) throw new Error(`markers not found: ${start} … ${end}`);
  return text.slice(text.lastIndexOf('\n', a) + 1, text.lastIndexOf('\n', b) + 1);
}

const curve = (() => {
  const t = read('tool-curve.js');
  const imports = [
    "import { TILE, SCALE, RATE, numName } from '../../deck/from2d/table-marks.js';",
    "import { HVPG_CUTS, HVPG_WORDS, PV_CUTS, PV_WORDS } from '../../../engine/hales/portal/pressure-cuts.js';",
    "import { READING_COLOUR } from '../plot/reading-colours.generated.js';",
    "import { minusFixed as fmt, clamp } from '../looks2d/num.js';   // (a true minus; −0.0 and toFixed's NaN kept as this chart has always printed them)",
    "import { airRatio } from '../../tests/copied/endo-size.copied.js';",
    "import { NODES } from '../../../engine/hales/portal/topology.js';",
    "import { safeParamPath, pathOf, getAt, patchOf, mergeOf } from '../../deck/from2d/import-safety.js';",
  ].join('\n');
  const body = slice(t, 'const CV_MIN = 12;', '// (2 Nov 2026: the chart is a model drawn on the GPU');
  return `${head('tool-curve.js')}${imports}\n${body}`;
})();

const course = (() => {
  const t = read('tool-course.js');
  const imports = [
    "import { TILE, RATE } from '../../deck/from2d/table-marks.js';",
    "import { lineMeta, cutsOf, fmtTick, placeWord } from './curve-pure.generated.js';",
  ].join('\n');
  const body = slice(t, 'const CO_MIN = 12;', '// (2 Nov 2026: the chart is a model drawn on the GPU');
  // Departure (reviewer, 24 Nov 2026): a course told `zones: false` draws no bands and no cut-off numbers on its axis (the ascites grades are not volumes: grade 1 is ultrasound-only, grade 3 is marked distension).
  let out = body;
  const dep = (a, b) => { if (out.split(a).length !== 2) throw new Error(`tool-course.js has changed shape: ${a.slice(0, 40)}`); out = out.replace(a, b); };
  dep('cuts = cutsOf(c.reading), total', 'cuts = c.zones === false ? [] : cutsOf(c.reading), total');
  dep('    reading,\n    from: pick(', '    reading, zones: t?.zones !== false,\n    from: pick(');
  // Departure (capture 52ef8e63, 25 Nov 2026): the "before" word (Tense ascites) found no clear spot among the four places just above the start point and sat on the first stroke of the line; more places, higher and then clear of the point's right, so it stands clear of the plateau.
  dep('[-1.0, -1.3, -1.6, -0.8].map((k) => ({ x: xd + 0.5 * f, y: yd + k * f, anchor: \'start\' }))', '[-1.0, -1.3, -1.6, -0.8, -2.0, -2.5, -3.0].flatMap((k) => [0.5, 1.6, 3].map((dx) => ({ x: xd + dx * f, y: yd + k * f, anchor: \'start\' })))');
  dep("  // (The strip at the left is the numbers and no more: the zones' names stand on the plot, placeLabels.)", `  if (c.zones === false) {
    ticks.length = 0;
    const raw = top / 4, mag = 10 ** Math.floor(Math.log10(raw)), st = [1, 2, 5, 10].map((q) => q * mag).find((q) => q >= raw) ?? raw;
    for (let v = 0; v < top - 1e-9; v += st) ticks.push({ v, rate: null, text: v ? \`\${fmtTick(v, m.d)} \${m.unit}\` : '0' });
  }
  // (The strip at the left is the numbers and no more: the zones' names stand on the plot, placeLabels.)`);
  return `${head('tool-course.js')}${imports}\n${out}`;
})();

const files = [[join(OUT, 'curve-pure.generated.js'), curve], [join(OUT, 'course-pure.generated.js'), course]];
const check = process.argv.includes('--check');
let bad = 0;
for (const [path, text] of files) {
  if (check) { if (!existsSync(path) || readFileSync(path, 'utf8') !== text) { console.error(`differs: ${path}`); bad++; } continue; }
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, text);
  console.log(`wrote ${path}`);
}
process.exit(bad ? 1 : 0);
