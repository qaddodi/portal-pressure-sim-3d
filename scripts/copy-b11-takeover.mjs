#!/usr/bin/env node
// Copies the monitor takeover from the 2D app, so its clock and its hand-over are not retyped (parity plan section 2).
//   src/ui/tests/copied/monitor-takeover.copied.js   monitor-takeover.js: HOLD_MS, createTakeover (idle > run > hold > idle: the monitor standing in a picture's place for one measurement)
//                                                    and createSwap (the fade-out, then fade-in hand-over between a picture and the monitor). Used by the EUS-PPG (endo/eus-run.ts) and the PPG by IR (ir/run.ts).
// Usage: node scripts/copy-b11-takeover.mjs --from <2D checkout> [--check]    (--check writes nothing and fails when a file would change)
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';

const args = process.argv.slice(2);
const flag = (n) => { const i = args.indexOf(n); return i >= 0 ? args[i + 1] : null; };
const from = flag('--from') ?? process.env.PPS_2D_REPO;
const check = args.includes('--check');
if (!from || !existsSync(`${from}/src/ui/monitor-takeover.js`)) { console.error('usage: copy-b11-takeover.mjs --from <2D checkout>'); process.exit(2); }
let commit = 'unknown';
try { commit = execFileSync('git', ['-C', from, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim(); } catch { /* not a checkout */ }
const dir = new URL('../src/ui/tests/copied/', import.meta.url);
mkdirSync(dir, { recursive: true });
const name = 'monitor-takeover.copied.js';
const src = readFileSync(`${from}/src/ui/monitor-takeover.js`, 'utf8');
if (!/from '\.\/ease\.js'/.test(src)) throw new Error('monitor-takeover.js no longer imports ./ease.js: the map is out of date');
const text = `// GENERATED by scripts/copy-b11-takeover.mjs from the 2D app at ${commit.slice(0, 8)} (monitor-takeover.js). Do not edit; run the script again.\n` + src.replace(/from '\.\/ease\.js'/, "from './ease.copied.js'");
const url = new URL(name, dir), same = existsSync(url) && readFileSync(url, 'utf8') === text;
if (check) { if (!same) { console.error(`out of date: ${name}`); process.exit(1); } console.log('monitor-takeover.copied.js is current'); }
else { if (!same) writeFileSync(url, text); console.log(same ? 'monitor-takeover.copied.js is current' : `wrote ${name}`); }
