#!/usr/bin/env node
// Copies, whole, the two small pure files of the 2D app that give a slide its graph without the slide naming an instrument (Mohammad, 15 Nov 2026, PC-6: a graph is the slide's instrument
// card, never part of the teaching card):
//   src/ui/lapse-graph.js      which two readings a time-lapse slide plots, and how the flow-time chart is told them (graphLines, lapseGraphOf)
//   src/ui/slide-instrument.js the instrument a slide gets when it names none: a time-lapse's flow-time chart, a procedure's event graph (instrumentOf)
// Only the imports are pointed at this app's own copies (the flow-time lines are charts/flowtime/model.ts, the event graph charts/evgraph/model.ts).
//
//   node scripts/copy-chart-lapse.mjs --from <2D checkout at the pin> [--check]
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const here = dirname(fileURLToPath(import.meta.url));
const arg = (n) => { const i = process.argv.indexOf(n); return i > 0 ? process.argv[i + 1] : null; };
const from = arg('--from');
if (!from) { console.error('usage: node scripts/copy-chart-lapse.mjs --from <2D checkout at the pin> [--check]'); process.exit(2); }
let sha = 'b3058ef392';
try { sha = execFileSync('git', ['-C', from, 'rev-parse', '--short=10', 'HEAD'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim(); } catch { /* not a git checkout */ }
const src = (f) => readFileSync(join(from, 'src/ui', f), 'utf8');
const head = (f) => `// @generated by scripts/copy-chart-lapse.mjs from the 2D app's src/ui/${f} at ${sha}. Do not edit; run the script again.\n// @ts-nocheck (the 2D app's own code, kept as it is)\n`;
/** One import line, replaced; the script fails when the 2D file no longer has it (so a moved pin is noticed, not silently wrong). */
const swap = (text, a, b) => { if (!text.includes(a)) throw new Error(`not found in the 2D file: ${a}`); return text.replace(a, b); };

const files = [
  ['charts/flowtime/lapse-graph.generated.js', head('lapse-graph.js') + swap(src('lapse-graph.js'), "from './flow-time.js'", "from './model.ts'")],
  ['talk/slide-instrument.generated.js', head('slide-instrument.js')
    + swap(swap(src('slide-instrument.js'), "from './lapse-graph.js'", "from '../charts/flowtime/lapse-graph.generated.js'"), "from './event-graph.js'", "from '../charts/evgraph/model.ts'")],
];

let bad = 0;
for (const [rel, text] of files) {
  const out = resolve(here, '../src/ui', rel);
  if (process.argv.includes('--check')) { if (!existsSync(out) || readFileSync(out, 'utf8') !== text) { console.error(`differs: ${rel}`); bad++; } continue; }
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, text);
  console.log(`wrote ${rel}`);
}
process.exit(bad ? 1 : 0);
