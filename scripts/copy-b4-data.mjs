#!/usr/bin/env node
// Copies what the organs and the disease states need from the 2D app, so nothing is retyped (parity plan section 5: values come from the 2D source):
//   src/scene/disease/copied/*.js        the 2D app's own pure modules, byte for byte but for their import lines
//                                        (num, clot-shape, cavernoma-strand, organ-ease, fluid-step, varix-look, varix-bead, liver-geo, liver-morph, dye-bolus)
//   src/scene/disease/copied/anatomy-b4.ts  the constants of anatomy.js the states read (organ ids and tones, spleen centre, strands, cavernoma channels, ...)
//   tests/fixtures/b4-2d.json            numbers the 2D functions give, for the tests that hold the ports to them
// Usage: node scripts/copy-b4-data.mjs --from <2D checkout> [--check]    (--check writes nothing and fails when a file would change)
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { pathToFileURL } from 'node:url';

const args = process.argv.slice(2);
const flag = (n) => { const i = args.indexOf(n); return i >= 0 ? args[i + 1] : null; };
const from = flag('--from') ?? process.env.PPS_2D_REPO;
const check = args.includes('--check');
if (!from || !existsSync(`${from}/src/ui/anatomy.js`)) { console.error('usage: copy-b4-data.mjs --from <2D checkout>'); process.exit(2); }
const out = (p) => new URL(`../${p}`, import.meta.url);
let commit = 'unknown';
try { commit = execFileSync('git', ['-C', from, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim(); } catch { /* not a checkout */ }
const HEAD = (what) => `// GENERATED by scripts/copy-b4-data.mjs from the 2D app at ${commit.slice(0, 8)} (${what}). Do not edit; run the script again.\n`;
const changed = [];
function put(path, text) {
  const url = out(path);
  mkdirSync(new URL('.', url), { recursive: true });
  const same = existsSync(url) && readFileSync(url, 'utf8') === text;
  if (same) return;
  changed.push(path);
  if (!check) writeFileSync(url, text);
}
const read = (p) => readFileSync(`${from}/${p}`, 'utf8');
const DIR = 'src/scene/disease/copied';

// ---------- the 2D app's pure modules, import lines rewritten ----------
const ENGINE = '../../../engine/hales/portal';
const REWRITE = {
  './anatomy.js': './anatomy-b4.ts',
  './motion.js': './num.js',
  './num.js': './num.js',
  './liver-geo.js': './liver-geo.js',
  '../engine/portal/pressure-cuts.js': `${ENGINE}/pressure-cuts.js`,
};
function copyModule(file, name = file) {
  let text = read(`src/ui/${file}`).replace(/^(import|export)([^'"\n]*?)from\s+'([^']+)';/gm, (m, kw, mid, spec) => {
    if (!(spec in REWRITE)) throw new Error(`${file}: an import this script does not map: ${spec}`);
    return `${kw}${mid}from '${REWRITE[spec]}';`;
  });
  put(`${DIR}/${name}`, `${HEAD(`src/ui/${file}`)}${text}`);
}
for (const f of ['sin-perfusion.js', 'stomach-lumen.js', 'num.js', 'clot-shape.js', 'cavernoma-strand.js', 'organ-ease.js', 'fluid-step.js', 'varix-look.js', 'varix-bead.js', 'liver-geo.js']) copyModule(f);
// liver-morph.js: its `smooth01` comes from motion.js in 2D, which is num.js's own (motion.js re-exports it)
copyModule('liver-morph.js');

// The dye bolus: the part of blood.js between its "Dye bolus" header and the end of createBolus (the rest of blood.js is the figure's streaks and the GPU's tables).
{
  const t = read('src/ui/blood.js');
  const a = t.indexOf('// ── Dye bolus');
  const f = t.indexOf('export function createBolus');
  const end = t.indexOf('\n}\n', f) + 3;
  if (a < 0 || f < 0 || end < f) throw new Error('blood.js: the dye bolus markers moved');
  const sp = t.indexOf('// Display speed, world units per second'), spEnd = t.indexOf('\n', t.indexOf('export const displaySpeed')) + 1;
  const sm = /^(const|function) smoothstep[^\n]*\n/m.exec(t);
  if (sp < 0 || !sm) throw new Error('blood.js: the display speed markers moved');
  put(`${DIR}/dye-bolus.js`, `${HEAD('src/ui/blood.js, the Dye bolus section and displaySpeed')}${sm[0]}${t.slice(sp, spEnd)}\n${t.slice(a, end)}`);
}

// The bleed's shapes (the pool and the thread): blood.js between "The bleed's strength" and the end of bleedShapes, with the stomach's lumen they read.
{
  const t = read('src/ui/blood.js');
  const a = t.indexOf("// The bleed's strength");
  const f = t.indexOf('export function bleedShapes(');
  const end = t.indexOf('\n}\n', f) + 3;
  if (a < 0 || f < 0 || end < f) throw new Error('blood.js: the bleed markers moved');
  put(`${DIR}/bleed-shapes.js`, `${HEAD('src/ui/blood.js, the bleed section')}import { lumenSurface, lumenAt } from './stomach-lumen.js';\n${t.slice(a, end)}`);
}

// ---------- the constants ----------
const A = await import(pathToFileURL(`${from}/src/ui/anatomy.js`).href);
const FS = await import(pathToFileURL(`${from}/src/ui/fluid-step.js`).href);
const OD = await import(pathToFileURL(`${from}/src/ui/organ-dim.js`).href);
const OE = await import(pathToFileURL(`${from}/src/ui/organ-ease.js`).href);
const LM = await import(pathToFileURL(`${from}/src/ui/liver-morph.js`).href);
const CS = await import(pathToFileURL(`${from}/src/ui/clot-shape.js`).href);
const CV = await import(pathToFileURL(`${from}/src/ui/cavernoma-strand.js`).href);
const VL = await import(pathToFileURL(`${from}/src/ui/varix-look.js`).href);
const VB = await import(pathToFileURL(`${from}/src/ui/varix-bead.js`).href);
const SM = await import(pathToFileURL(`${from}/src/ui/spleen-motion.js`).href);
const J = (v) => JSON.stringify(v);
const organs = A.ORGANS.filter((o) => !o.deco && !o.circle && !o.band || ['appendix', 'duodenum', 'colon'].includes(o.id)).map((o) => ({ id: o.id, tone: o.tone ?? null, noCover: !!o.noCover, band: !!o.band }));
const sitesText = J(A.SITES);
put(`${DIR}/anatomy-b4.ts`, `${HEAD('anatomy.js and the small constants of fluid-step, organ-dim, organ-ease, spleen-motion')}// Exports the names the copied modules import from anatomy.js (EDGE_PATH, LIVER_EDGES, HIDDEN_EDGES, ANAT_HIDDEN, STRANDS, CAV_GROW, APPENDIX_TIP, ABDOMEN_FLOOR) and what the states read.
export const EDGE_PATH: Record<string, string> = ${J(Object.fromEntries(Object.entries(A.EDGE_PATH).filter(([id]) => A.LIVER_EDGES.has(id) || id in A.STRANDS || id === 'C8')))};
export const LIVER_EDGES: ReadonlySet<string> = new Set(${J([...A.LIVER_EDGES])});
export const HIDDEN_EDGES: ReadonlySet<string> = new Set(${J([...A.HIDDEN_EDGES])});
export const ANAT_HIDDEN: ReadonlySet<string> = new Set(${J([...A.ANAT_HIDDEN])});
export const STRANDS: Record<string, number[][]> = ${J(A.STRANDS)};
export const CAV_GROW = ${A.CAV_GROW};
export const CAV_CHANNELS: Record<string, { v: number; amp: number; cyc: number; ph: number; a: number; z: number; k: number; r0: number; ramp: number }[]> = ${J(A.CAV_CHANNELS)};
export const APPENDIX_TIP = ${A.APPENDIX_TIP};
export const ABDOMEN_FLOOR = ${A.ABDOMEN_FLOOR};
export const SPLEEN_CENTER: readonly [number, number] = ${J(A.SPLEEN_CENTER)};
/** The liver's pivot (stage-diaphragm.js: its shrink is about this point), in 2D units. */
export const LIVER_PIVOT: readonly [number, number] = [560, 350];
export const SITES: Record<string, number[]> = ${sitesText};
/** The organs of the 2D figure, in its drawing order: id, tone, and whether it is the gut (no vessel is veiled behind it). */
export const ORGAN_TABLE: readonly { id: string; tone: string | null; noCover: boolean; band: boolean }[] = ${J(organs)};
export const ABDOMEN_CLIP = ${J(A.ABDOMEN_CLIP)};
/** The abdominal wall's outline by bulge step (half units, 0 to 34): anatomy.js abdomenOutline. */
export const ABDOMEN_OUTLINES: readonly string[] = ${J(Array.from({ length: 69 }, (_, i) => A.abdomenOutline(i / 2)))};
export const STRAND_FROM: Record<string, number> = ${J(A.STRAND_FROM)};
export const STRAND_SOFT: ReadonlySet<string> = new Set(${J([...A.STRAND_SOFT])});
export const SIN_EDGES: ReadonlySet<string> = new Set(${J([...A.SIN_EDGES])});
export const SEAM_D = ${J(A.SEAM_D)};
export const SPLEEN_PSE_BADGE: readonly number[] = ${J(A.SPLEEN_PSE_BADGE)};
/** The embolized spleen's infarct: the edge of the dead lower part (the stroke) and the area it closes below (anatomy.js). */
export const SPLEEN_PSE_EDGE = ${J(A.SPLEEN_PSE_EDGE)};
export const SPLEEN_PSE_AREA = ${J(A.SPLEEN_PSE_AREA)};
/** The navel's ring: where the navel's ring is drawn (organs[umbilicus].circle: x, y, r). */
export const UMBILICUS: readonly number[] = ${J(A.ORGANS.find((o) => o.id === 'umbilicus').circle)};
/** A lens other than Pressure takes the organs to this saturation and opacity (organ-dim.js LENS_GREY). */
export const LENS_GREY: { sat: number; dim: number } = ${J(OD.LENS_GREY)};
export const LUMA: readonly number[] = ${J(OD.LUMA)};
export const LIVER_TAU = ${OE.LIVER_TAU};
export const SPLEEN_RATE = ${SM.SPLEEN_RATE};
export const SPLEEN_WINDOW = ${SM.SPLEEN_WINDOW};
export const SPLEEN_STILL = ${SM.SPLEEN_STILL};
/** The pool's rise: FLUID_TOP and FLUID_POW (fluid-step.js), kept here as numbers so a test can name them. */
export const FLUID_CONSTANTS = ${J({ top: FS.FLUID_TOP, pow: FS.FLUID_POW, gap: FS.POOL_GAP, min: FS.POOL_MIN })};
`);

// ---------- fixtures: what the 2D functions answer, for the tests of the ports ----------
const grid = (n) => Array.from({ length: n + 1 }, (_, i) => i / n);
const fixture = {
  generatedFrom: { commit },
  liverShrink: grid(4).flatMap((c) => grid(4).map((g) => [c, g, LM.liverShrink(c, g)])),
  liverSurface: grid(10).map((c) => { const s = LM.liverSurface(c); return [c, s.gloss, s.nod]; }),
  liverField: [[400, 300], [500, 350], [560, 350], [700, 280], [820, 300], [610, 420]].flatMap(([x, y]) => [0, 0.5, 1].map((c) => { const p = LM.liverField(x, y, c); return [x, y, c, p[0], p[1]]; })),
  fluidLevel: [0, 100, 150, 300, 1000, 2500, 5000, 8500, 12000].map((v) => { const l = FS.fluidLevel(v); return [v, l.h, l.amp, l.floor, FS.poolFade(v)]; }),
  fluidTarget: [[null, 5], [5, 5.05], [5, 5.2], [0.2, 0], [0, 0]].map(([d, v]) => [d, v, FS.fluidTarget(d, v)]),
  easeTo: [[0, 1, 0.1], [0, 1, 0.5], [0.99, 1, 0.1], [0.5, 0.2, 0.016]].map(([v, t, dt]) => [v, t, dt, OE.easeTo(v, t, dt)]),
  fluidSpring: [[0, 0, 1000, 0.016], [500, 20, 1000, 0.05], [999, 0, 1000, 0.05]].map(([s, v, t, dt]) => { const r = { ...OE.fluidSpring(s, v, t, dt) }; return [s, v, t, dt, r.shown, r.vel]; }),
  clotRadius: ['PV_TRUNK', 'SV_CONF', 'PVH_R'].flatMap((id) => [0.2, 0.6, 1].flatMap((v) => [0, 0.25, 0.5, 0.9].map((f) => [id, v, f, CS.clotRadius(v, 12, f, CS.hashSeed(id))]))),
  clotSpan: [0, 0.5, 1].map((v) => [v, CS.clotSpan(v).u0, CS.clotSpan(v).u1]),
  clotSide: ['PV_TRUNK', 'SV_CONF', 'PVH_R', 'SMV_CONF'].map((id) => [id, CS.clotSide(CS.hashSeed(id))]),
  cavGrow: grid(10).map((r) => [r, CV.cavGrow(r, 0.22)]),
  cavOffset: A.CAV_CHANNELS.C8.map((c, i) => [i, [30, 50, 80, 100, 130].map((u) => CV.cavOffset(c, u, 150))]),
  varixSize: [['VAR', 2], ['VAR', 4.5], ['VAR', 7], ['GV', 6], ['GV', 9], ['GV', NaN]].map(([s, d]) => [s, Number.isFinite(d) ? d : null, VL.varixSize(s, d)]),
  varixBead: [0, 2, 4.5, 7, 10].map((d) => [d, VB.varixBead(d)]),
  grey: { sat: OD.LENS_GREY.sat, dim: OD.LENS_GREY.dim },
};
put('tests/fixtures/b4-2d.json', `${JSON.stringify(fixture)}\n`);

if (check) {
  if (changed.length) { console.error(`out of date: ${changed.join(', ')}\nrun: node scripts/copy-b4-data.mjs --from <2D checkout>`); process.exit(1); }
  console.log('b4 copies are current');
} else console.log(changed.length ? `wrote ${changed.length} file(s): ${changed.join(', ')}` : 'nothing changed');
