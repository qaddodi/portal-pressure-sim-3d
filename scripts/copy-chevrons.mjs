#!/usr/bin/env node
// Copies the 2D app's flow arrowhead into the 3D lobule (the owner, 20 Nov 2026: "Why is there stripe chevrons in the lobule wtf. Just use the normal chevrons similar to the 2D version"):
//   src/ui/chevron-glsl.js      -> CHEV_GLSL (chevD, chevHead), CHEV_PITCH_GLSL (chevLevel, chevKeep), CHEV_PITCH, CHEV_FLIP
//   src/ui/veins-gl.js          -> CHEV_ORANGE_GLSL (chevOrange)
//   src/ui/tube-lumen-glsl.js   -> LYMPH_INK (the lymph heads' inks, spacing and size rule), and the bile heads' pitch, size rule and two inks (read out of its shader text)
//   src/ui/lobule-zoom.js       -> LY_PITCH / LY_OCT (the lymph lattice), and the bile pitch (bile-flow: lobule-bile.js bileFlowInto: R * 0.14)
// into src/scene/lobule/from2d/chevron.generated.js, which the lobule's shader reads (lobule/shading.ts). Nothing about the heads is written by hand here.
//
//   node scripts/copy-chevrons.mjs --from <2D checkout> [--check]       (or PPS_2D_REPO=<2D checkout>)
//
// --check writes nothing and exits 1 when the file differs from what the 2D app would give.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { execFileSync } from 'node:child_process';

const here = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(here, '../src/scene/lobule/from2d/chevron.generated.js');
const arg = (n) => { const i = process.argv.indexOf(n); return i > 0 ? process.argv[i + 1] : null; };
const from = arg('--from') ?? process.env.PPS_2D_REPO, check = process.argv.includes('--check');
if (!from) { console.error('usage: node scripts/copy-chevrons.mjs --from <2D checkout> [--check]'); process.exit(2); }
let sha = 'unknown';
try { sha = execFileSync('git', ['-C', from, 'rev-parse', '--short=10', 'HEAD'], { encoding: 'utf8' }).trim(); } catch { /* not a git checkout */ }
const read = (rel) => readFileSync(join(from, rel), 'utf8');
const must = (m, what) => { if (!m) { console.error(`the 2D app no longer has ${what} where this script reads it`); process.exit(1); } return m; };

const ch = await import(pathToFileURL(join(from, 'src/ui/chevron-glsl.js')).href);   // (plain ES module, no imports)
const orangeAll = must(/export const CHEV_ORANGE_GLSL = `([\s\S]*?)`;/.exec(read('src/ui/veins-gl.js')), 'CHEV_ORANGE_GLSL')[1];
const orange = orangeAll.slice(0, orangeAll.indexOf('// A head\'s two inks')).trimEnd() + '\n';   // (chevOrange alone: the composite's own chevInks needs its uniforms; headInksGLSL in chevron-glsl.js drops it the same way)
const lumen = read('src/ui/tube-lumen-glsl.js');
const lymphInk = must(/export const LYMPH_INK = (\{[\s\S]*?\n\});/.exec(lumen), 'LYMPH_INK')[1];
const LYMPH_INK = new Function(`return (${lymphInk});`)();
// the bile heads: "float hw = min(0.8 * R1, clamp(0.5 * R1, 4.0 * cpx, 8.0 * cpx));" and the two inks "vec3(0.14, 0.18, 0.05)" (rim) and "vec3(0.64, 0.88, 0.30)" (core)
const bileAt = lumen.indexOf('if (blood == 1 && isBi && f1.z > 0.0) {');
const bile = must(bileAt >= 0 ? lumen.slice(bileAt, lumen.indexOf('if (blood == 1 && isLy', bileAt)) : null, 'the bile heads');
const hwB = must(/float hw = min\(([\d.]+) \* R1, clamp\(([\d.]+) \* R1, ([\d.]+) \* cpx, ([\d.]+) \* cpx\)\);/.exec(bile), 'the bile heads size rule').slice(1, 5).map(Number);
const gateB = must(/smoothstep\(([\d.]+), ([\d.]+), R1 \/ max\(pxW, 1e-3\)\)/.exec(bile), 'the bile heads thin-duct gate').slice(1, 3).map(Number);
const rimB = must(/col = mix\(col, vec3\(([\d., ]+)\), clamp\(h\.y \* ([\d.]+) \* k/.exec(bile), 'the bile heads rim');
const coreB = must(/col = mix\(col, vec3\(([\d., ]+)\), clamp\(h\.x \* k, 0\.0, 1\.0\)\);/.exec(bile), 'the bile heads core');
const nums = (s) => s.split(',').map((v) => Number(v.trim()));
const zoom = read('src/ui/lobule-zoom.js');
const ly = must(/const LY_PITCH = ([\d.]+), LY_OCT = (\d+);/.exec(zoom), 'LY_PITCH, LY_OCT');
const bileFlow = must(/const pitch = R \* ([\d.]+), v = R \* ([\d.]+);/.exec(read('src/ui/lobule-bile.js')), 'bileFlowInto');

const out = `// @generated by scripts/copy-chevrons.mjs from the 2D app's src/ui/chevron-glsl.js, veins-gl.js (CHEV_ORANGE_GLSL), tube-lumen-glsl.js (LYMPH_INK, the bile heads) and lobule-zoom.js at ${sha}. Do not edit; run the script again.
// @ts-nocheck (the 2D app's own code, kept as it is)
/** The flow arrowhead's shape (chevD, chevHead: u along the flow from the head's centre, ay across, hw the half width, px one device pixel, rev the reversed flag's second head). */
export const CHEV_GLSL = ${JSON.stringify(ch.CHEV_GLSL)};
/** The heads' spacing rule (chevLevel, chevKeep): the same distance on screen between heads, CHEV_PITCH CSS px, whatever the zoom. */
export const CHEV_PITCH_GLSL = ${JSON.stringify(ch.CHEV_PITCH_GLSL)};
export const CHEV_PITCH = ${ch.CHEV_PITCH};
/** The lumen luminance band over which a head's ink flips from near-black to cream. */
export const CHEV_FLIP = ${JSON.stringify(ch.CHEV_FLIP)};
/** How orange a vessel's colour is (a reversed head is cream on an orange lumen). */
export const CHEV_ORANGE_GLSL = ${JSON.stringify(orange)};
/** The lymph heads: inks, spacing (CSS px), size rule and strength (tube-lumen-glsl.js LYMPH_INK); LY_PITCH is the base pitch as a share of the lobule radius and LY_OCT how many times it may double (lobule-zoom.js). */
export const LYMPH_INK = ${JSON.stringify(LYMPH_INK)};
export const LY_PITCH = ${ly[1]}, LY_OCT = ${ly[2]};
/** The bile heads: the pitch and speed as shares of the lobule radius (lobule-bile.js bileFlowInto), the size rule (half the caliber, 4 to 8 CSS px, never wider than 0.8 of it), the thin-duct gate (device px of radius), the core and rim inks. */
export const BILE_HEADS = ${JSON.stringify({ pitch: Number(bileFlow[1]), speed: Number(bileFlow[2]), hw: hwB, gate: gateB, core: nums(coreB[1]), rim: nums(rimB[1]), rimStrength: Number(rimB[2]) })};
`;
if (check) {
  let cur = ''; try { cur = readFileSync(OUT, 'utf8'); } catch { /* none */ }
  if (cur !== out) { console.error('src/scene/lobule/from2d/chevron.generated.js differs from the 2D app: run scripts/copy-chevrons.mjs --from <2D>'); process.exit(1); }
  console.log('chevron copy is current'); process.exit(0);
}
writeFileSync(OUT, out);
console.log('wrote', OUT);
