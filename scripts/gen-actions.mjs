// Writes the tap-anything cards' words and the 2D app's answers the 3D port is tested against, from a checkout of the 2D app (never retyped):
//   src/ui/action/actions.generated.ts   the lobule parts' sentences (actions.js constants, verbatim)
//   tests/fixtures/actions-2d.json        every card (actions.js cardFor) as the 2D app builds it: its words and verbs, and for six patients what its readings,
//                                         status and sliders say, and what each slider and toggle does to the parameters
// Usage: node scripts/gen-actions.mjs --from <2D checkout, preview branch>
// The patients' frames come from this repository's engine (the vendored copy of the one the 2D app runs), fed to the 2D app's own card functions.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createCore } from '../src/engine/host/worker-core.js';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const argv = process.argv.slice(2);
const from = resolve(argv[argv.indexOf('--from') + 1] || '../portal-pressure-simulator');
const at = (p) => pathToFileURL(resolve(from, p)).href;
await import(at('tests/dom-shim.js'));
const src = readFileSync(resolve(from, 'src/ui/actions.js'), 'utf8');
const A = await import(at('src/ui/actions.js'));
const { store } = await import(at('src/ui/store.js'));
const { EDGES } = await import(at('src/engine/portal/topology.js'));
const { fmt } = await import(at('src/ui/util.js'));

// ── the lobule's sentences, verbatim ──
const NAMES = ['TRIAD_A', 'TRIAD_FIB', 'TRIAD_BACK', 'IN_A', 'IN_BACK', 'AN_A', 'SIN_A', 'SIN_FIB', 'SIN_CONG', 'CV_A', 'CV_FIB', 'CV_CONG', 'HA_A', 'HA_BUFFER', 'BD_A', 'BS_A', 'BH_A', 'LV_A', 'LV_UP', 'LV_DOWN', 'SEPTUM_A', 'HEP_CONG', 'ZONE_TEXT'];
const lines = [];
for (const n of NAMES) {
  const m = src.match(new RegExp(`^const ${n} = (.*);(?:\\s*//.*)?$`, 'm'));
  if (!m) throw new Error(`2D no longer has ${n}`);
  new Function('fmt', `return (${m[1]})`)(fmt);   // (it must still evaluate)
  lines.push(`export const ${n} = ${m[1].replace(/^\(x\) =>/, '(x: number) =>')};`);
}
const gen = `// GENERATED by scripts/gen-actions.mjs from the 2D app (qaddodi/portal-pressure-simulator, src/ui/actions.js). Do not edit.
// The lobule parts' sentences, as the 2D cards say them.
import { fmt } from '../charts/fmt.ts';
${lines.join('\n')}
`;
writeFileSync(resolve(root, 'src/ui/action/actions.generated.ts'), gen);

// ── the cards ──
const ctx = { canShunt: () => true, injectDye() {}, releaseDye() {}, dyeInjecting: () => false, canDye: () => true, openIr() {}, probe() {}, showPane() {}, select() {}, startShunt() {}, action() {}, paneApi: () => null, zoomLobule() {}, askSinusoid() {} };
const PRESETS = ['healthy', 'cirr-decomp', 'pvt-acute', 'cirr-decomp-tips', 'budd-chiari', 'gastric-varix'];
const sels = [
  ...EDGES.filter((e) => e.kind !== 'wedge').map((e) => ({ type: 'edge', id: e.id })),
  ...['liver', 'heart', 'varices', 'gastric', 'spleen'].map((id) => ({ type: 'organ', id })),
  ...['triad', 'in', 'sin', 'an', 'cv', 'ha', 'bd', 'bs', 'bh', 'lv', 'septum'].map((part) => ({ type: 'lobule', part })),
  { type: 'lobule', zone: 1 }, { type: 'lobule', zone: 2 }, { type: 'lobule', zone: 3 },
];
// (the 119 generated custom shunts read alike: three stand for them)
let custom = 0;
const picked = sels.filter((s) => { if (s.type === 'edge' && s.id.startsWith('X_')) return custom++ < 3; return true; });

const STATIC_KEYS = ['type', 'id', 'key', 'label', 'short', 'icon', 'min', 'max', 'step', 'def', 'info', 'hist', 'options', 'ticks', 'tickNames', 'danger', 'quiet', 'small', 'unit'];
const clone = (o) => JSON.parse(JSON.stringify(o));
function diff(a, b, path = '', out = {}) {
  const isO = (x) => x && typeof x === 'object' && !Array.isArray(x);
  if (isO(a) && isO(b)) { for (const k of new Set([...Object.keys(a), ...Object.keys(b)])) diff(a[k], b[k], path ? `${path}.${k}` : k, out); }
  else if (JSON.stringify(a) !== JSON.stringify(b)) out[path] = b === undefined ? null : b;   // (null = the key is gone)
  return out;
}
const num = (x) => (typeof x === 'number' && Number.isFinite(x) ? x : x ?? null);
const copyReading = (r) => (r == null ? null : { v: r.v, u: r.u, d: r.d ?? null, up: !!r.up });
const safe = (fn) => { try { return fn(); } catch (e) { return `ERR ${e.message}`; } };

const out = { generatedFrom: '2D preview branch, actions.js cardFor', presets: PRESETS, cards: [], readings: {}, sets: {}, patients: {} };
const keyOf = (s) => `${s.type}:${s.id ?? s.part ?? s.zone}`;
const cards = picked.map((s) => ({ s, c: A.cardFor(s, ctx) }));
for (const { s, c } of cards) {
  if (!c) { out.cards.push({ sel: s, none: true }); continue; }
  out.cards.push({
    sel: s, key: c.key ?? null, kicker: c.kicker, title: c.title, why: c.why ?? null, edge: c.edge ?? null, noValue: !!c.noValue, noDetails: !!c.noDetails, hasSpan: !!c.span,
    spanLabels: c.span ? { el: c.span.el ?? null, dn: c.span.dn ?? null, cut: c.span.cut ?? null } : null,
    verbs: c.verbs.map((v) => { const o = {}; for (const k of STATIC_KEYS) if (v[k] !== undefined) o[k] = v[k]; if (typeof v.format === 'function' && v.min !== undefined) o.formatAt = [v.min, v.max, v.def].map((x) => v.format(x)); return o; }),
  });
}
const core = createCore((m) => frames.push(m));
const frames = [];
await core.handle({ type: 'init' }); await core.handle({ type: 'run', running: false });
for (const id of PRESETS) {
  frames.length = 0;
  await core.handle({ type: 'preset', id, reqId: 1 });
  await core.handle({ type: 'healthyProfile', reqId: 2 });
  const h = frames.find((m) => m.type === 'healthy'), f0 = frames.filter((m) => m.type === 'frame').pop(), pl = frames.find((m) => m.type === 'presetLoaded');
  // (The frame goes into the fixture, and the 2D cards read the frame as the test will read it: the engine's last frame differs by a beat from one run to the next.)
  const rec0 = { params: pl.params, healthy: { P: Array.from(h.P), Q: Array.from(h.Q), hepLymph: h.metrics?.ascites?.hepLymph ?? h.metrics?.hepLymph ?? null },
    frame: { P: Array.from(f0.P), Pf: Array.from(f0.Pf), Q: Array.from(f0.Q), Qf: Array.from(f0.Qf), D: Array.from(f0.D), metrics: f0.metrics, slow: f0.slow, bands: f0.bands ?? 0 } };
  const back = JSON.parse(JSON.stringify(rec0));
  out.patients[id] = back;
  const f = { ...back.frame, P: Float32Array.from(back.frame.P), Pf: Float32Array.from(back.frame.Pf), Q: Float32Array.from(back.frame.Q), Qf: Float32Array.from(back.frame.Qf), D: Float32Array.from(back.frame.D) };
  const hh = { P: back.healthy.P, Q: back.healthy.Q, metrics: { ascites: { hepLymph: back.healthy.hepLymph } } };
  store.set({ params: back.params, healthy: hh, frame: f });
  const P = back.params, rec = {};
  for (const { s, c } of cards) {
    if (!c) continue;
    const r = { verbs: [] };
    if (!c.noValue) r.value = Object.fromEntries(['pressure', 'flow', 'velocity', 'drop', 'oxygen'].map((lens) => [lens, copyReading(safe(() => c.value(f, lens, hh.P)))]));
    else r.value = null;
    r.status = c.status ? safe(() => c.status(f)) : null;
    r.span = c.span ? safe(() => { const q = c.span.at(f); return { a: num(q.a), b: num(q.b), d: num(q.d), ok: !!q.ok }; }) : null;
    for (const v of c.verbs) {
      const e = { type: v.type, id: v.id ?? null };
      if (v.type === 'read') e.value = safe(() => String(v.value(f)));
      else if (v.type === 'stat') e.value = safe(() => String(v.value(f)));
      else if (v.type === 'about') e.lines = safe(() => [...v.text(f)]);
      else if (v.type === 'meter') e.share = safe(() => num(v.share(f)));
      else if (v.type === 'slider') { const g = safe(() => v.get(P)); e.get = num(g); e.text = typeof g === 'number' ? safe(() => v.format(g)) : null; }
      else if (v.type === 'toggle') e.get = safe(() => !!v.get(P));
      else if (v.type === 'seg') e.get = safe(() => v.get());
      if (v.showIf) e.showIf = safe(() => !!v.showIf(P));
      if (v.note) e.note = safe(() => v.note(f));
      r.verbs.push(e);
    }
    (rec[keyOf(s)] ||= r);
  }
  out.readings[id] = rec;
  // what each slider and toggle does to the parameters, on this patient's own (the first patient with the control that is not at its default)
  if (id === 'healthy' || id === 'cirr-decomp') {
    const sets = {};
    for (const { s, c } of cards) {
      if (!c) continue;
      const list = [];
      for (const v of c.verbs) {
        if (v.type === 'slider') {
          const mid = +(v.min + (v.max - v.min) * 0.37).toFixed(3), probes = [...new Set([v.def, v.min, v.max, mid, 0.002, 0.004, 0.006].filter((x) => x >= v.min && x <= v.max))];
          const r = {};
          for (const x of probes) { const p = clone(P); safe(() => v.set(p, x)); r[x] = diff(P, p); }
          const p1 = clone(P); safe(() => v.set(p1, mid)); const p2 = clone(p1); safe(() => v.set(p2, v.def)); r.midThenDef = diff(p1, p2);
          list.push({ id: v.id, probes: r });
        } else if (v.type === 'toggle') {
          const on = clone(P), off = clone(P); safe(() => v.set(on, true)); safe(() => v.set(off, false));
          const on2 = clone(on); safe(() => v.set(on2, false));
          list.push({ id: v.id, on: diff(P, on), off: diff(P, off), onThenOff: diff(on, on2) });
        }
      }
      if (list.length) (sets[id] ||= {})[keyOf(s)] = list;
    }
    out.sets[id] = sets[id];
  }
}
core.dispose();
mkdirSync(resolve(root, 'tests/fixtures'), { recursive: true });
writeFileSync(resolve(root, 'tests/fixtures/actions-2d.json'), JSON.stringify(out) + '\n');
console.log(`actions.generated.ts, actions-2d.json (${out.cards.length} cards, ${PRESETS.length} patients)`);
