#!/usr/bin/env node
// Copies what the Tests instruments need to run as a slide's data card (a slide's `tool`), so no number, word or layout is retyped (parity plan section 2).
//   src/ui/tests/slide/copied/beat-card.copied.js   beat-card.js: the slide's beat-by-beat card's layout (scale top, column plan, EKG paper squares, where "before" goes, the change since)
//   src/ui/tests/slide/copied/hvpg-card.copied.js   tool-hvpg.js, its words and pure parts (levelsOf, STEPS, the three readings, the next reading's words) and hvpg-proc.js's SPAN and ORDER
//   src/ui/tests/slide/copied/tool-room.copied.js   tool-room.js: the room a data card's instrument has for its pictures
// Usage: node scripts/copy-b11-slide.mjs --from <2D checkout> [--check]    (--check writes nothing and fails when a file would change)
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';

const args = process.argv.slice(2);
const flag = (n) => { const i = args.indexOf(n); return i >= 0 ? args[i + 1] : null; };
const from = flag('--from') ?? process.env.PPS_2D_REPO;
const check = args.includes('--check');
if (!from || !existsSync(`${from}/src/ui/beat-card.js`)) { console.error('usage: copy-b11-slide.mjs --from <2D checkout>'); process.exit(2); }
let commit = 'unknown';
try { commit = execFileSync('git', ['-C', from, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim(); } catch { /* not a checkout */ }
const dir = new URL('../src/ui/tests/slide/copied/', import.meta.url);
mkdirSync(dir, { recursive: true });
const changed = [];
const put = (name, text) => {
  const url = new URL(name, dir);
  if (existsSync(url) && readFileSync(url, 'utf8') === text) return;
  changed.push(name);
  if (!check) writeFileSync(url, text);
};
const HEAD = (what) => `// GENERATED by scripts/copy-b11-slide.mjs from the 2D app at ${commit.slice(0, 8)} (${what}). Do not edit; run the script again.\n`;
const read = (p) => readFileSync(`${from}/${p}`, 'utf8');

put('beat-card.copied.js', HEAD('beat-card.js') + read('src/ui/beat-card.js'));
put('tool-room.copied.js', HEAD('tool-room.js') + read('src/ui/tool-room.js'));

// ── tool-hvpg.js: levelsOf, STEPS, READS and NEXT_WORDS (the card's words); hvpg-proc.js: the three spans the tracing plays and their order ──
{
  const src = read('src/ui/tool-hvpg.js'), proc = read('src/ui/hvpg-proc.js');
  const a = src.indexOf('/** The readings a card shows from a fingerprint');
  const b = src.indexOf('export function createHvpgCard');
  const s1 = proc.indexOf('const SPAN = '), s2 = proc.indexOf('const ORDER = ');
  if (a < 0 || b < 0 || s1 < 0 || s2 < 0) throw new Error('tool-hvpg.js or hvpg-proc.js has changed shape');
  const spans = proc.slice(s1, proc.indexOf('\n', s2) + 1).replace(/^const /gm, 'export const ');
  const head = `import { tenthGap } from '../../../../engine/hales/core/gap.js';
import { T } from '../../copied/hvpg-clock.copied.js';
`;
  put('hvpg-card.copied.js', HEAD('tool-hvpg.js, its pure parts; hvpg-proc.js SPAN and ORDER') + head + src.slice(a, b).replace(/^const (KEYS|READS|NEXT_WORDS) = /gm, 'export const $1 = ') + spans);
}

if (check) { if (changed.length) { console.error(`out of date: ${changed.join(', ')}`); process.exit(1); } console.log('src/ui/tests/slide/copied is current'); }
else console.log(changed.length ? `wrote ${changed.join(', ')}` : 'src/ui/tests/slide/copied is current');
