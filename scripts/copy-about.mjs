#!/usr/bin/env node
// Copies the About the model and Privacy pages of the 2D app as data, so the 3D app shows the same words (parity plan, section 2: "Words come from the 2D source, never retyped").
//
//   node scripts/copy-about.mjs --from <2D checkout> [--check]
//
// Runs the 2D source's own openAbout() and openPrivacy() (src/ui/main.js) against a stub `h` that records the tree it would have built, with the page's constants
// (src/version.js: AUTHOR, AUTHOR_URL, UPDATED, VALIDATION; src/ui/dock.js: CUTOFFS) read from the same checkout, and writes src/ui/shell/about.copied.ts.
// The tree is {t: tag, p: props, k: kids}; the clear-data button is {t: 'clear-row'} (the 3D app owns what it clears) and the paragraph that names the feedback email
// is marked {p: {needsEmail: true}} (the 3D app leaves it out while no email is configured). --check writes nothing and exits 1 when the file differs.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const here = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(here, '../src/ui/shell/about.copied.ts');
const arg = (n) => { const i = process.argv.indexOf(n); return i > 0 ? process.argv[i + 1] : null; };
const from = arg('--from'), check = process.argv.includes('--check');
if (!from) { console.error('usage: node scripts/copy-about.mjs --from <2D checkout> [--check]'); process.exit(2); }
const read = (f) => readFileSync(resolve(from, f), 'utf8');

/** The text from `start` (an index at an opening bracket) to its closing bracket, skipping strings, template literals and comments. */
function balanced(text, start) {
  const open = text[start], close = { '{': '}', '[': ']', '(': ')' }[open];
  let depth = 0, q = null;
  for (let i = start; i < text.length; i++) {
    const c = text[i];
    if (q) { if (c === '\\') i++; else if (c === q) q = null; continue; }
    if (c === '"' || c === "'" || c === '`') { q = c; continue; }
    if (c === '/' && text[i + 1] === '/') { while (i < text.length && text[i] !== '\n') i++; continue; }
    if (c === open) depth++; else if (c === close && --depth === 0) return text.slice(start, i + 1);
  }
  throw new Error('never closed');
}
const fnSource = (text, name) => {
  const m = new RegExp(`function ${name}\\s*\\(`).exec(text);
  if (!m) throw new Error(`the 2D source has no function ${name} any more`);
  const body = text.indexOf('{', text.indexOf(')', m.index));
  return text.slice(m.index, body) + balanced(text, body);
};
const constSource = (text, name) => {
  const m = new RegExp(`(?:const |, )${name}\\s*=\\s*`).exec(text);
  if (!m) throw new Error(`the 2D source has no const ${name} any more`);
  const i = m.index + m[0].length;
  return balanced(text, text[i] === '[' || text[i] === '{' ? i : text.indexOf('[', i));
};

const main = read('src/ui/main.js'), version = read('src/version.js'), dock = read('src/ui/dock.js');
const str = (name) => new RegExp(`export const ${name} = '([^']*)'`).exec(version)?.[1].replace(/\\u00a0/g, ' ');
const ctx = {
  AUTHOR: str('AUTHOR'), AUTHOR_URL: str('AUTHOR_URL'), UPDATED: str('UPDATED'), RELEASE: '', FEEDBACK_EMAIL: 'email',
  VALIDATION: vm.runInNewContext(constSource(version, 'VALIDATION')),
  CUTOFFS: vm.runInNewContext(constSource(dock, 'CUTOFFS')),
  CUT_HEADS: vm.runInNewContext(constSource(main, 'CUT_HEADS')), CUT_SEV: vm.runInNewContext(constSource(main, 'CUT_SEV')),
  prefs: { keys: () => [] }, scrollToSection() {}, tableRoles: (x) => x, clearRow: () => ({ t: 'clear-row' }),
};
const flat = (kids) => kids.flat(Infinity).filter((k) => k != null && k !== false);
ctx.h = (t, p, ...k) => {
  const node = { t };
  if (p && Object.keys(p).length) node.p = p;
  const kids = flat(k);
  if (kids.length) node.k = kids;
  return node;
};
ctx.pmid = (id) => ctx.h('a', { href: `https://pubmed.ncbi.nlm.nih.gov/${id}/` }, `PMID ${id}`);
const out = {};
ctx.openModal = (title, body, opts = {}) => { out.title = title; out.body = body; out.sub = opts.sub ?? null; out.wide = !!opts.wide; };
const run = (name) => { out.title = out.body = null; vm.runInNewContext(`${fnSource(main, name)}; ${name}();`, ctx); return { title: out.title, sub: out.sub, wide: out.wide, body: out.body }; };
const about = run('openAbout'), privacy = run('openPrivacy');
// the paragraph about the feedback email: kept for a build that has one
const mark = (n) => { if (n && typeof n === 'object') { if (n.t === 'p' && typeof n.k?.[0] === 'string' && n.k[0].startsWith('Send feedback (in Settings)')) (n.p ??= {}).needsEmail = true; n.k?.forEach(mark); } };
mark(privacy.body);
const ver = /Updated \S+ · /; if (about.sub) about.sub = about.sub.replace(/ · .*$/, '');
const file = `// @generated by scripts/copy-about.mjs from the 2D app's openAbout() and openPrivacy() (src/ui/main.js). Do not edit: re-run the script.
export interface Node { t: string; p?: Record<string, string | boolean | number>; k?: (Node | string)[] }
export interface Page { title: string; sub: string | null; wide: boolean; body: Node }
export const ABOUT: Page = ${JSON.stringify(about, null, 1)};
export const PRIVACY: Page = ${JSON.stringify(privacy, null, 1)};
`;
void ver;
if (check) { let cur = ''; try { cur = readFileSync(OUT, 'utf8'); } catch { /* none yet */ } if (cur !== file) { console.error('src/ui/shell/about.copied.ts differs from the 2D source: run node scripts/copy-about.mjs --from <2D>'); process.exit(1); } console.log('about.copied.ts matches the 2D source'); }
else { writeFileSync(OUT, file); console.log(`wrote ${OUT}`); }
