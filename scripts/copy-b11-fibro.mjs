#!/usr/bin/env node
// Copies what the FibroScan pane needs from the 2D app, so no number, word or shader line is retyped (parity plan section 2).
//   src/ui/tests/fibro/copied/fibro-model.copied.js    fibroscan.js: the depth and window constants, the noise fields and elastogramPixels (the CPU reference of the map), shearSpeed, the two
//                                                      exams' table (ORGAN: name, colours, widest reading), the label texts and the dash patterns. The DOM half of the file is left behind.
//   src/ui/tests/fibro/copied/fibro-gl.copied.js       fibroscan-gl.js whole: the map's shaders and elastogramUnder(F), which draws the map inside another WebGL2 context (the chart pool's).
//   src/ui/tests/fibro/copied/display-state.copied.js  display-state.js whole (createFollow: the number's critically damped follow).
// Usage: node scripts/copy-b11-fibro.mjs --from <2D checkout> [--check]    (--check writes nothing and fails when a file would change)
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';

const args = process.argv.slice(2);
const flag = (n) => { const i = args.indexOf(n); return i >= 0 ? args[i + 1] : null; };
const from = flag('--from') ?? process.env.PPS_2D_REPO;
const check = args.includes('--check');
if (!from || !existsSync(`${from}/src/ui/fibroscan.js`)) { console.error('usage: copy-b11-fibro.mjs --from <2D checkout>'); process.exit(2); }
let commit = 'unknown';
try { commit = execFileSync('git', ['-C', from, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim(); } catch { /* not a checkout */ }

const dir = new URL('../src/ui/tests/fibro/copied/', import.meta.url);
mkdirSync(dir, { recursive: true });
const changed = [];
const put = (name, text) => {
  const url = new URL(name, dir);
  if (existsSync(url) && readFileSync(url, 'utf8') === text) return;
  changed.push(name);
  if (!check) writeFileSync(url, text);
};
const HEAD = (what) => `// GENERATED by scripts/copy-b11-fibro.mjs from the 2D app at ${commit.slice(0, 8)} (${what}). Do not edit; run the script again.\n`;
const read = (p) => readFileSync(`${from}/${p}`, 'utf8');

// ── fibroscan.js: the pure half ──
const fs = read('src/ui/fibroscan.js').split('\n');
const at = (re, from0 = 0) => { const i = fs.findIndex((l, k) => k >= from0 && re.test(l)); if (i < 0) throw new Error(`fibroscan.js has no line for ${re}`); return i; };
const span = (a, b) => fs.slice(at(a), at(b) + 1).join('\n');
const exp = (s) => s.replace(/^const /gm, 'export const ');
// (clamp comes from num.js, which the Tests card already has as ../../copied/num.copied.js)
if (!/^export const clamp\b|^export function clamp\b/m.test(read('src/ui/num.js'))) throw new Error('num.js has no clamp');
const parts = [
  "import { clamp } from '../../copied/num.copied.js';",
  exp(span(/^const WAVE_T0\b/, /^export const DEPTH0\b/)),
  exp(fs[at(/^const DASH = /)]),
  exp(fs[at(/^const DEPTH_TXT = /)]),
  span(/^const rnd = /, /^export const elastogramInputs\b/).replace(/^const REDUCED_MQ\b.*$/m, '// (REDUCED_MQ: the pane reads Reduce Motion itself)'),
  exp(span(/^const ORGAN = \{/, /^const ORGAN_WORDS\b/)),
];
put('fibro-model.copied.js', HEAD('fibroscan.js, the pure half') + parts.join('\n') + '\n');

// ── fibroscan-gl.js: the map's shaders, whole; its one import (the shader starter) is the pane's own small shim ──
const gl = read('src/ui/fibroscan-gl.js');
if (!/from '\.\/gl-compile\.js'/.test(gl)) throw new Error("fibroscan-gl.js no longer imports './gl-compile.js'");
put('fibro-gl.copied.js', HEAD('fibroscan-gl.js') + gl.replace(/from '\.\/gl-compile\.js'/, "from '../gl-compile.shim.js'"));

// ── display-state.js: whole (it imports nothing) ──
const ds = read('src/ui/display-state.js');
if (/^import /m.test(ds)) throw new Error('display-state.js now imports something: not copied whole');
put('display-state.copied.js', HEAD('display-state.js') + ds);

if (check) { if (changed.length) { console.error(`out of date: ${changed.join(', ')}`); process.exit(1); } console.log('src/ui/tests/fibro/copied is current'); }
else console.log(changed.length ? `wrote ${changed.join(', ')}` : 'src/ui/tests/fibro/copied is current');
