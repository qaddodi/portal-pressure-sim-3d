#!/usr/bin/env node
// Copies what the 2D presenter points a slide's figure fields at, so the 3D figure lights the same things for the same words
// (parity plan, section 2: "Words come from the 2D source, never retyped").
//
//   node scripts/copy-figure-targets.mjs --from <2D checkout> [--check]
//
// Reads <2D>/src/ui/presenter-words.js (TARGETS: a word's station, vessels, organ and colour; EDGE_TONE, SITE_NODE, VAL_TONE), highlight-math.js (SETS, the
// organ targets), callout-math.js (ORGAN_ANCHOR, ORGAN_MARKS, the spleen's caliper axis, the varix vessel) and stage-sites.js (SITE_DEF: each site's station,
// words and kind), and writes src/scene/labels/figure2d.copied.ts. --check writes nothing and exits 1 when the copied file differs from the 2D source.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { pathToFileURL, fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';
import { execFileSync } from 'node:child_process';
import vm from 'node:vm';

const here = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(here, '../src/scene/labels/figure2d.copied.ts');
/** The text of a top-level `const NAME = <literal>;` block, found by its brackets (strings and comments inside are skipped). */
export function literalOf(text, name) {
  const m = new RegExp(`(?:export\\s+)?const\\s+${name}\\s*=\\s*`).exec(text);
  if (!m) throw new Error(`the 2D source has no "${name}" any more`);
  let i = m.index + m[0].length;
  const start = i;
  const open = text[i];
  const close = { '{': '}', '[': ']' }[open];
  if (!close) throw new Error(`"${name}" is not an object or array literal`);
  let depth = 0, q = null;
  for (; i < text.length; i++) {
    const c = text[i];
    if (q) { if (c === '\\') i++; else if (c === q) q = null; continue; }
    if (c === '"' || c === "'" || c === '`') { q = c; continue; }
    if (c === '/' && text[i + 1] === '/') { while (i < text.length && text[i] !== '\n') i++; continue; }
    if (c === open) depth++;
    else if (c === close && --depth === 0) return text.slice(start, i + 1);
  }
  throw new Error(`"${name}" is never closed`);
}

const arg = (n) => { const i = process.argv.indexOf(n); return i > 0 ? process.argv[i + 1] : null; };

export async function extract(root) {
  await import(pathToFileURL(`${root}/tests/dom-shim.js`).href);   // (the presenter's modules are UI modules; Node has no DOM)
  const words = await import(pathToFileURL(`${root}/src/ui/presenter-words.js`).href);
  const hm = await import(pathToFileURL(`${root}/src/ui/highlight-math.js`).href);
  const cm = await import(pathToFileURL(`${root}/src/ui/callout-math.js`).href);
  const sitesSrc = readFileSync(`${root}/src/ui/stage-sites.js`, 'utf8');
  const SITE_DEF = vm.runInNewContext(`(${literalOf(sitesSrc, 'SITE_DEF')})`, {});
  const clean = (t) => Object.fromEntries(Object.entries(t).filter(([, v]) => v !== undefined));
  return {
    TARGETS: Object.fromEntries(Object.entries(words.TARGETS).map(([k, t]) => [k, clean(t)])),
    EDGE_TONE: words.EDGE_TONE, SITE_NODE: words.SITE_NODE, VAL_TONE: words.VAL_TONE,
    SETS: hm.SETS,
    ORGANS: ['liver', 'caudate', 'caudate-lobe', 'spleen', 'heart', 'heart-ra', ...hm.NEW_ORGANS],
    ORGAN_ANCHOR: Object.fromEntries(Object.entries(cm.ORGAN_ANCHOR).map(([k, a]) => [k, { at: [...a.at], half: [...a.half] }])),
    ORGAN_MARKS: cm.ORGAN_MARKS, SPLEEN_AXIS: cm.SPLEEN_AXIS, VARIX_EDGE: cm.VARIX_EDGE,
    SPAN: { y: cm.SPAN_Y, tick: cm.SPAN_TICK, laneLow: cm.LANE_LOW, room: cm.SPAN_ROOM },
    SITE_DEF,
  };
}

export function render(d, source) {
  const line = (name, type, v) => `export const ${name}: ${type} = ${JSON.stringify(v)};\n`;
  return `// @generated by scripts/copy-figure-targets.mjs from ${source}. Do not edit: run the script again.
// What a slide's figure fields point at (presenter-words.js TARGETS and its colour tables, highlight-math.js SETS, callout-math.js organ anchors, the spleen's caliper axis and the circuit bracket's heights,
// stage-sites.js SITE_DEF). World units are the 2D plate's (x 300 to 1120, y 0 to 920).
export interface Target2D { node?: string; edges?: readonly string[]; organ?: string; res?: string; site?: string; lit?: boolean; tone: string; words?: string }
export interface SiteDef2D { node?: string; kicker: string; cls: string; below?: boolean; split?: boolean; unit?: string; res?: string }
${line('TARGETS_FIG', 'Readonly<Record<string, Target2D>>', d.TARGETS)}${line('EDGE_TONE_2D', 'Readonly<Record<string, string>>', d.EDGE_TONE)}${line('SITE_NODE_2D', 'Readonly<Record<string, string>>', d.SITE_NODE)}${line('VAL_TONE_2D', 'Readonly<Record<string, string>>', d.VAL_TONE)}${line('SETS_FIG', 'Readonly<Record<string, readonly string[]>>', d.SETS)}${line('ORGANS_FIG', 'readonly string[]', d.ORGANS)}${line('ORGAN_ANCHOR_2D', 'Readonly<Record<string, { at: readonly [number, number]; half: readonly [number, number] }>>', d.ORGAN_ANCHOR)}${line('ORGAN_MARKS_2D', 'readonly string[]', d.ORGAN_MARKS)}${line('SPLEEN_AXIS_2D', 'readonly [readonly [number, number], readonly [number, number]]', d.SPLEEN_AXIS)}${line('VARIX_EDGE_2D', 'string', d.VARIX_EDGE)}${line('SPAN_2D', '{ readonly y: number; readonly tick: number; readonly laneLow: number; readonly room: number }', d.SPAN)}${line('SITE_DEF_2D', 'Readonly<Record<string, SiteDef2D>>', d.SITE_DEF)}`;
}

async function main() {
  const from = arg('--from') ?? process.env.PPS_2D_REPO;
  if (!from || !existsSync(`${from}/src/ui/presenter-words.js`)) { console.error('usage: node scripts/copy-figure-targets.mjs --from <2D checkout> [--check]'); process.exit(2); }
  const root = resolve(from);
  let commit = 'unknown';
  try { commit = execFileSync('git', ['-C', root, 'rev-parse', '--short=10', 'HEAD'], { encoding: 'utf8' }).trim(); } catch { /* not a git checkout */ }
  const text = render(await extract(root), `src/ui/presenter-words.js, highlight-math.js, callout-math.js and stage-sites.js of qaddodi/portal-pressure-simulator at ${commit}`);
  const body = (t) => t.split('\n').filter((l) => !l.startsWith('// @generated')).join('\n');
  if (process.argv.includes('--check')) {
    if (!existsSync(OUT) || body(readFileSync(OUT, 'utf8')) !== body(text)) { console.error('src/scene/labels/figure2d.copied.ts differs from the 2D source: run scripts/copy-figure-targets.mjs again'); process.exit(1); }
    console.log('figure2d.copied.ts matches the 2D app');
    return;
  }
  writeFileSync(OUT, text);
  console.log(`wrote ${OUT} (2D at ${commit})`);
}
if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) await main();
