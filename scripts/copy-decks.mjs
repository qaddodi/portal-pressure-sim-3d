#!/usr/bin/env node
// Copies the words of the HVPG deck's slice from the 2D app, so the 3D app teaches exactly what the 2D app teaches.
//
//   node scripts/copy-decks.mjs --from <2D checkout> [--check]
//
// Reads <2D checkout>/src/ui/decks/hvpg.js, takes the slice (the slides and checks named below), and writes
// src/decks/hvpg.copied.ts. The 3D fields (shots, ladder rows) are NOT written here: they live in src/decks/hvpg.ts.
// --check writes nothing and exits 1 when the copied file differs from what the 2D deck would give (the unit test uses it
// when a 2D checkout is at hand). Run it again before every slice push (docs/slice-plan.md, section 6).

import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { pathToFileURL } from 'node:url';
import { resolve, dirname } from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(here, '../src/decks/hvpg.copied.ts');

/** The slice: slide ids, in the order the 3D deck plays them, and which of the deck's quick-check questions the slice has taught. */
export const SLICE = {
  slides: ['route', 'free', 'wedge', 'hvpg'],
  // checks 1 and 2 are about the HVPG's calculation and cut-offs, which the slice teaches; 3 (PPG) and 4 (right heart failure) come with their slides
  checks: [0, 1],
  fields: ['id', 'kicker', 'title', 'line', 'vignette', 'terms', 'notes', 'ask', 'cath'],
};

/** <mi class="eq-wedge">WHVP</mi> → { tag: 'mi', text: 'WHVP', tone: 'wedge' } */
export function parseEq(markup) {
  const parts = [];
  for (const m of String(markup).matchAll(/<(mi|mo)(?:\s+class="([^"]*)")?>([^<]*)<\/\1>/g)) {
    const part = { tag: m[1], text: m[3] };
    if (/eq-wedge/.test(m[2] || '')) part.tone = 'wedge';
    else if (/eq-hv/.test(m[2] || '')) part.tone = 'free';
    parts.push(part);
  }
  const left = String(markup).replace(/<(mi|mo)(?:\s+class="[^"]*")?>[^<]*<\/\1>/g, '').trim();
  if (left) throw new Error(`an equation part this script does not read: ${left}`);
  return parts;
}

export function extract(deck) {
  const slides = SLICE.slides.map((id) => {
    const s = deck.slides.find((x) => x.id === id);
    if (!s) throw new Error(`the 2D deck has no slide "${id}"`);
    const out = {};
    for (const f of SLICE.fields) if (s[f] !== undefined) out[f] = s[f];
    if (s.eq) out.eq = parseEq(s.eq[0]);
    return out;
  });
  return {
    id: deck.id, title: deck.title, level: deck.level, minutes: deck.minutes, summary: deck.summary, objectives: deck.objectives,
    // the outline's own sections ([name, [kickers or slide ids]]), as the 2D deck writes them: the opening slide lists them (withOverview)
    ...(deck.sections ? { sections: deck.sections } : {}),
    checks: SLICE.checks.map((i) => deck.checks[i]),
    slides,
  };
}

export function render(copied, source) {
  const json = JSON.stringify(copied, null, 2);
  const hash = createHash('sha256').update(json).digest('hex').slice(0, 12);
  return `// @generated by scripts/copy-decks.mjs from ${source}. Do not edit: run the script again.
// Words and checks are the 2D app's, character for character; the 3D fields are in hvpg.ts.
// content hash ${hash}

export const HVPG_COPIED = ${json} as const;

export const HVPG_COPIED_HASH = '${hash}';
`;
}

async function main() {
  const args = process.argv.slice(2);
  const at = args.indexOf('--from');
  if (at < 0 || !args[at + 1]) { console.error('usage: node scripts/copy-decks.mjs --from <2D checkout> [--check]'); process.exit(2); }
  const file = resolve(args[at + 1], 'src/ui/decks/hvpg.js');
  const { HVPG } = await import(pathToFileURL(file).href);
  let commit = 'unknown';
  try { commit = execFileSync('git', ['-C', resolve(args[at + 1]), 'rev-parse', '--short=10', 'HEAD'], { encoding: 'utf8' }).trim(); } catch { /* not a git checkout */ }
  const text = render(extract(HVPG), `src/ui/decks/hvpg.js of qaddodi/portal-pressure-simulator at ${commit}`);
  if (args.includes('--check')) {
    // compare the words, not the commit line (a 2D checkout on another commit with the same words is fine)
    const body = (t) => t.split('\n').filter((l) => !l.startsWith('// @generated')).join('\n');
    const now = readFileSync(OUT, 'utf8');
    if (body(now) !== body(text)) { console.error('src/decks/hvpg.copied.ts differs from the 2D deck: run scripts/copy-decks.mjs again'); process.exit(1); }
    console.log('hvpg.copied.ts matches the 2D deck');
    return;
  }
  writeFileSync(OUT, text);
  console.log(`wrote ${OUT}`);
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) await main();
