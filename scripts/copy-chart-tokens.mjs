#!/usr/bin/env node
// Copies the chart colour tokens of the 2D app (src/ui/theme-tokens.js, the table its charts read) into src/ui/charts/tokens.generated.ts, so a
// chart in 3D wears the same colours as the same chart in 2D and no colour is typed by hand.
//
//   node scripts/copy-chart-tokens.mjs --from <2D checkout> [--check]
//
// Each look's tokens are stacked as the 2D app stacks them (light, then soft/dark, then navy/black on dark), `var(--x)` chains are resolved,
// and every value that is a colour is written as [r, g, b, a] (0..1). Tokens the 3D looks table owns (surface, text, text-2, text-3, ok, caution,
// danger, accent) are overridden at run time by src/ui/charts/palette.ts, so the cards and the charts always agree; the tints that sit beside the
// surface (surface-2, surface-3, border, border-strong) are re-derived there from the 3D surface with the same mixing ratio as here
// (the `ratios` object), so a chart plot sits on a 3D card exactly as it sat on a 2D card.
// --check writes nothing and exits 1 when the file differs from what the 2D app would give.

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { execFileSync } from 'node:child_process';

const here = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(here, '../src/ui/charts/tokens.generated.ts');
const OUT_METRICS = resolve(here, '../src/ui/charts/metrics.generated.ts');
const OUT_TRIALS = resolve(here, '../src/ui/charts/trial/trials.generated.ts');
const OUT_FIT = resolve(here, '../src/ui/charts/trial/trial-fit.generated.js');
const OUT_TILES = resolve(here, '../src/ui/charts/tiles.generated.ts');
// Pure files of the 2D app copied as they are (no imports to rewrite): [2D path, 3D path].
const VERBATIM = [
  ['src/ui/reading-colours.js', '../src/ui/charts/plot/reading-colours.generated.js'],
  ['src/ui/rx-bands.js', '../src/ui/charts/plot/rx-bands.generated.js'],
];
const LOOKS = ['light', 'soft', 'dark', 'navy', 'black'];

const arg = (n) => { const i = process.argv.indexOf(n); return i > 0 ? process.argv[i + 1] : null; };
const from = arg('--from');
if (!from && process.argv[1] === fileURLToPath(import.meta.url)) { console.error('usage: node scripts/copy-chart-tokens.mjs --from <2D checkout> [--check]'); process.exit(2); }

const r4 = (v) => Math.round(v * 10000) / 10000;

/** The generated file's text for a 2D checkout. */
export async function build(two) {
  const load = (p) => import(pathToFileURL(join(two, 'src/ui', p)).href);
  const { tokensOfLook } = await load('theme-tokens.js');
  const { withVarsResolved } = await load('chart-looks/resolve.js');
  const { parseCssColor } = await load('css-color.js');
  const table = {};
  for (const id of LOOKS) {
    const t = withVarsResolved(tokensOfLook(id));
    const o = {};
    for (const n of Object.keys(t).sort()) {
      if (typeof t[n] !== 'string' || !/^(#|rgb|hsl|color|oklab|oklch|lab|lch|hwb)/.test(t[n].trim())) continue;
      const c = parseCssColor(t[n]);
      if (c) o[n] = c.map(r4);
    }
    table[id] = o;
  }
  // how far each tint sits from the surface toward the text, per look (0..1): the 3D palette re-applies it to the 3D card colour
  const ratios = {};
  for (const id of LOOKS) {
    const t = table[id], s = t.surface, x = t.text;
    ratios[id] = {};
    for (const n of ['surface-2', 'surface-3', 'border', 'border-strong']) {
      const c = t[n];
      let num = 0, den = 0;
      for (let i = 0; i < 3; i++) { num += (c[i] - s[i]) * (x[i] - s[i]); den += (x[i] - s[i]) ** 2; }
      ratios[id][n] = den ? r4(Math.max(0, Math.min(1, num / den))) : 0;
    }
  }
  let sha = 'unknown';
  try { sha = execFileSync('git', ['-C', two, 'rev-parse', '--short=10', 'HEAD'], { encoding: 'utf8' }).trim(); } catch { /* not a git checkout */ }
  return `// @generated by scripts/copy-chart-tokens.mjs from the 2D app's src/ui/theme-tokens.js at ${sha}. Do not edit; run the script again.\n`
    + `export type Rgba = readonly [number, number, number, number];\n`
    + `export const CHART_TOKENS: Record<'light' | 'soft' | 'dark' | 'navy' | 'black', Record<string, Rgba>> = ${JSON.stringify(table)};\n`
    + `export const TINT_RATIOS: Record<'light' | 'soft' | 'dark' | 'navy' | 'black', Record<'surface-2' | 'surface-3' | 'border' | 'border-strong', number>> = ${JSON.stringify(ratios)};\n`;
}

/** The tile table's words and display rules (name, unit, scale, decimals) as the charts print a live reading. */
export async function buildTiles(two) {
  const { TILE, NO_ASC } = await import(pathToFileURL(join(two, 'src/ui/table-marks.js')).href);
  const out = {};
  for (const k of Object.keys(TILE).sort()) {
    const t = TILE[k], o = {};
    for (const f of ['t', 'n', 's', 'u', 'x', 'd', 'better']) if (t[f] !== undefined) o[f] = t[f];
    out[k] = o;
  }
  let sha = 'unknown';
  try { sha = execFileSync('git', ['-C', two, 'rev-parse', '--short=10', 'HEAD'], { encoding: 'utf8' }).trim(); } catch { /* not a git checkout */ }
  return `// @generated by scripts/copy-chart-tokens.mjs from the 2D app's src/ui/table-marks.js (TILE) at ${sha}. Do not edit; run the script again.\n`
    + `export interface TileInfo { t: string; n?: string; s?: string; u: string; /** multiplier from the engine's value to the printed one */ x?: number; /** decimals printed (1 when absent) */ d?: number; /** -1: lower is better, 1: higher is better */ better?: number }\n`
    + `export const TILE: Record<string, TileInfo> = ${JSON.stringify(out)};\n`
    + `/** the ascites volume (mL) under which a patient has no fluid to tap */\nexport const NO_ASC = ${NO_ASC};\n`;
}

/** Inter's advance widths (em) for the weights the charts use: a word's width without a canvas, so the layout can be measured in a test. */
export async function buildMetrics(two) {
  const { GLYPHS } = await import(pathToFileURL(join(two, 'src/ui/glyphs-inter.js')).href);
  const out = {};
  for (const w of [400, 500, 600, 700]) {
    const o = {};
    for (const ch of Object.keys(GLYPHS[w]).sort()) o[ch] = Math.round(GLYPHS[w][ch][0] * 10000) / 10000;
    out[w] = o;
  }
  let sha = 'unknown';
  try { sha = execFileSync('git', ['-C', two, 'rev-parse', '--short=10', 'HEAD'], { encoding: 'utf8' }).trim(); } catch { /* not a git checkout */ }
  return `// @generated by scripts/copy-chart-tokens.mjs from the 2D app's src/ui/glyphs-inter.js at ${sha}. Do not edit; run the script again.\n`
    + `export const ADVANCE: Record<number, Record<string, number>> = ${JSON.stringify(out)};\n`;
}

/** The landmark trials (the 21 records of trials.js) as data, and the Baveno VIII lines they cite. */
export async function buildTrials(two) {
  const m = await import(pathToFileURL(join(two, 'src/ui/trials.js')).href);
  let sha = 'unknown';
  try { sha = execFileSync('git', ['-C', two, 'rev-parse', '--short=10', 'HEAD'], { encoding: 'utf8' }).trim(); } catch { /* not a git checkout */ }
  return `// @generated by scripts/copy-chart-tokens.mjs from the 2D app's src/ui/trials.js at ${sha}. Do not edit; run the script again.\n`
    + `export interface TrialArm { label: string; short?: string; rate: number; n?: number; events?: number; side: 'treat' | 'control' }\n`
    + `export interface TrialRatio { kind: 'HR' | 'OR' | 'RR'; est: number; lo: number; hi: number; of: string; vs?: string }\n`
    + `export interface TrialEntry { rule: string; test: string | null; value?: number; minor?: boolean; context?: boolean }\n`
    + `export interface Trial { id: string; name: string; short: string; group: 'decomp' | 'bleed' | 'ascites' | 'kidney' | 'infection' | 'he'; journal: string; year: number; firstAuthor: string; pmid: string | null; doi: string | null; n: number; setting: string; followUp: string | null; endpoint: string; better: 'lower' | 'higher'; arms: TrialArm[]; km?: boolean; effect: string | null; ratios: TrialRatio[]; bav: string[]; entry: TrialEntry[]; note: string | null; verified: string; status: 'checked' | 'unchecked'; [extra: string]: unknown }\n`
    + `export const TRIALS: Record<string, Trial> = ${JSON.stringify(m.TRIALS, null, 1)};\n`
    + `export const BAVENO_VIII: Record<string, string> = ${JSON.stringify(m.BAVENO_VIII, null, 1)};\n`;
}
/** The trial-fit rules, copied as they are with the engine imports pointed at the 3D app's pinned engine. */
export function buildFit(two) {
  let sha = 'unknown';
  try { sha = execFileSync('git', ['-C', two, 'rev-parse', '--short=10', 'HEAD'], { encoding: 'utf8' }).trim(); } catch { /* not a git checkout */ }
  const src = readFileSync(join(two, 'src/ui/trial-fit.js'), 'utf8').replace(/'\.\.\/engine\/portal\//g, "'../../../engine/hales/portal/");
  return `// @generated by scripts/copy-chart-tokens.mjs from the 2D app's src/ui/trial-fit.js at ${sha}. Do not edit; run the script again.\n// @ts-nocheck\n${src}`;
}

/** A pure 2D file as it is, under a generated header. */
export function buildVerbatim(two, rel) {
  let sha = 'unknown';
  try { sha = execFileSync('git', ['-C', two, 'rev-parse', '--short=10', 'HEAD'], { encoding: 'utf8' }).trim(); } catch { /* not a git checkout */ }
  return `// @generated by scripts/copy-chart-tokens.mjs from the 2D app's ${rel} at ${sha}. Do not edit; run the script again.\n// @ts-nocheck\n${readFileSync(join(two, rel), 'utf8')}`;
}

if (from) {
  const text = await build(resolve(from));
  const trials = await buildTrials(resolve(from));
  const fit = buildFit(resolve(from));
  const metrics = await buildMetrics(resolve(from));
  const tiles = await buildTiles(resolve(from));
  const verb = VERBATIM.map(([rel, out]) => [resolve(here, out), buildVerbatim(resolve(from), rel), out]);
  if (process.argv.includes('--check')) {
    const now = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
    const body = (t) => t.split('\n').slice(1).join('\n');
    const nowT = existsSync(OUT_TILES) ? readFileSync(OUT_TILES, 'utf8') : '';
    if (body(nowT) !== body(tiles)) { console.error('src/ui/charts/tiles.generated.ts differs from the 2D app: run node scripts/copy-chart-tokens.mjs --from <2D checkout>'); process.exit(1); }
    const nowM = existsSync(OUT_METRICS) ? readFileSync(OUT_METRICS, 'utf8') : '';
    if (body(nowM) !== body(metrics)) { console.error('src/ui/charts/metrics.generated.ts differs from the 2D app: run node scripts/copy-chart-tokens.mjs --from <2D checkout>'); process.exit(1); }
    for (const [f, t, n] of [[OUT_TRIALS, trials, 'trials.generated.ts'], [OUT_FIT, fit, 'trial-fit.generated.js'], ...verb.map(([f, t, n]) => [f, t, n])]) {
      const cur = existsSync(f) ? readFileSync(f, 'utf8') : '';
      if (body(cur) !== body(t)) { console.error(`${n} differs from the 2D app: run node scripts/copy-chart-tokens.mjs --from <2D checkout>`); process.exit(1); }
    }
    if (body(now) !== body(text)) { console.error('src/ui/charts/tokens.generated.ts differs from the 2D app: run node scripts/copy-chart-tokens.mjs --from <2D checkout>'); process.exit(1); }
    console.log('chart tokens: ok');
  } else {
    writeFileSync(OUT, text);
    writeFileSync(OUT_TILES, tiles);
    writeFileSync(OUT_METRICS, metrics);
    mkdirSync(dirname(OUT_TRIALS), { recursive: true });
    writeFileSync(OUT_TRIALS, trials);
    writeFileSync(OUT_FIT, fit);
    for (const [f, t] of verb) { mkdirSync(dirname(f), { recursive: true }); writeFileSync(f, t); }
    console.log(`wrote ${OUT}`);
  }
}
