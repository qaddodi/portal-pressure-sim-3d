#!/usr/bin/env node
// Copies the guideline path card's pure files from the 2D app (src/ui/path-algos/*.js, path-data.js, path-cards.js) into src/ui/charts/path/ as *.generated.js,
// so the algorithms (the Baveno VIII and AASLD flowcharts, their lit sets, readings and chips) are the 2D app's own, never retyped.
//
//   node scripts/copy-chart-path.mjs --from <2D checkout> [--check]
//
// Only the imports are pointed at their new places (the algorithms to ./algos/, the engine's cuts to this app's engine copy). --check writes nothing and exits 1 when a file differs.

import { readFileSync, writeFileSync, existsSync, mkdirSync, readdirSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const here = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(here, '../src/ui/charts/path');
const arg = (n) => { const i = process.argv.indexOf(n); return i > 0 ? process.argv[i + 1] : null; };
const from = arg('--from');
if (!from) { console.error('usage: node scripts/copy-chart-path.mjs --from <2D checkout> [--check]'); process.exit(2); }

let sha = 'unknown';
try { sha = execFileSync('git', ['-C', from, 'rev-parse', '--short=10', 'HEAD'], { encoding: 'utf8' }).trim(); } catch { /* not a git checkout */ }

const ui = join(from, 'src/ui');
const files = [
  ...readdirSync(join(ui, 'path-algos')).filter((f) => f.endsWith('.js')).map((f) => [`path-algos/${f}`, `algos/${f.replace(/\.js$/, '.generated.js')}`]),
  ['path-data.js', 'path-data.generated.js'],
  ['path-cards.js', 'path-cards.generated.js'],
];
const REWRITE = [
  [/'\.\/path-algos\/([\w-]+)\.js'/g, "'./algos/$1.generated.js'"],
  [/'\.\/helpers\.js'/g, "'./helpers.generated.js'"],
  [/'\.\.\/\.\.\/engine\/portal\/([\w-]+\.js)'/g, "'../../../../engine/hales/portal/$1'"],
];
const out = files.map(([rel, to]) => {
  let t = readFileSync(join(ui, rel), 'utf8');
  for (const [re, r] of REWRITE) t = t.replace(re, r);
  return [join(OUT, to), `// @generated by scripts/copy-chart-path.mjs from the 2D app's src/ui/${rel} at ${sha}. Do not edit; run the script again.\n// @ts-nocheck\n${t}`];
});

let bad = 0;
for (const [p, t] of out) {
  if (process.argv.includes('--check')) { if (!existsSync(p) || readFileSync(p, 'utf8') !== t) { console.error(`differs: ${p}`); bad++; } continue; }
  mkdirSync(dirname(p), { recursive: true });
  writeFileSync(p, t);
}
if (bad) process.exit(1);
console.log(process.argv.includes('--check') ? 'path files match the 2D app' : `wrote ${out.length} files`);
