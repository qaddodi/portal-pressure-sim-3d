#!/usr/bin/env node
// Copies the corner credit's free-spot rule from the 2D app (credit.js: CORNERS, hit, wideSpots, freeSpots): the credit is never on or touching a card, a bar or a menu; a bottom
// corner rises above whatever covers it, then the other corners are tried. Pure functions of rectangles, so they run here as they run there.
//
//   node scripts/copy-credit-spots.mjs --from <2D checkout> [--check]
//
// Writes src/ui/shell/credit-spots.copied.js. --check writes nothing and exits 1 when the copy differs.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(here, '../src/ui/shell/credit-spots.copied.js');
const arg = (n) => { const i = process.argv.indexOf(n); return i > 0 ? process.argv[i + 1] : null; };
const from = arg('--from'), check = process.argv.includes('--check');
if (!from) { console.error('usage: node scripts/copy-credit-spots.mjs --from <2D checkout> [--check]'); process.exit(2); }
const text = readFileSync(resolve(from, 'src/ui/credit.js'), 'utf8');
const a = text.indexOf('// Corners in order of preference.'), b = text.indexOf('// The last resort where no bare spot exists');
if (a < 0 || b < a) { console.error('the 2D credit.js no longer has the corner rule where this script reads it'); process.exit(1); }
const out = `// GENERATED by scripts/copy-credit-spots.mjs from the 2D app at the pin (src/ui/credit.js: CORNERS, hit, freeSpots). Do not edit; run the script again.\n// @ts-nocheck\n${text.slice(a, b).trimEnd()}\n`;
if (check) {
  let cur = ''; try { cur = readFileSync(OUT, 'utf8'); } catch { /* none */ }
  if (cur !== out) { console.error('src/ui/shell/credit-spots.copied.js differs from the 2D source: run scripts/copy-credit-spots.mjs --from <2D>'); process.exit(1); }
  console.log('credit-spots copy is current'); process.exit(0);
}
writeFileSync(OUT, out);
console.log('wrote', OUT);
