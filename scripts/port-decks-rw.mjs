#!/usr/bin/env node
// Batch B13c (decks R to W): copies the 2D app's decks, whole and verbatim, so the 3D app teaches exactly what the 2D app teaches and nothing is retyped
// (parity plan section 5: words come from the 2D source, numbers from the engine).
//
//   node scripts/port-decks-rw.mjs --from <2D checkout> [--check]
//
// Writes src/decks/rw/copied/<deck id>.ts (the deck as the 2D app's src/ui/decks/*.js has it: every slide field, in the 2D app's own order and spelling),
// src/decks/rw/copied/plate.ts (what a camera can name: regions, vessel sets, term targets, organ boxes, the Circuit's regions) and src/decks/rw/copied/all.ts (every deck at once) and src/decks/rw/copied/index.ts (the loaders, one dynamic import per
// deck so a deck's words load only when it is opened). The 3D fields (shots, hooks, the model chain) are never written here: they are DERIVED from the copied
// fields by src/decks/rw/plan.ts, so a change in 2D changes them with it.
// --check writes nothing and exits 1 when a copied file differs from what the 2D checkout gives (the unit test runs it when a 2D checkout is at hand: PPS_2D_REPO).
// Deck split of the three B13 threads is by deck id: A to G, H to P, R to W (this file's list is the R to W one; meso-rex is H to P's).
import { readFileSync, writeFileSync, existsSync, mkdirSync, readdirSync, unlinkSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { bavenoEdits } from './baveno-edits.mjs';
import { instrumentEdits } from './instrument-edits.mjs';
import { execFileSync } from 'node:child_process';
import { pathToFileURL } from 'node:url';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(here, '../src/decks/rw/copied');

/** The decks of this batch, by id, in the 2D menu's order. */
export const RW_DECK_IDS = ['sites', 'stiffness', 'varices', 'treatment', 'shunts', 'tips-doppler', 'variceal-bleed', 'two-inflows', 'recompensation', 'where-resistance', 'ten-years', 'tipping', 'same-gradient', 'two-lesions', 'tips-candidacy', 'tips-complete'];

const constName = (id) => id.toUpperCase().replace(/-/g, '_');
const fileOf = (id) => `${OUT}/${id}.ts`;

export function renderDeck(deck, source) {
  const json = instrumentEdits(bavenoEdits(JSON.stringify(deck, null, 1)));
  const hash = createHash('sha256').update(json).digest('hex').slice(0, 12);
  return `// @generated by scripts/port-decks-rw.mjs from ${source}. Do not edit: run the script again.
// The 2D deck "${deck.id}" as it is, field for field. The 3D fields are derived from it in ../plan.ts.
// content hash ${hash}
import type { CopiedDeck } from '../types.ts';

export const ${constName(deck.id)}: CopiedDeck = ${json};

export const ${constName(deck.id)}_HASH = '${hash}';
`;
}

/** The anatomy plate's names a slide's camera can use: regions, named vessel sets, term targets, organ boxes (from the organs' outlines) and the Circuit's regions. */
export function renderPlate(plate, source) {
  const line = (name, type, v) => `export const ${name}: ${type} = ${JSON.stringify(v)};\n`;
  return `// @generated by scripts/port-decks-rw.mjs from ${source}. Do not edit: run the script again.
// What a 2D slide's \`cam\` can name (src/ui/cam-frame.js): the plate's regions (decks.js REGIONS), the named vessel sets (highlight-math.js SETS), the term targets
// (presenter-words.js TARGETS: a word's station, vessels and organ), the organs' boxes (anatomy.js ORGANS, from their outlines) and the Circuit's regions
// (cam-frame.js CIRC_REGIONS). Boxes are [x0, y0, x1, y1] in the plate's world units (x 300 to 1120, y 0 to 920).
export type Box2D = readonly [number, number, number, number];
export interface Target2D { node?: string; edges?: readonly string[]; organ?: string }
${line('REGIONS_2D', 'Readonly<Record<string, Box2D>>', plate.regions)}${line('SETS_2D', 'Readonly<Record<string, readonly string[]>>', plate.sets)}${line('TARGETS_2D', 'Readonly<Record<string, Target2D>>', plate.targets)}${line('ORGAN_BOX_2D', 'Readonly<Record<string, Box2D>>', plate.organBox)}${line('CIRC_REGIONS_2D', 'Readonly<Record<string, Box2D>>', plate.circ)}`;
}

export function renderIndex(ids) {
  return `// @generated by scripts/port-decks-rw.mjs. Do not edit: run the script again.
import type { CopiedDeck } from '../types.ts';

/** The decks of batch B13c, R to W by id. A deck's words are one dynamic import, so they load only when the deck is opened (decks open instantly). */
export const RW_LOADERS: Readonly<Record<string, () => Promise<CopiedDeck>>> = {
${ids.map((id) => `  '${id}': () => import('./${id}.ts').then((m) => m.${constName(id)}),`).join('\n')}
};

export const RW_IDS: readonly string[] = ${JSON.stringify(ids)};
`;
}

/** Every deck's words together, for the places that need all of them at once (the parity claims, the tests). The page loads one at a time (index.ts). */
export function renderAll(ids) {
  return `// @generated by scripts/port-decks-rw.mjs. Do not edit: run the script again.
import type { CopiedDeck } from '../types.ts';
${ids.map((id) => `import { ${constName(id)} } from './${id}.ts';`).join('\n')}

export const DECKS: Readonly<Record<string, CopiedDeck>> = {
${ids.map((id) => `  '${id}': ${constName(id)},`).join('\n')}
};
`;
}

async function main() {
  const args = process.argv.slice(2);
  const at = args.indexOf('--from');
  const from = at >= 0 ? args[at + 1] : process.env.PPS_2D_REPO;
  if (!from || !existsSync(`${from}/src/ui/decks.js`)) { console.error('usage: node scripts/port-decks-rw.mjs --from <2D checkout> [--check]'); process.exit(2); }
  const root = resolve(from);
  let commit = 'unknown';
  try { commit = execFileSync('git', ['-C', root, 'rev-parse', '--short=10', 'HEAD'], { encoding: 'utf8' }).trim(); } catch { /* not a git checkout */ }
  const source = `src/ui/decks.js of qaddodi/portal-pressure-simulator at ${commit}`;
  await import(pathToFileURL(`${root}/tests/dom-shim.js`).href);   // (decks.js is a UI module; Node has no DOM)
  const { DECKS, REGIONS } = await import(pathToFileURL(`${root}/src/ui/decks.js`).href);
  const { SETS } = await import(pathToFileURL(`${root}/src/ui/highlight-math.js`).href);
  const { TARGETS } = await import(pathToFileURL(`${root}/src/ui/presenter-words.js`).href);
  const { ORGANS } = await import(pathToFileURL(`${root}/src/ui/anatomy.js`).href);
  const { CIRC_REGIONS } = await import(pathToFileURL(`${root}/src/ui/cam-frame.js`).href);
  // An organ's box: the numbers of its outline taken as points (the esophagus runs up out of the picture: only its seen part, y > -40, as the 2D camera reads it).
  const organBox = {};
  for (const o of ORGANS) {
    if (typeof o.d !== 'string' || o.deco) continue;
    const n = (o.d.match(/-?\d+(?:\.\d+)?/g) || []).map(Number), pts = [];
    for (let i = 0; i + 1 < n.length; i += 2) if (n[i + 1] > -40) pts.push([n[i], n[i + 1]]);
    if (!pts.length) continue;
    const xs = pts.map((p) => p[0]), ys = pts.map((p) => p[1]);
    organBox[o.id] = [Math.min(...xs), Math.min(...ys), Math.max(...xs), Math.max(...ys)];
  }
  const targets = Object.fromEntries(Object.entries(TARGETS).map(([k, t]) => [k, Object.fromEntries(['node', 'edges', 'organ'].filter((f) => t[f] !== undefined).map((f) => [f, t[f]]))]));
  const plate = { regions: REGIONS, sets: SETS, targets, organBox, circ: CIRC_REGIONS };
  const files = new Map();
  for (const id of RW_DECK_IDS) {
    const d = DECKS.find((x) => x.id === id);
    if (!d) throw new Error(`the 2D app has no deck "${id}"`);
    // (a slide is plain data; a function in one would be lost in JSON, so refuse it rather than copy half of it)
    JSON.stringify(d, (k, v) => { if (typeof v === 'function') throw new Error(`deck ${id} has a function at "${k}": the copy would drop it`); return v; });
    files.set(fileOf(id), renderDeck(d, source));
  }
  files.set(`${OUT}/plate.ts`, renderPlate(plate, source));
  files.set(`${OUT}/index.ts`, renderIndex(RW_DECK_IDS));
  files.set(`${OUT}/all.ts`, renderAll(RW_DECK_IDS));
  const body = (t) => t.split('\n').filter((l) => !l.startsWith('// @generated')).join('\n');   // (a 2D checkout on another commit with the same words is fine)
  if (args.includes('--check')) {
    let bad = 0;
    for (const [f, text] of files) { if (!existsSync(f) || body(readFileSync(f, 'utf8')) !== body(text)) { console.error(`${f} differs from the 2D deck: run scripts/port-decks-rw.mjs again`); bad++; } }
    if (bad) process.exit(1);
    console.log(`${files.size} copied files match the 2D app`);
    return;
  }
  mkdirSync(OUT, { recursive: true });
  for (const f of readdirSync(OUT)) if (!files.has(`${OUT}/${f}`)) unlinkSync(`${OUT}/${f}`);   // (a deck that left the list leaves the folder)
  for (const [f, text] of files) writeFileSync(f, text);
  console.log(`wrote ${files.size} files in ${OUT} (2D at ${commit})`);
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) await main();
