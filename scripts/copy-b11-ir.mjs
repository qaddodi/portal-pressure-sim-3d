#!/usr/bin/env node
// Copies what the Tests card's IR pane needs from the 2D app, so no number, word, script or curve is retyped (parity plan section 2).
//   src/ui/tests/ir/copied/monitor.copied.js         monitor.js: the one pressure monitor (it draws on a 2D-context-shaped drawer; ir/ctx-frame.ts records that into a chart Frame)
//   src/ui/tests/ir/copied/trace-callouts.copied.js  trace-callouts.js: a marker's drop and the line's inked boxes (the monitor's two imports)
//   src/ui/tests/ir/copied/hvpg-script.copied.js     hvpg-proc.js, its pure parts: the HVPG catheter's words, steps, abort timings, result colours and HVPG_SCRIPT (the monitor's script)
//   src/ui/tests/ir/copied/reading-scripts.copied.js tool-reading.js, its pure parts: the scripts of the PPG by IR and the PPG through a TIPS (and the EUS-PPG), the clocks and the phase
//   src/ui/tests/ir/copied/tips-parts.copied.js      ir-tips.js, its pure parts: the stents it lists, its numbers, the line under the chip, the menu's views
//   src/ui/tests/ir/copied/figure-parts.copied.js    tips-figure.js, its layout and axes: the rows of the stent and its chart, the x of a place, the axes' round tops, the words a figure prints
//   src/ui/tests/ir/copied/compare-parts.copied.js   ir-compare.js, its rows and the change a row prints (Then | Now | Change)
//   src/ui/tests/ir/copied/curves-parts.copied.js    ir-curves.js, its sweeps, words and the curve tool each sweep asks the deck's chart for (Tube vs patient)
// Usage: node scripts/copy-b11-ir.mjs --from <2D checkout> [--check]    (--check writes nothing and fails when a file would change)
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';

const args = process.argv.slice(2);
const flag = (n) => { const i = args.indexOf(n); return i >= 0 ? args[i + 1] : null; };
const from = flag('--from') ?? process.env.PPS_2D_REPO;
const check = args.includes('--check');
if (!from || !existsSync(`${from}/src/ui/monitor.js`)) { console.error('usage: copy-b11-ir.mjs --from <2D checkout>'); process.exit(2); }
let commit = 'unknown';
try { commit = execFileSync('git', ['-C', from, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim(); } catch { /* not a checkout */ }

const dir = new URL('../src/ui/tests/ir/copied/', import.meta.url);
mkdirSync(dir, { recursive: true });
const changed = [];
const put = (name, text) => {
  const url = new URL(name, dir);
  if (existsSync(url) && readFileSync(url, 'utf8') === text) return;
  changed.push(name);
  if (!check) writeFileSync(url, text);
};
const HEAD = (what) => `// GENERATED by scripts/copy-b11-ir.mjs from the 2D app at ${commit.slice(0, 8)} (${what}). Do not edit; run the script again.\n`;
const read = (p) => readFileSync(`${from}/${p}`, 'utf8');

/** Where each 2D import goes in this repo (paths from src/ui/tests/ir/copied/). */
const SHIM = '../ir-shims.js';
const MAP = {
  './util.js': SHIM, './charts.js': SHIM, './trace-gl.js': SHIM, './store.js': SHIM,
  './hvpg-clock.js': '../../copied/hvpg-clock.copied.js', './trace-room.js': '../../copied/trace-room.copied.js', './trace-tape.js': '../../copied/trace-tape.copied.js',
  './motion.js': '../../copied/motion.copied.js', './table-marks.js': '../../copied/table-marks.copied.js',
  './trace-callouts.js': './trace-callouts.copied.js', './monitor.js': './monitor.copied.js',
  './proc-anim.js': '../../../../scene/procedures/copied/proc-anim.js',
};
function rewrite(name, src) {
  return src.replace(/(from\s*|import\s*)'([^']+)'/g, (m, kw, spec) => {
    if (!spec.startsWith('.')) return m;
    const eng = /^\.\.\/engine\/(core|portal)\/(.+)$/.exec(spec);
    if (eng) return `${kw}'../../../../engine/hales/${eng[1]}/${eng[2]}'`;
    if (MAP[spec]) return `${kw}'${MAP[spec]}'`;
    throw new Error(`${name} imports '${spec}', which is not in the map (add it, or the file is not pure)`);
  });
}

put('monitor.copied.js', HEAD('monitor.js') + rewrite('monitor.js', read('src/ui/monitor.js')));
put('trace-callouts.copied.js', HEAD('trace-callouts.js') + rewrite('trace-callouts.js', read('src/ui/trace-callouts.js')));

// ── hvpg-proc.js: the pure head (words, steps, timings) and the monitor script at the foot; the pane's DOM and the figure's catheter in between are the 3D pane's own ──
{
  const src = read('src/ui/hvpg-proc.js');
  const a = src.indexOf('// A thrombosed hepatic vein (Budd');
  const a1 = src.indexOf('export function createHvpgProcedure');
  const b = src.indexOf('// ── The tracing: the one monitor (monitor.js)');
  if (a < 0 || a1 < 0 || b < 0) throw new Error('hvpg-proc.js has changed shape: the markers are gone');
  const head = `import { fmt } from '../ir-shims.js';
import { hvpgSev, HVPG_WORDS, hvBlocked, NOT_SHOWN, NOT_MEASURABLE } from '../../../../engine/hales/portal/pressure-cuts.js';
import { T, k01, ease, cruise, balloonAt, levelAt, dampAt, pressureAt } from '../../copied/hvpg-clock.copied.js';
import { drawMonitor, C, SEV_C, cell, fm1, HVPG_TEXT } from './monitor.copied.js';
import { rateOf } from '../../copied/table-marks.copied.js';
export { hvBlocked, NOT_SHOWN, NOT_MEASURABLE };
`;
  let body = src.slice(a, a1) + src.slice(b);
  body = body.replace(/^const TB = /m, 'export const TB = ').replace(/^const ABORT_MSG = /m, 'export const ABORT_MSG = ').replace(/^const STEPS = /m, 'export const STEPS = ')
    .replace(/^const sevOf = /m, 'export const sevOf = ').replace(/^const SEV_WORD = /m, 'export const SEV_WORD = ').replace(/^const sevWord = /m, 'export const sevWord = ')
    .replace(/^const ABORT_CAP = /m, 'export const ABORT_CAP = ').replace(/^const RESULT_CAP = /m, 'export const RESULT_CAP = ').replace(/^const RESULT_CLS = /m, 'export const RESULT_CLS = ')
    .replace(/^const sevOfRead = /m, 'export const sevOfRead = ').replace(/^function drawTrace\(/m, 'export function drawTrace(');
  put('hvpg-script.copied.js', HEAD('hvpg-proc.js, its pure parts') + head + body);
}

// ── tool-reading.js: everything before createReading (the DOM card), which the pane replaces ──
{
  const src = read('src/ui/tool-reading.js');
  const z = src.indexOf('export function createReading');
  if (z < 0) throw new Error('tool-reading.js has changed shape');
  let body = src.slice(0, z).replace(/^import \{ h, fmt \} from '\.\/util\.js';$/m, "import { fmt } from './util.js';")
    .replace(/^import \{ createTraceGL \} from '\.\/trace-gl\.js';\n/m, '').replace(/^import \{ drawMonitor, HVPG_TEXT, monitorTitle \} from '\.\/monitor\.js';$/m, "import { HVPG_TEXT, monitorTitle } from './monitor.js';");
  // Departure (reviewer, 24 Nov 2026): the <12 mmHg target is a target for the GRADIENT, so it is not drawn as a line on the absolute catheter-pressure axis (it read as a target for single pressures); it stands beside the PPG result tag instead.
  const TIPS_LINE = 'target: PPG_CUTS.red, targetWord: `reference <${PPG_CUTS.red}`,';
  const TIPS_RES = "lo: 'b', hi: 'a', key: 'g', word: 'PPG', sev: ppgSev";
  if (!body.includes(TIPS_LINE) || !body.includes(TIPS_RES)) throw new Error('tool-reading.js: the TIPS target line has changed shape');
  body = body.replace(TIPS_LINE, '').replace(TIPS_RES, "lo: 'b', hi: 'a', key: 'g', word: `PPG (reference <${PPG_CUTS.red})`, sev: ppgSev");
  put('reading-scripts.copied.js', HEAD('tool-reading.js, before createReading') + rewrite('tool-reading.js', body));
}

// ── ir-tips.js: the TIPS view's pure parts (the stents it lists, its three numbers, the line under the chip, the views) ──
{
  const src = read('src/ui/ir-tips.js');
  const a = src.indexOf('/** The stents the Tests view reads');
  const bm = src.indexOf('export const SUBS = ');
  const b = src.indexOf('\n', bm);
  if (a < 0 || bm < 0) throw new Error('ir-tips.js has changed shape');
  const head = `import { STENT_RANGE as RANGE } from '../../copied/table-marks.copied.js';
import { stentBand, gateKindsOf, reductionJet, lumenShown } from '../../../../engine/hales/portal/stent-geom.js';
`;
  put('tips-parts.copied.js', HEAD('ir-tips.js, its pure parts') + head + src.slice(a, b + 1));
}

// ── tips-figure.js: the layout and the axes (everything from the veins' length down to the words a figure prints; the SVG pieces and their paint stay 2D's, the 3D frame in tips-figure.ts draws the same numbers) ──
{
  const src = read('src/ui/tips-figure.js');
  const a = src.indexOf('/** How much of each vein is shown either side of the stent');
  const b = src.indexOf("// The follower's channels");
  if (a < 0 || b < 0) throw new Error('tips-figure.js has changed shape');
  const head = `import { clamp } from '../ir-shims.js';
import { STENT_SITES } from '../../../../engine/hales/portal/topology.js';
import { TRACE_N } from '../../../../engine/hales/portal/stent-trace.js';
import { TR, ten } from '../../../charts/stent/model.ts';
`;
  let body = src.slice(a, b).replace(/^const HEAD = /m, 'export const HEAD = ').replace(/^const memo = /m, 'export const memo = ')
    .replace(/^const (waistWord|mmWord|dpWord|ppgWord|usualWord) = /gm, 'export const $1 = ');
  put('figure-parts.copied.js', HEAD('tips-figure.js, its layout and axes') + head + body);
}

// ── ir-compare.js: the rows and the change a row prints ──
{
  const src = read('src/ui/ir-compare.js');
  const a = src.indexOf('export const NOTHING_PINNED');
  const b = src.indexOf('/** Returns { el, update(frame, which) }');
  if (a < 0 || b < 0) throw new Error('ir-compare.js has changed shape');
  const body = src.slice(a, b).replace(/^const DASH = /m, 'export const DASH = ').replace(/^const ROWS = /m, 'export const ROWS = ').replace(/^const num = /m, 'export const num = ');
  put('compare-parts.copied.js', HEAD('ir-compare.js, its rows and changeOf') + "import { fmt } from '../ir-shims.js';\n" + body);
}

// ── ir-curves.js: the sweeps and the curve tool each asks for ──
{
  const src = read('src/ui/ir-curves.js');
  const a = src.indexOf("export const SWEEPS");
  const b = src.indexOf('/**\n * Returns { el, update(frame, which), stop(), setActive(on) }');
  if (a < 0 || b < 0) throw new Error('ir-curves.js has changed shape');
  const body = src.slice(a, b).replace(/^const LABEL = /m, 'export const LABEL = ').replace(/^const SETTLE_MS = /m, 'export const SETTLE_MS = ');
  put('curves-parts.copied.js', HEAD('ir-curves.js, its sweeps and curveToolOf') + "import { GEOM_RANGE, BENCH_DP, WAIST_STEP } from '../../../../engine/hales/portal/stent-geom.js';\n" + body);
}

if (check) { if (changed.length) { console.error(`out of date: ${changed.join(', ')}`); process.exit(1); } console.log('src/ui/tests/ir/copied is current'); }
else console.log(changed.length ? `wrote ${changed.join(', ')}` : 'src/ui/tests/ir/copied is current');
