#!/usr/bin/env node
// Copies the 2D app's "From readings" (Work backward) whole, so no row, word, range or rule of it is retyped: only the import addresses change.
//   src/ui/readings/copied/from-readings.copied.js    from-readings.js: the four steps, the review, the scenarios, the cases to try, "Open as patient"
//   src/ui/readings/copied/inverse-remote.copied.js   inverse-remote.js: the ranking on the page and the refinement in its worker
//   src/ui/readings/copied/inverse-worker.copied.js   inverse-worker.js: the worker's entry
//   src/ui/readings/copied/fold-slide.copied.js       fold-slide.js: the transform fold every opening row uses
//   src/ui/readings/copied/yours-store.copied.js      yours-store.js: the saved "Yours" patients on this device
// Their 2D helpers (util.js h, popover, swapFade…; ease.js; motion.js; prefs.js; caught.js) are the 3D app's own small shim, src/ui/readings/dom2d.ts; the engine modules are
// the pinned copy (src/engine/hales/portal). SOURCE.json keeps a hash per written file: tests/from-readings-copy.test.ts fails a hand edit.
// Usage: node scripts/copy-from-readings.mjs --from <2D checkout> [--check]
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';

const args = process.argv.slice(2);
const flag = (n) => { const i = args.indexOf(n); return i >= 0 ? args[i + 1] : null; };
const from = flag('--from') ?? process.env.PPS_2D_REPO;
const check = args.includes('--check');
if (!from || !existsSync(`${from}/src/ui/from-readings.js`)) { console.error('usage: copy-from-readings.mjs --from <2D checkout>'); process.exit(2); }
let commit = 'unknown';
try { commit = execFileSync('git', ['-C', from, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim(); } catch { /* not a checkout */ }

const dir = new URL('../src/ui/readings/copied/', import.meta.url);
mkdirSync(dir, { recursive: true });
const sha = (t) => createHash('sha256').update(t).digest('hex').slice(0, 16);
const SHIM = '../dom2d.ts';
/** Every relative import a copied file may have, and where it points here. Anything else stops the copy. */
const MAP = {
  './util.js': SHIM, './ease.js': SHIM, './motion.js': SHIM, './prefs.js': SHIM, './caught.js': SHIM,
  './fold-slide.js': './fold-slide.copied.js', './inverse-remote.js': './inverse-remote.copied.js',
};
const FILES = ['from-readings', 'inverse-remote', 'inverse-worker', 'fold-slide', 'yours-store'];
const hashes = {}, changed = [];
for (const name of FILES) {
  const src = readFileSync(`${from}/src/ui/${name}.js`, 'utf8');
  const body = src.replace(/from '(\.\.?\/[^']+)'/g, (all, p) => {
    if (p.startsWith('../engine/portal/')) return `from '../../../engine/hales/portal/${p.slice('../engine/portal/'.length)}'`;
    if (!MAP[p]) throw new Error(`${name}.js imports ${p}, which the copy has no place for`);
    return `from '${MAP[p]}'`;
  });
  if (/import\(|new URL\(/.test(body)) throw new Error(`${name}.js now loads something by address: not copied whole`);
  const text = `// GENERATED by scripts/copy-from-readings.mjs from the 2D app (src/ui/${name}.js). Only the import addresses differ. Do not edit; run the script again.\n${body}`;
  const out = `${name}.copied.js`, url = new URL(out, dir);
  hashes[out] = sha(text);
  if (existsSync(url) && readFileSync(url, 'utf8') === text) continue;
  changed.push(out);
  if (!check) writeFileSync(url, text);
}
const srcUrl = new URL('SOURCE.json', dir);
const was = existsSync(srcUrl) ? JSON.parse(readFileSync(srcUrl, 'utf8')) : null;
if (!was || JSON.stringify(was.hashes) !== JSON.stringify(hashes)) { if (!changed.length) changed.push('SOURCE.json'); if (!check) writeFileSync(srcUrl, `${JSON.stringify({ source: `qaddodi/portal-pressure-simulator at ${commit.slice(0, 10)}`, hashes }, null, 1)}\n`); }
if (check) { if (changed.length) { console.error(`out of date: ${changed.join(', ')}`); process.exit(1); } console.log('src/ui/readings/copied is current'); }
else console.log(changed.length ? `wrote ${changed.join(', ')}` : 'src/ui/readings/copied is current');
