#!/usr/bin/env node
// Copies the pure file of the 2D app the stent pictures need, as it is, into src/ui/charts/stent/, with its two engine imports pointed at this app's engine copy:
//   src/ui/stent-waist.js (a stent's drawn waist: the lumen's radius factor along it, smoothed; where the pressure falls, as shares)  ->  stent-waist.generated.js
//
//   node scripts/copy-chart-stent.mjs --from <2D checkout> [--check]
//
// --check writes nothing and exits 1 when a file differs from what the 2D app would give.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const here = dirname(fileURLToPath(import.meta.url));
const FILES = [['src/ui/stent-waist.js', '../src/ui/charts/stent/stent-waist.generated.js']];
const REWRITE = [
  [/'\.\.\/engine\/core\/([\w-]+\.js)'/g, "'../../../engine/hales/core/$1'"],
  [/'\.\.\/engine\/portal\/([\w-]+\.js)'/g, "'../../../engine/hales/portal/$1'"],
];
const arg = (n) => { const i = process.argv.indexOf(n); return i > 0 ? process.argv[i + 1] : null; };
const from = arg('--from');
if (!from) { console.error('usage: node scripts/copy-chart-stent.mjs --from <2D checkout> [--check]'); process.exit(2); }
let sha = 'unknown';
try { sha = execFileSync('git', ['-C', from, 'rev-parse', '--short=10', 'HEAD'], { encoding: 'utf8' }).trim(); } catch { /* not a git checkout */ }
let bad = 0;
for (const [src, out] of FILES) {
  let t = readFileSync(join(from, src), 'utf8');
  for (const [re, to] of REWRITE) t = t.replace(re, to);
  const text = `// @generated by scripts/copy-chart-stent.mjs from the 2D app's ${src} at ${sha}. Do not edit; run the script again.\n// @ts-nocheck\n${t}`;
  const dest = resolve(here, out);
  if (process.argv.includes('--check')) { if (!existsSync(dest) || readFileSync(dest, 'utf8') !== text) { console.error(`${out} differs`); bad = 1; } continue; }
  writeFileSync(dest, text);
  console.log(`wrote ${out}`);
}
process.exit(bad);
