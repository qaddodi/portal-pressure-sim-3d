#!/usr/bin/env node
// Copies the 2D app's own sheet logic for the Treat card and the vessel card, so none of it is retyped (the owner's rule: 3D matches 2D 1:1, lift, no redesigns):
//   src/ui/treat/sheet-height.copied.ts  dock-sheet.js: the stops (SIZES, THUMB, TABLET) and sheetHeight(), the height a sheet is given at Half and Full
//   src/ui/treat/card-glide.copied.ts    card-glide.js whole: glideCard, glideFrames, cutFrames, rideFrames (a card's height glides by transforms and a clip, FLIP)
//   src/ui/treat/release.copied.ts       ease.js: releaseSpeed, isFlick and the SHEET_* numbers every sheet is let go by (the finger's speed, a flick, a pull far enough to close)
//   src/ui/treat/seg-glide.copied.ts     seg-glide.js whole: the one moving piece of a tab strip or segmented control (the 2D stylesheet draws it)
// Usage: node scripts/copy-treat-sheet.mjs --from <2D checkout> [--check]   (--check writes nothing and fails when a file would change)
// What is changed in the copies is listed here and nowhere else: 2D's imports of ease.js / layout-snap.js / rest-pass.js / motion.js become one shim (src/ui/treat/sheet-shim.ts),
// and seg-glide.js does not start itself on import (the Treat card starts it on its own box).
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { execFileSync } from 'node:child_process';

const args = process.argv.slice(2);
const flag = (n) => { const i = args.indexOf(n); return i >= 0 ? args[i + 1] : null; };
const from = flag('--from') ?? process.env.PPS_2D_REPO;
const check = args.includes('--check');
if (!from || !existsSync(`${from}/src/ui/dock-sheet.js`)) { console.error('usage: copy-treat-sheet.mjs --from <2D checkout>'); process.exit(2); }
let commit = 'unknown';
try { commit = execFileSync('git', ['-C', from, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim(); } catch { /* not a checkout */ }
const HEAD = (what) => `// GENERATED by scripts/copy-treat-sheet.mjs from the 2D app at ${commit.slice(0, 8)} (${what}). Do not edit; run the script again.\n// @ts-nocheck\n`;
const read = (p) => readFileSync(`${from}/${p}`, 'utf8');
const dir = new URL('../src/ui/treat/', import.meta.url);
const changed = [];
const put = (name, text) => {
  const url = new URL(name, dir);
  if (existsSync(url) && readFileSync(url, 'utf8') === text) return;
  changed.push(name);
  if (!check) writeFileSync(url, text);
};
/** The text from the first line matching `start` up to and including the first line after it matching `stop`. */
function cut(text, start, stop) {
  const lines = text.split('\n');
  const a = lines.findIndex((l) => start.test(l));
  if (a < 0) throw new Error(`no line for ${start}`);
  const b = lines.findIndex((l, i) => i >= a && stop.test(l));
  if (b < 0) throw new Error(`no line for ${stop} after ${start}`);
  return lines.slice(a, b + 1).join('\n');
}

// ── dock-sheet.js: the stops and sheetHeight ──
const dock = read('src/ui/dock-sheet.js');
const stops = /^\s*const (SIZES = \[[^\]]*\], THUMB = \[[^\]]*\], TABLET = \[[^\]]*\]);/m.exec(dock);
if (!stops) throw new Error('dock-sheet.js has no SIZES / THUMB / TABLET line any more');
const doc = cut(dock, /^\/\*\* The height a sheet is given at one of its stops/, /^export function sheetHeight/);
const fn = cut(dock, /^export function sheetHeight/, /^}/);
put('sheet-height.copied.ts', HEAD('dock-sheet.js stops and sheetHeight') + [
  `/** The stops of a sheet, as shares of the room (2D dock-sheet.js sheetBehaviour): every screen, the phone upright over the thumb dock, an upright tablet. Half is the one before the last. */`,
  [...stops[1].matchAll(/(SIZES|THUMB|TABLET) = (\[[^\]]*\])/g)].map((m) => `export const ${m[1]} = ${m[2]};`).join('\n'),
  doc.split('\n').slice(0, -1).join('\n'),
  fn.replace(/^export function sheetHeight\(\{ size, half, stops, room, area, need, page \}\)/, 'export function sheetHeight({ size, half, stops, room, area, need, page }: { size: number; half: number; stops: readonly number[]; room: number; area: number; need: number; page?: boolean })'),
  '',
].join('\n'));

// ── ease.js: the two numbers the glide uses ──
const ease = read('src/ui/ease.js');
const dSurface = /export const D_FLIP = \d+, D_SMALL = (\d+), D_SURFACE = (\d+);/.exec(ease), arrive = /export const EASE_ARRIVE = '([^']*)'/.exec(ease);
if (!dSurface || !arrive) throw new Error('ease.js has no D_SMALL / D_SURFACE / EASE_ARRIVE any more');
const consts = `const D_SMALL = ${dSurface[1]}, D_SURFACE = ${dSurface[2]}, EASE_ARRIVE = '${arrive[1]}';   // (ease.js)`;

// ── ease.js: how a sheet is let go ──
const rel = [cut(ease, /^export function releaseSpeed/, /^}/), ease.split('\n').find((l) => /^export const SHEET_FLICK_MIN = /.test(l)), cut(ease, /^export function isFlick/, /^}/)];
if (!rel[1]) throw new Error('ease.js has no SHEET_FLICK_MIN line any more');
put('release.copied.ts', HEAD('ease.js releaseSpeed, SHEET_*, isFlick') + [
  rel[0].replace('export function releaseSpeed(trail, now)', 'export function releaseSpeed(trail: [number, number][], now: number): number'),
  rel[1],
  rel[2].replace('export function isFlick(dy, speed, avg, min, far)', 'export function isFlick(dy: number, speed: number, avg: number, min: number, far: number): boolean'),
  '',
].join('\n'));

// ── card-glide.js: whole ──
const glide = read('src/ui/card-glide.js');
if (!/^import \{ D_SURFACE, EASE_ARRIVE \} from '\.\/ease\.js';$/m.test(glide)) throw new Error('card-glide.js imports changed');
put('card-glide.copied.ts', HEAD('card-glide.js') + glide.replace(/^import \{ D_SURFACE, EASE_ARRIVE \} from '\.\/ease\.js';$/m, consts));

// ── seg-glide.js: whole, not started on import ──
const seg = read('src/ui/seg-glide.js');
const imports = ["import { D_SMALL } from './ease.js';", "import { restPass } from './rest-pass.js';", "import { readBox, readMetric, readStyle } from './layout-snap.js';", "import { reduceMotionMQ } from './motion.js';"];
for (const l of imports) if (!seg.includes(l)) throw new Error(`seg-glide.js no longer has ${l}`);
const tail = /\nlet live = null;[\s\S]*$/.exec(seg);
if (!tail || !/glideNow/.test(tail[0])) throw new Error('seg-glide.js tail changed');
let segOut = seg.slice(0, tail.index);
segOut = segOut.replace(imports.join('\n'), "import { D_SMALL, restPass, readBox, readMetric, readStyle, reduceMotionMQ } from './sheet-shim.ts';");
put('seg-glide.copied.ts', HEAD('seg-glide.js') + segOut + `
let live = null;
/** Places a control's piece now, in the caller's task, right after it changed its buttons (2D seg-glide.js glideNow). */
export function glideNow(ctl) { if (ctl) live?.now(ctl); }
/** Starts the glide on \`root\` (2D starts it on the whole body when the module loads; the 3D card starts it on its own box). Returns the stopper. */
export function startSegGlideOn(root) { live?.stop(); live = startSegGlide(root); return () => { live?.stop(); live = null; }; }
`);

if (check) { if (changed.length) { console.error(`out of date: ${changed.join(', ')} (run scripts/copy-treat-sheet.mjs)`); process.exit(1); } console.log('copy-treat-sheet: up to date'); }
else console.log(changed.length ? `wrote ${changed.join(', ')}` : 'nothing changed');
