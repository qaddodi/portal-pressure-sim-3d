#!/usr/bin/env node
// Batch B13a: copies the 14 decks A to G (by deck id) of the 2D app, word for word and field for field, and the numbers the engine gives for every slide.
//
//   node scripts/copy-decks-ag.mjs --from <2D checkout> [--check] [--no-numbers]
//
// Writes src/decks/ag/<id>.copied.ts (the deck exactly as the 2D app's src/ui/decks/*.js holds it: every slide field, so the model's steps, the
// data card's tiles and tools, the lens, the camera and the words all come from the one source and nothing is retyped), and
// tests/fixtures/deck-numbers-ag.json (per slide: the engine's fingerprint at that slide as the presenter computes it, and every {brace} value of its
// words as the 2D app prints it). --check writes nothing and exits 1 when what is on disk differs from what the 2D checkout gives (the numbers too,
// unless --no-numbers). The 3D fields (shot, needs) are DERIVED from these files in src/decks/ag/plate.ts, never typed.
import { writeFileSync, readFileSync, mkdirSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { pathToFileURL, fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';
import { execFileSync } from 'node:child_process';

const here = dirname(fileURLToPath(import.meta.url));
const OUT_DIR = resolve(here, '../src/decks/ag');
const NUMBERS = resolve(here, '../tests/fixtures/deck-numbers-ag.json');
const REGIONS_OUT = resolve(here, '../src/decks/ag/regions.generated.ts');

/** Decks A to G, by deck id (the three threads split the 42 decks by id: A to G, H to P, R to W). */
export const AG_IDS = ['albumin', 'ascites', 'budd-chiari', 'carvedilol', 'cause-treated', 'choose-treatment', 'circuit', 'circulation', 'day', 'doppler', 'encephalopathy', 'endoscopy', 'gastric-varices', 'gradients'];

export const constName = (id) => id.toUpperCase().replace(/-/g, '_');

/** Deck fields the 3D app keeps. (`topic`, `short` and `head` are added by decks.js from TOPICS, so they are the menu's words.) */
const DECK_FIELDS = ['id', 'level', 'title', 'minutes', 'summary', 'objectives', 'checks', 'sections', 'topic', 'short', 'head', 'keepPinch', 'zoomTiles'];

/** The brace tokens of a string: {pv}, {pv:0}, {co@terli}, {6 to 8 g}, {>=10 mmHg}, {#2}. */
export const braceTokens = (s) => [...String(s ?? '').matchAll(/\{([^}]+)\}/g)].map((m) => m[1]);

export function extractDeck(deck) {
  const out = {};
  for (const f of DECK_FIELDS) if (deck[f] !== undefined) out[f] = deck[f];
  out.slides = deck.slides.map((s) => JSON.parse(JSON.stringify(s)));   // (slides are plain data: no functions, no cycles; the round trip proves it)
  return out;
}

export function render(deck, source) {
  const json = JSON.stringify(extractDeck(deck), null, 1);
  const hash = createHash('sha256').update(json).digest('hex').slice(0, 12);
  return `// @generated by scripts/copy-decks-ag.mjs from ${source}. Do not edit: run the script again.
// The deck as the 2D app holds it, character for character (every slide field; the 3D fields are derived in plate.ts).
// content hash ${hash}
import type { CopiedDeck } from './types.ts';

export const ${constName(deck.id)}: CopiedDeck = ${json};

export const ${constName(deck.id)}_HASH = '${hash}';
`;
}

/** Every string of a slide where {tokens} may stand: its words, its tool and tile words, and the deck's checks. */
function wordsOf(deck) {
  const out = [];
  const walk = (v, at) => { if (typeof v === 'string') out.push([at, v]); else if (Array.isArray(v)) v.forEach((x, i) => walk(x, `${at}[${i}]`)); else if (v && typeof v === 'object') for (const [k, x] of Object.entries(v)) walk(x, `${at}.${k}`); };
  deck.slides.forEach((s) => walk(s, s.id));
  deck.checks?.forEach((c, i) => walk(c, `check ${i + 1}`));
  return out;
}

async function numbersOf(twoD, decks) {
  const { deckStates, changes } = await import(pathToFileURL(resolve(twoD, 'tests/deck-states.js')).href);
  const { valueText } = await import(pathToFileURL(resolve(twoD, 'src/ui/callout-math.js')).href);
  const { TILE } = await import(pathToFileURL(resolve(twoD, 'src/ui/table-marks.js')).href);
  const out = {};
  for (const d of decks) {
    const fps = await deckStates(d);   // slide i's state: its own, or the last before it that changed the model (the presenter's rule)
    const at = (id) => { const i = d.slides.findIndex((x) => x.id === id); return i < 0 ? null : fps[i]; };
    // keep the fingerprint keys a slide can show (its tiles and keys, its {tokens}) and the headline readings, so the fixture stays small
    const keep = new Set(['pv', 'whvp', 'fhvp', 'hvpg', 'ppg', 'ivc', 'ra', 'map', 'co', 'sbp', 'dbp']);
    for (const s of d.slides) for (const k of [...(s.tiles || []), ...(s.key || []), ...(s.cols || [])]) if (typeof k === 'string') keep.add(k);
    for (const [, text] of wordsOf(d)) for (const t of braceTokens(text)) { const m = /^(\w+)(?::0|@[\w-]+)?$/.exec(t); if (m && TILE[m[1]]) keep.add(m[1]); }
    const slim = (fp) => Object.fromEntries(Object.entries(fp || {}).filter(([k]) => keep.has(k)));
    const slides = d.slides.map((s, i) => ({ id: s.id, models: !!changes(s) || i === 0, fp: slim(fps[i]) }));
    const tokens = [];
    for (const [where, text] of wordsOf(d)) {
      const slideId = where.startsWith('check') ? null : where.split(/[.[]/)[0];
      const i = slideId === null ? d.slides.length - 1 : d.slides.findIndex((x) => x.id === slideId);
      for (const t of braceTokens(text)) {
        let m, key = null, fp = null, whole = false, kind = 'literal', shown = null;
        if (/^#\d+$/.test(t)) kind = 'step';
        else if (TILE[t]) { kind = 'tile'; key = t; fp = fps[i]; }
        else if ((m = /^(\w+):0$/.exec(t)) && TILE[m[1]]) { kind = 'tile'; key = m[1]; fp = fps[i]; whole = true; }
        else if ((m = /^(\w+)@([\w-]+)$/.exec(t)) && TILE[m[1]]) { kind = 'tile-at'; key = m[1]; fp = at(m[2]); }
        else if (/^[<>≥≤]=?/.test(t)) kind = 'cutoff';
        if (key) shown = fp && Number.isFinite(fp[key]) ? valueText(key, fp, whole) : null;
        tokens.push({ where, token: t, kind, key, whole, shown });
      }
    }
    out[d.id] = { slides, tokens };
  }
  return out;
}

/** The 2D app's named camera regions (decks.js REGIONS: the anatomy plate, world units) and the Circuit view's (cam-frame.js CIRC_REGIONS: circuit units). */
async function regionsText(twoD, commit) {
  const { REGIONS } = await import(pathToFileURL(resolve(twoD, 'src/ui/decks.js')).href);
  const { CIRC_REGIONS } = await import(pathToFileURL(resolve(twoD, 'src/ui/cam-frame.js')).href);
  return `// @generated by scripts/copy-decks-ag.mjs from src/ui/decks.js (REGIONS) and src/ui/cam-frame.js (CIRC_REGIONS) of qaddodi/portal-pressure-simulator at ${commit}. Do not edit: run the script again.
// A slide's \`cam\` names one of these (boxes [x0, y0, x1, y1] in the 2D figure's own world units; the circuit's in circuit units).
export const REGIONS_2D: Record<string, readonly [number, number, number, number]> = ${JSON.stringify(REGIONS)};
export const CIRC_REGIONS_2D: Record<string, readonly [number, number, number, number]> = ${JSON.stringify(CIRC_REGIONS)};
`;
}

async function main() {
  const args = process.argv.slice(2);
  const at = args.indexOf('--from');
  if (at < 0 || !args[at + 1]) { console.error('usage: node scripts/copy-decks-ag.mjs --from <2D checkout> [--check] [--no-numbers]'); process.exit(2); }
  const twoD = resolve(args[at + 1]);
  const { DECKS } = await import(pathToFileURL(resolve(twoD, 'src/ui/decks.js')).href);
  let commit = 'unknown';
  try { commit = execFileSync('git', ['-C', twoD, 'rev-parse', '--short=10', 'HEAD'], { encoding: 'utf8' }).trim(); } catch { /* not a git checkout */ }
  const decks = AG_IDS.map((id) => { const d = DECKS.find((x) => x.id === id); if (!d) throw new Error(`the 2D app has no deck "${id}"`); return d; });
  const check = args.includes('--check');
  const body = (t) => t.split('\n').filter((l) => !l.startsWith('// @generated')).join('\n');
  let differs = 0;
  mkdirSync(OUT_DIR, { recursive: true });
  for (const d of decks) {
    const file = resolve(OUT_DIR, `${d.id}.copied.ts`);
    const text = render(d, `src/ui/decks/ of qaddodi/portal-pressure-simulator at ${commit}`);
    if (check) { if (!existsSync(file) || body(readFileSync(file, 'utf8')) !== body(text)) { console.error(`${d.id}.copied.ts differs from the 2D deck`); differs++; } }
    else writeFileSync(file, text);
  }
  {
    const text = await regionsText(twoD, commit);
    if (check) { if (!existsSync(REGIONS_OUT) || body(readFileSync(REGIONS_OUT, 'utf8')) !== body(text)) { console.error('regions.generated.ts differs from the 2D regions'); differs++; } }
    else writeFileSync(REGIONS_OUT, text);
  }
  if (!args.includes('--no-numbers')) {
    const nums = await numbersOf(twoD, decks);
    const text = JSON.stringify({ from: `qaddodi/portal-pressure-simulator ${commit}`, decks: nums }, null, 1) + '\n';
    const strip = (t) => JSON.stringify(JSON.parse(t).decks);
    if (check) { if (!existsSync(NUMBERS) || strip(readFileSync(NUMBERS, 'utf8')) !== strip(text)) { console.error('deck-numbers-ag.json differs from the engine\'s numbers'); differs++; } }
    else writeFileSync(NUMBERS, text);
  }
  if (check) { if (differs) process.exit(1); console.log('decks A to G match the 2D app'); return; }
  console.log(`wrote ${decks.length} decks (${decks.reduce((n, d) => n + d.slides.length, 0)} slides) from 2D ${commit}`);
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) await main();
