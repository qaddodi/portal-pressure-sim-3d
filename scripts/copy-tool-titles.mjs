#!/usr/bin/env node
// Copies the 2D data card's heading words (and title-units.js, which sets a unit in a title apart): the names of the vessels an instrument's title uses and the title of each built-in instrument (presenter-tools.js VESSEL, TITLE), and the short
// forms a phone's card takes (presenter-question.js SHORT_TITLE), line for line. The titles of the chart kinds a deck visuals package registers (ext-charts.js ...) are ui/talk/tool-title.ts's,
// held against the 2D files by tests/data-card-head.test.ts.
//
//   node scripts/copy-tool-titles.mjs --from <2D checkout at the pin> [--check]
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const here = dirname(fileURLToPath(import.meta.url));
const DIR = resolve(here, '../src/ui/talk');
const arg = (n) => { const i = process.argv.indexOf(n); return i > 0 ? process.argv[i + 1] : null; };
const from = arg('--from');
if (!from) { console.error('usage: node scripts/copy-tool-titles.mjs --from <2D checkout at the pin> [--check]'); process.exit(2); }
let sha = 'b3058ef392';
try { sha = execFileSync('git', ['-C', from, 'rev-parse', '--short=10', 'HEAD'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim(); } catch { /* not a git checkout */ }
/** The text from the line holding `start` up to (not with) the line holding `end`. */
function slice(text, start, end) {
  const a = text.indexOf(start), b = text.indexOf(end, a);
  if (a < 0 || b < 0) throw new Error(`markers not found: ${start} … ${end}`);
  return text.slice(text.lastIndexOf('\n', a) + 1, text.lastIndexOf('\n', b) + 1);
}
const tools = readFileSync(join(from, 'src/ui/presenter-tools.js'), 'utf8'), question = readFileSync(join(from, 'src/ui/presenter-question.js'), 'utf8');
const text = `// @generated by scripts/copy-tool-titles.mjs from the 2D app's src/ui/presenter-tools.js and presenter-question.js at ${sha}. Do not edit; run the script again.
// @ts-nocheck (the 2D app's own code, kept as it is)
import { EDGES } from '../../engine/hales/portal/topology.js';
${slice(tools, 'const VESSEL = {', 'const noop = ')
  .replace(/^withPieces\(VESSEL\);\n/m, '')   // (registers the names with 2D's word-pieces table: not used here)
  .replace(/^const VESSEL/m, 'export const VESSEL').replace(/^const TITLE/m, 'export const TITLE')}
${slice(question, 'const SHORT_TITLE = {', '  // (A phone on its side takes the short title too').replace(/^\s*const SHORT_TITLE/, 'export const SHORT_TITLE')}`;
const units = `// @generated by scripts/copy-tool-titles.mjs from the 2D app's src/ui/title-units.js at ${sha}. Do not edit; run the script again.
// @ts-nocheck (the 2D app's own code, kept as it is)
${readFileSync(join(from, 'src/ui/title-units.js'), 'utf8')}`;
let bad = 0;
for (const [name, body] of [['tool-titles.generated.js', text], ['title-units.generated.js', units]]) {
  const out = join(DIR, name);
  if (process.argv.includes('--check')) { if (!existsSync(out) || readFileSync(out, 'utf8') !== body) { console.error(`differs: ${out}`); bad++; } continue; }
  writeFileSync(out, body);
  console.log(`wrote ${out}`);
}
process.exit(bad ? 1 : 0);
