#!/usr/bin/env node
// Copies the 2D app's scope-lens rule (src/ui/scope-lens-rule.js, mock C1: which slides get the ring on the varices, its shapes and hit test, where the lens opens, the cone) as it is
// into src/scene/disease/copied/scope-lens-rule.js, so the 3D ring and lens follow the 2D rule to the letter (a slide the 2D rule picks gets the ring here, in every deck).
//
//   node scripts/copy-scope-lens.mjs --from <2D checkout> [--check]
//
// --check writes nothing and exits 1 when the file differs from what the 2D app would give.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const here = dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2), arg = (k) => { const i = args.indexOf(k); return i >= 0 ? args[i + 1] : null; };
const from = arg('--from');
if (!from) { console.error('usage: node scripts/copy-scope-lens.mjs --from <2D checkout> [--check]'); process.exit(2); }
const src = readFileSync(resolve(from, 'src/ui/scope-lens-rule.js'), 'utf8');
let sha = 'unknown';
try { sha = execFileSync('git', ['-C', from, 'rev-parse', '--short=8', 'HEAD'], { encoding: 'utf8' }).trim(); } catch { /* not a checkout */ }
const out = `// GENERATED by scripts/copy-scope-lens.mjs from the 2D app at ${sha} (scope-lens-rule.js). Do not edit; run the script again.\n${src}`;
const to = resolve(here, '../src/scene/disease/copied/scope-lens-rule.js');
if (args.includes('--check')) {
  let cur = ''; try { cur = readFileSync(to, 'utf8'); } catch { /* none */ }
  if (cur !== out) { console.error('scope-lens-rule.copied.js differs from the 2D app'); process.exit(1); }
} else writeFileSync(to, out);
