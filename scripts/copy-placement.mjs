// Copies the APPROVED anatomy placement (Mohammad, 24 Nov 2026: "i like the mock now"; frozen round 15 of the rotatable mock) into the repo, so nothing is retyped
// (anatomy integration plan, phase 0: /mnt/project-files/anatomy-integration-plan.md):
//   art/anatomy-placement/          the frozen data as it is (placement-data.json, pack.json, organsA.json) with its checksums: the inputs the organ bake and the vessel builder read
//   src/scene/anatomy/placement.generated.ts   the vessels (courses in scene units, tones, radii, fades, joins), the gut's centrelines and the caudate lobe, typed
//   docs/approved/anatomy-placement.md          the approved sheet (his words, the rules, the intended contacts, the rejections)
// The frozen folder's SHA256SUMS are checked first: a file that is not the approved one stops the copy.
// Usage: node scripts/copy-placement.mjs [--from <frozen round folder>] [--check]    (--check writes nothing and fails when a file would change)
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const args = process.argv.slice(2);
const flag = (n) => { const i = args.indexOf(n); return i >= 0 ? args[i + 1] : null; };
const from = flag('--from') ?? '/mnt/project-files/anatomy-placement-mocks/frozen/round-16';
const check = args.includes('--check');
const ROUND = (from.match(/round-(\d+)/) ?? [])[1] ?? '?';
if (!existsSync(`${from}/placement-data.json`)) { console.error(`copy-placement: no frozen round at ${from}`); process.exit(2); }

const sha = (b) => createHash('sha256').update(b).digest('hex');
for (const line of readFileSync(`${from}/SHA256SUMS`, 'utf8').trim().split('\n')) {
  const [want, file] = line.trim().split(/\s+/);
  if (sha(readFileSync(`${from}/${file}`)) !== want) { console.error(`copy-placement: ${file} is not the frozen file (checksum)`); process.exit(1); }
}

const root = fileURLToPath(new URL('..', import.meta.url));
const changed = [];
function put(path, data) {
  const p = `${root}${path}`;
  if (existsSync(p) && Buffer.compare(readFileSync(p), Buffer.from(data)) === 0) return;
  changed.push(path);
  if (!check) { mkdirSync(dirname(p), { recursive: true }); writeFileSync(p, data); }
}

const raw = (f) => readFileSync(`${from}/${f}`);
const files = ['placement-data.json', 'pack.json', 'organsA.json'];
for (const f of files) put(`art/anatomy-placement/${f}`, raw(f));
put('art/anatomy-placement/SOURCE.json', JSON.stringify({ round: Number(ROUND), from, files: Object.fromEntries(files.map((f) => [f, sha(raw(f))])) }, null, 1) + '\n');

const D = JSON.parse(raw('placement-data.json'));
const ts = `// GENERATED by scripts/copy-placement.mjs from the frozen anatomy placement, round ${ROUND} (approved by Mohammad, 24 Nov 2026). Do not edit; run the script again.
// Units: ${D.units}
// VESSELS: each whole vessel's course (x, y, z) in flow order, as the approved mock draws it ('A'), and its tone, radius and free-end fades. JOINS: which end of which vessel joins which
// (vjoin). GUT: the gut's centrelines [x, y, z, r] (upper: stomach to duodenum; ileum; colon with haustra) and the small bowel's packed loops. CAUDATE: the lobe's centre and half-axes.
export type P3 = readonly [number, number, number];
export type P4 = readonly [number, number, number, number];
export interface PlacedVessel { tone: string; r: number; fade: readonly [boolean, boolean]; group?: string; label?: string; extra?: boolean; aOnly?: boolean }
export const PLACEMENT_ROUND = ${Number(ROUND)};
export const PLACED_VESSELS: Readonly<Record<string, PlacedVessel>> = ${JSON.stringify(D.vessels)};
export const PLACED_COURSES: Readonly<Record<string, readonly P3[]>> = ${JSON.stringify(D.A)};
export const TODAY_COURSES: Readonly<Record<string, readonly P3[]>> = ${JSON.stringify(D.today)};
export const PLACED_JOINS = ${JSON.stringify(D.vjoin)} as const;
export const PLACED_GUT = ${JSON.stringify(D.gut)} as const;
export const PLACED_ORGANS = ${JSON.stringify(D.organs)} as const;
export const PLACED_CAUDATE: { c: P3; ax: P3 } = ${JSON.stringify(D.caudate)};
`;
put('src/scene/anatomy/placement.generated.ts', ts);

const sheet = readFileSync(`${from}/anatomy-placement.md`, 'utf8');
put('docs/approved/anatomy-placement.md', sheet.replace(/\n?Commit this file as `docs\/approved\/anatomy-placement.md`\.?/, '') + (existsSync(`${root}art/anatomy-placement/RULINGS.md`) ? `\n${readFileSync(`${root}art/anatomy-placement/RULINGS.md`, 'utf8')}` : '') + `\n\n_Copied into the repo by \`scripts/copy-placement.mjs\` from \`${from}\` (round ${ROUND}); its data is \`art/anatomy-placement/\`._\n`);

if (check && changed.length) { console.error(`copy-placement --check: would change ${changed.join(', ')}`); process.exit(1); }
console.log(changed.length ? `copy-placement: ${check ? 'would write' : 'wrote'} ${changed.join(', ')}` : 'copy-placement: up to date');
