#!/usr/bin/env node
// Copies the stent editor's lists from the 2D app, so no row, word or control is retyped (parity plan section 2):
//   src/ui/action/stent/stent-controls.copied.ts  actions.js `stentControls(id)`: Diameter, Stenosis (+ End), Waist (+ Waist length, Ends), as the vessel card and the Tests card read them
//   src/ui/action/stent/stent-rows.copied.ts      stent-editor.js: the three tiles (EDITOR_ROWS), their words (tileWords, rowValue, splitValue) and the lumen slider's low end
//   src/ui/action/shunt-rules.copied.ts           stage-hover.js: NAMED_RULES, the names a shunt between two stations takes
// Usage: node scripts/copy-b11-stent.mjs --from <2D checkout> [--check]   (--check writes nothing and fails when a file would change)
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';

const args = process.argv.slice(2);
const flag = (n) => { const i = args.indexOf(n); return i >= 0 ? args[i + 1] : null; };
const from = flag('--from') ?? process.env.PPS_2D_REPO;
const check = args.includes('--check');
if (!from || !existsSync(`${from}/src/ui/actions.js`)) { console.error('usage: copy-b11-stent.mjs --from <2D checkout>'); process.exit(2); }
let commit = 'unknown';
try { commit = execFileSync('git', ['-C', from, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim(); } catch { /* not a checkout */ }
const HEAD = (what) => `// GENERATED by scripts/copy-b11-stent.mjs from the 2D app at ${commit.slice(0, 8)} (${what}). Do not edit; run the script again.\n// @ts-nocheck\n`;
const read = (p) => readFileSync(`${from}/${p}`, 'utf8').split('\n');
/** The lines from the first one matching `start` up to (not including) the first after it matching `stop`. */
function cut(lines, start, stop) {
  const a = lines.findIndex((l) => start.test(l));
  if (a < 0) throw new Error(`no line for ${start}`);
  const b = lines.findIndex((l, i) => i > a && stop.test(l));
  if (b < 0) throw new Error(`no line for ${stop} after ${start}`);
  return lines.slice(a, b).join('\n');
}

const dir = new URL('../src/ui/action/', import.meta.url);
mkdirSync(new URL('stent/', dir), { recursive: true });
const changed = [];
const put = (name, text) => {
  const url = new URL(name, dir);
  if (existsSync(url) && readFileSync(url, 'utf8') === text) return;
  changed.push(name);
  if (!check) writeFileSync(url, text);
};

// ── actions.js: stentControls ──
const ctl = cut(read('src/ui/actions.js'), /^const STENT_CTL = /, /^\/\*\* A stent's card holds its controls/)
  .replaceAll('store.get().params', 'currentParams()');
put('stent/stent-controls.copied.ts', HEAD('actions.js stentControls') + [
  `import { edgeById } from '../../../engine/hales/portal/topology.js';`,
  `import { GEOM_RANGE, TAPER_CM, WAIST_MAX, WAIST_STEP, endSiteOf, geomDefault, geomOf, kindOf, lumenShown, withEnd, withWaist } from '../../../engine/hales/portal/stent-geom.js';`,
  `import { currentParams, updateParams } from '../params.ts';`,
  `import { pct } from '../read.ts';`,
  `// (2D's \`store.get().params\` is the 3D app's \`currentParams()\`; its updateParams takes the same patch or edit and { label }.)`,
  ctl, '',
].join('\n'));

// ── stent-editor.js: the rows and their words ──
const rows = cut(read('src/ui/stent-editor.js'), /^\/\*\* The rows, by the controls' ids/, /^\/\/ One editor on screen at a time/);
put('stent/stent-rows.copied.ts', HEAD('stent-editor.js rows, splitValue, rowValue, tileWords') + [
  `import { stentControls } from './stent-controls.copied.ts';`,
  `import { LUMEN_STEP, lumenShown, waistShown } from '../../../engine/hales/portal/stent-geom.js';`,
  rows, `export { LUMEN, CAPTION, lumLo, mm1 };`, '',
].join('\n'));

// ── tips-vessel.js: the line of three numbers under the stent ──
const tv = read('src/ui/tips-vessel.js');
const a0 = tv.findIndex((l) => /^export const VESSEL_KEYS = \[/.test(l)), a1 = tv.findIndex((l, i) => i > a0 && /^\];/.test(l));
put('stent/vessel-keys.copied.ts', HEAD('tips-vessel.js VESSEL_KEYS') + tv.slice(a0, a1 + 1).join('\n') + '\n');

// ── stage-hover.js: the named shunts and the two rules that pick a shunt for a pair of vessels ──
// (The rules read the 2D figure's vessel table E and its node positions; here the caller hands the same things in: `edgeOf(id)`, `nodePos(node)`, `EI`.)
const hover = read('src/ui/stage-hover.js');
const named = cut(hover, /^ {2}const NAMED_RULES = \{/, /^ {2}function shuntRule\(/);
const rules = cut(hover, /^ {2}function shuntRule\(/, /^ {2}function startShunt\(/)
  .replaceAll(/^ {4}const t = easeInOut\(live\.morph\);\n/gm, '')
  .replaceAll('E[id].e.from, E[id].e.to', 'edgeOf(id).from, edgeOf(id).to')
  .replaceAll('E[id].e.from', 'edgeOf(id).from').replaceAll('E[id].e.to', 'edgeOf(id).to')
  .replaceAll(/nodePos\(([^,()]+), t\)/g, 'nodePos($1)');
if (/\bE\[|live\.|, t\)/.test(rules)) throw new Error('shuntRule still reads the 2D figure: ' + rules.match(/.*(\bE\[|live\.|, t\)).*/)?.[0]);
put('shunt-rules.copied.ts', HEAD('stage-hover.js NAMED_RULES, shuntRule, portalLinkRule') + [
  `import { EDGES, SHUNT_PORTAL, SHUNT_SYSTEMIC, SHUNT_PORTAL_VEINS, customShuntId } from '../../engine/hales/portal/topology.js';`,
  `import { procLabel } from '../../scene/procedures/copied/procedure-names.js';`,
  named.replace(/^ {2}const NAMED_RULES/, 'export const NAMED_RULES').replace(/^ {2}\};?$/m, '};'),
  `export interface ShuntRule { key: string; label: string; id?: string }`,
  `/** The rule for a shunt from vessel \`a\` (its middle at ax, ay) to vessel \`b\` (bx, by): what it would make, or null. \`edgeOf(id)\` is the vessel's topology edge, \`nodePos(node)\` where a station is (the same plane as the points), \`EI\` the edge index. */`,
  `export function makeShuntRule({ edgeOf, nodePos, EI }: { edgeOf(id: string): { from: string; to: string }; nodePos(node: string): [number, number]; EI: Record<string, number | undefined> }): (a: string, b: string, ax: number, ay: number, bx: number, by: number) => ShuntRule | null {`,
  rules.replace(/^ {2}function shuntRule\(/m, '  function shuntRule(') + '',
  `  return shuntRule;`,
  `}`, '',
].join('\n'));

// ── the shunt's words: the toasts (stage-hover.js) and the hint card's lines (main.js shuntHint), each checked to stand in the 2D source as written ──
const hoverText = hover.join('\n'), mainText = read('src/ui/main.js').join('\n');
const W = {
  none: ['No vessel on the other side of the circulation to connect this one to.', hoverText], canceled: ['Shunt canceled.', hoverText],
  tapTarget: ['Tap a glowing vein to connect it to.', mainText], clickTarget: ['Click a glowing vein to connect it to.', mainText],
  l1a: ['A portal branch to a ', mainText], l1b: ['hepatic vein', mainText], l1c: [' makes a TIPS.', mainText],
  l2a: ['A portal branch to the ', mainText], l2b: ['IVC', mainText], l2c: [' below the hepatic veins makes a DIPS.', mainText],
  l3a: ['The splenic vein to the ', mainText], l3b: ['left renal vein', mainText], l3c: [' makes a distal splenorenal shunt (DSRS).', mainText],
  tipsOnly: ['Place the TIPS', mainText], clickThe: ['Click the ', mainText], tapThe: ['Tap the ', mainText], tipsEnd: [' where the stent should end. Glowing vessels are valid targets.', mainText], esc: ['Esc cancels.', mainText],
  title: ['Make a shunt', mainText], cancel: ['Cancel', mainText],
};
for (const [k, [t, src]] of Object.entries(W)) if (!src.includes(t)) throw new Error(`shunt word '${k}' (${t}) is not in the 2D source any more`);
put('shunt-words.copied.ts', HEAD('stage-hover.js, main.js shunt hint') + `export const SHUNT_WORDS = ${JSON.stringify(Object.fromEntries(Object.entries(W).map(([k, [t]]) => [k, t])), null, 2)};\nexport const SHUNT_CREATED = (label: string): string => \`\${label} created.\`;\n`);

if (changed.length) { console.log(`${check ? 'would change' : 'wrote'}: ${changed.join(', ')}`); if (check) process.exit(1); } else console.log('src/ui/action/stent is current');
