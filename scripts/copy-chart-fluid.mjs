#!/usr/bin/env node
// Copies the pure file of the 2D app the fluid chart needs, as it is, into src/ui/charts/fluid/:
//   src/ui/lymph-day.js (the one rounding every lymph reading prints: mL a day, to the nearest 10)  ->  lymph-day.generated.js
//
//   node scripts/copy-chart-fluid.mjs --from <2D checkout> [--check]
//
// --check writes nothing and exits 1 when a file differs from what the 2D app would give.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const here = dirname(fileURLToPath(import.meta.url));
const FILES = [['src/ui/lymph-day.js', '../src/ui/charts/fluid/lymph-day.generated.js']];
const arg = (n) => { const i = process.argv.indexOf(n); return i > 0 ? process.argv[i + 1] : null; };
const from = arg('--from');
if (!from) { console.error('usage: node scripts/copy-chart-fluid.mjs --from <2D checkout> [--check]'); process.exit(2); }
let sha = 'unknown';
try { sha = execFileSync('git', ['-C', from, 'rev-parse', '--short=10', 'HEAD'], { encoding: 'utf8' }).trim(); } catch { /* not a git checkout */ }
let bad = 0;
for (const [src, out] of FILES) {
  const text = `// @generated by scripts/copy-chart-fluid.mjs from the 2D app's ${src} at ${sha}. Do not edit; run the script again.\n// @ts-nocheck\n${readFileSync(join(from, src), 'utf8')}`;
  const dest = resolve(here, out);
  if (process.argv.includes('--check')) { if (!existsSync(dest) || readFileSync(dest, 'utf8') !== text) { console.error(`${out} differs`); bad = 1; } continue; }
  writeFileSync(dest, text);
  console.log(`wrote ${out}`);
}
process.exit(bad);
