#!/usr/bin/env node
// Copies the vessel and organ card's Details face from the 2D app (src/ui/card-details.js), so its words and its numbers are not retyped (the owner's rule: 3D matches 2D 1:1).
//   src/ui/action/card-details.copied.ts   ABOUT_EDGE, STATION, ORGAN_ABOUT, ORGAN_STATS, kickerOfEdge, stationName, aboutEdge and detailsPlan(m), verbatim,
//                                           plus the three strings the face's markup says (DETAILS_WORDS: "Between", "Why this value?", the Back and region labels)
// The face's markup is Details.tsx (the 2D createCardDetails, class for class); its stylesheet is the 2D app's (src/ui/css2d, .ac-details and .ad-*).
// What is changed in the copy: 2D's `store.get().healthy` is the 3D `patient.reference`; its live-readings cells (numText, lpmText, Pof, Qof) are the three one-line helpers at the top
// (a 3D card is one component drawn when a number changes, not a hand-managed cell); everything else is the 2D text.
// Usage: node scripts/copy-card-details.mjs --from <2D checkout> [--check]
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { execFileSync } from 'node:child_process';

const args = process.argv.slice(2);
const flag = (n) => { const i = args.indexOf(n); return i >= 0 ? args[i + 1] : null; };
const from = flag('--from') ?? process.env.PPS_2D_REPO;
const check = args.includes('--check');
if (!from || !existsSync(`${from}/src/ui/card-details.js`)) { console.error('usage: copy-card-details.mjs --from <2D checkout>'); process.exit(2); }
let commit = 'unknown';
try { commit = execFileSync('git', ['-C', from, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim(); } catch { /* not a checkout */ }
const src = readFileSync(`${from}/src/ui/card-details.js`, 'utf8');
const a = src.indexOf('const EI = Object.fromEntries'), b = src.indexOf('/**\n * createCardDetails(');
if (a < 0 || b < 0) throw new Error('card-details.js has changed shape (no const EI … or no createCardDetails block)');
let body = src.slice(a, b).trimEnd();
if (!body.includes("store.get().healthy?.Q?.[k]")) throw new Error('card-details.js no longer reads store.get().healthy');
body = body.replace('store.get().healthy?.Q?.[k]', 'patient.reference?.Q?.[k]');
for (const need of ['export function detailsPlan', 'export const stationName', 'const ABOUT_EDGE', 'const ORGAN_ABOUT', 'const ORGAN_STATS', 'const kickerOfEdge', 'const STATION']) if (!body.includes(need)) throw new Error(`card-details.js has no ${need} any more`);
// the strings the markup says (createCardDetails)
const words = { between: /h\('em', \{\}, '([^']*)'\), plan\.between/.exec(src)?.[1] };
if (!words.between) throw new Error('no Between word in createCardDetails');
if (!/'Why this value\?'/.test(src)) throw new Error('no Why this value? in createCardDetails');
const out = `// GENERATED by scripts/copy-card-details.mjs from the 2D app at ${commit.slice(0, 8)} (card-details.js: the words, the stations, the numbers). Do not edit; run the script again.
// @ts-nocheck
import { EDGES, NODES, dMinOf } from '../../engine/hales/portal/topology.js';
import { wallShare } from '../../engine/hales/portal/wall-read.js';
import { patient } from '../../engine/store.ts';
import { fmt } from '../charts/fmt.ts';
import { fmtFlow, clamp } from './read.ts';

// (2D's live-readings.js words a number once per place value in a hand-managed cell; here a number is worded where it is shown, with the same fmt: tests/card-details.test.ts holds the words to 2D's.)
const newCell = () => null;
const numText = (_c, v, d, suffix) => \`\${fmt(v, d)}\${suffix}\`;
const lpmText = (_c, v) => \`\${fmtFlow(v)} L/min\`;
const Pof = (f) => f.Pf || f.P, Qof = (f) => f.Qf || f.Q;

${body}

/** The words the face's markup says (2D createCardDetails). */
export const DETAILS_WORDS = { between: ${JSON.stringify(words.between)}, why: 'Why this value?', back: (title) => \`Back to \${title}\`, region: (title) => \`\${title}: details\` };
`;
const url = new URL('../src/ui/action/card-details.copied.ts', import.meta.url);
const same = existsSync(url) && readFileSync(url, 'utf8') === out;
if (check) { if (!same) { console.error('src/ui/action/card-details.copied.ts is out of date (run scripts/copy-card-details.mjs)'); process.exit(1); } console.log('copy-card-details: up to date'); }
else { if (!same) writeFileSync(url, out); console.log(same ? 'nothing changed' : 'wrote src/ui/action/card-details.copied.ts'); }
