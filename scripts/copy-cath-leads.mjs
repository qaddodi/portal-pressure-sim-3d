#!/usr/bin/env node
// Copies the summary's leader planner from the 2D app (cath-leads.js: the order of the two rows and leaders that never cross, with seg-hits.js's segment tests),
// so the stack's leaders are the 2D app's own. Never edited by hand.
//   node scripts/copy-cath-leads.mjs --from <2D checkout> [--check]
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';
import { execFileSync } from 'node:child_process';

const here = dirname(fileURLToPath(import.meta.url));
const arg = (n) => { const i = process.argv.indexOf(n); return i > 0 ? process.argv[i + 1] : null; };
const from = arg('--from'), check = process.argv.includes('--check');
if (!from) { console.error('usage: node scripts/copy-cath-leads.mjs --from <2D checkout> [--check]'); process.exit(2); }
const sha = (() => { try { return execFileSync('git', ['-C', from, 'rev-parse', '--short=10', 'HEAD'], { encoding: 'utf8' }).trim(); } catch { return 'unknown'; } })();
const head = (f) => `// @generated by scripts/copy-cath-leads.mjs from src/ui/${f} of qaddodi/portal-pressure-simulator at ${sha}. Do not edit: run the script again.\n`;
const read = (f) => readFileSync(resolve(from, 'src/ui', f), 'utf8');
let leads = read('cath-leads.js');
const imp = "import { clamp } from './num.js';\nimport { segsCross, segHitsBox } from './seg-hits.js';";
if (!leads.includes(imp)) throw new Error('cath-leads.js no longer imports what it did: look at it');
leads = leads.replace(imp, "import { segsCross, segHitsBox } from './seg-hits.copied.js';\nconst clamp = (v, a, b) => Math.min(b, Math.max(a, v));   // (num.js clamp: that file reads the engine)");
const files = { 'cath-leads.copied.js': head('cath-leads.js') + leads, 'seg-hits.copied.js': head('seg-hits.js') + read('seg-hits.js') };
const strip = (t) => t.replace(/^\/\/ @generated.*\n/, '');
const out = (f) => resolve(here, '../src/scene/labels/cath2d', f);
if (check) {
  for (const [f, t] of Object.entries(files)) if (!existsSync(out(f)) || strip(readFileSync(out(f), 'utf8')) !== strip(t)) { console.error(`src/scene/labels/cath2d/${f} differs from the 2D app: run scripts/copy-cath-leads.mjs`); process.exit(1); }
  console.log('cath leads: same as the 2D app');
} else { for (const [f, t] of Object.entries(files)) writeFileSync(out(f), t); console.log(`wrote ${Object.keys(files).length} files (2D at ${sha})`); }
