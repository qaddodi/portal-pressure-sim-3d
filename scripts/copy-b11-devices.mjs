#!/usr/bin/env node
// Copies what the Tests scene devices need from the 2D app, so no number is retyped (parity plan section 2).
//   src/scene/devices/probes/copied/dop-probe.copied.js   the Doppler probe's geometry (dop-probe.js, whole: PROBE, gateDims, gateFrac, awayFromProbe, probeGeomInto…)
//   src/scene/devices/probes/copied/eus-scope.copied.js   the echoendoscope's route, stations and targets (eus-scope.js, whole: EUS_ROUTE, EUS_STATIONS, EUS_TARGETS, EUS_SCOPE_R…)
//   src/scene/devices/probes/copied/scan-probe.copied.js  the FibroScan probe's shapes, wave numbers, turns and place on the organ (stage-scan.js) and its two colours (tokens.css)
// Usage: node scripts/copy-b11-devices.mjs --from <2D checkout> [--check]    (--check writes nothing and fails when a file would change)
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';

const args = process.argv.slice(2);
const flag = (n) => { const i = args.indexOf(n); return i >= 0 ? args[i + 1] : null; };
const from = flag('--from') ?? process.env.PPS_2D_REPO;
const check = args.includes('--check');
if (!from || !existsSync(`${from}/src/ui/dop-probe.js`)) { console.error('usage: copy-b11-devices.mjs --from <2D checkout>'); process.exit(2); }
let commit = 'unknown';
try { commit = execFileSync('git', ['-C', from, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim(); } catch { /* not a checkout */ }

const dir = new URL('../src/scene/devices/probes/copied/', import.meta.url);
mkdirSync(dir, { recursive: true });
const changed = [];
const put = (name, text) => {
  const url = new URL(name, dir);
  if (existsSync(url) && readFileSync(url, 'utf8') === text) return;
  changed.push(name);
  if (!check) writeFileSync(url, text);
};
const HEAD = (what) => `// GENERATED by scripts/copy-b11-devices.mjs from the 2D app at ${commit.slice(0, 8)} (${what}). Do not edit; run the script again.\n`;
const read = (p) => readFileSync(`${from}/${p}`, 'utf8');
const MOTION = '../../../../ui/tests/copied/motion.copied.js';

/** A whole 2D file; its one import (motion.js) points at this repo's copy of it. */
function whole(name, file) {
  const src = read(`src/ui/${file}`).replace(/(from\s*)'\.\/motion\.js'/g, `$1'${MOTION}'`);
  const left = [...src.matchAll(/^import .*from\s*'(\.[^']*)'/gm)].filter((m) => m[1] !== MOTION);
  if (left.length) throw new Error(`${file} imports ${left.map((m) => m[1]).join(', ')}, which is not copied (the file is not pure)`);
  put(name, HEAD(file) + src);
}
whole('dop-probe.copied.js', 'dop-probe.js');
whole('eus-scope.copied.js', 'eus-scope.js');

// ── stage-scan.js: the FibroScan probe's numbers (they sit inside the stage's closure, so they are read out of its text) ──
const scan = read('src/ui/stage-scan.js');
const grab = (re, what) => { const m = re.exec(scan); if (!m) throw new Error(`stage-scan.js has no ${what}`); return m; };
const nums = (s) => s.split(',').map((x) => Number(x.trim()));
const consts = grab(/const SCAN_EDGE = (\d+), SCAN_TIP = \[([^\]]+)\], SCAN_SPAN = (\d+), SCAN_EVERY = 1 \/ (\d+), SCAN_N = (\d+), SCAN_HALF = ([\d.]+), SCAN_GAP = (\d+);/, 'SCAN_ constants');
const box = (cls) => nums(grab(new RegExp(`box\\('${cls}', ([^)]+)\\)`), `${cls} box`)[1]);   // x, y, w, h, rx (in the probe's own 220 x 96 frame)
const cable = grab(/class="sp-cable" d="([^"]+)"/, 'cable')[1];
const at = grab(/if \(spl\) \{ SCAN_AT\.tx = l \+ \(r - l\) \* ([\d.]+); SCAN_AT\.y = t \+ \(b - t\) \* ([\d.]+); \} else \{ SCAN_AT\.tx = l \+ \(r - l\) \* ([\d.]+); SCAN_AT\.y = t \+ \(b - t\) \* ([\d.]+); \}/, 'the probe\'s place on the organ');
const speed = grab(/const scanSpeed = \(\) => (\d+) \* \(clamp\(scanKpa\(\) \?\? (\d+), (\d+), (\d+)\) \/ (\d+)\) \*\* ([\d.]+);/, 'scanSpeed');
const deg = grab(/let deg = (\d+);/, 'the probe\'s turn');
const turn = grab(/const turn = scanR\(\) \? (\d+) - deg : deg;/, 'the spleen\'s turn');
const tokens = read('styles/tokens.css');
const col = (n) => { const m = new RegExp(`--${n}:\\s*(#[0-9a-fA-F]{6})`).exec(tokens); if (!m) throw new Error(`tokens.css has no --${n}`); return m[1]; };
put('scan-probe.copied.js', HEAD('stage-scan.js, styles/tokens.css') + `// The FibroScan probe (screen furniture in 2D, in a 220 x 96 px frame whose tip is TIP): its shapes (x, y, width, height, radius), the shear wave's arc and pace, the turn at each organ and where on the organ's box
// the tip stands (the fractions of the box from its left and its top), and the two map colours.
export const SCAN = {
  EDGE: ${consts[1]}, TIP: [${consts[2]}], SPAN: ${consts[3]}, EVERY: 1 / ${consts[4]}, N: ${consts[5]}, HALF: ${consts[6]}, GAP: ${consts[7]},
  BODY: [${box('sp-body')}], PAD: [${box('sp-tip')}], SCREEN: [${box('sp-screen')}], CABLE: '${cable}',
  AT: { liver: [${at[3]}, ${at[4]}], spleen: [${at[1]}, ${at[2]}] },
  TURN: { liver: ${deg[1]}, spleen: ${turn[1]} - ${deg[1]} },
  SPEED: { base: ${speed[1]}, ref: ${speed[5]}, lo: ${speed[3]}, hi: ${speed[4]}, pow: ${speed[6]}, dflt: ${speed[2]} },
  COLOUR: { liver: '${col('fibroscan')}', spleen: '${col('fibroscan-spleen')}' },
};
`);

if (changed.length) console.log(`${check ? 'would change' : 'wrote'}: ${changed.join(', ')}`);
else console.log('src/scene/devices/probes/copied is current');
process.exit(check && changed.length ? 1 : 0);
