#!/usr/bin/env node
// Copies the procedure modules of the 2D app that carry its choreography, its routes and its stent rules, so nothing is retyped (parity plan section 5: words and
// numbers come from the 2D source). Each file is copied whole, only its import lines rewritten to this repo's engine copy and to the small shims beside it:
//   proc-anim.js        the procedure table: steps and words, the timeline `procFrame(kind, t)` (catheter, balloon, needle, wire, column, coil), Treat checks (`can`, `apply`, `undo`)
//   hvpg-clock.js       the one timing table (travel speed, balloon times, route lengths) and the HVPG's own sequence
//   proc-routes.js      the routes TIPS, BRTO and BATO travel, laid on the vessels' courses
//   part-names.js, procedure-names.js, cath-arrival.js (where a catheter step ends), hvpg-balloon.js (the balloon fitted in the vein)
//   balloon-eso.js, balloon-gas.js   the tamponade tube and its two balloons (fitted to the stomach and the oesophagus as drawn)
//   band-ring.js, band-ease.js        the ligation bands on the oesophagus
//   stent-mesh.js, stent-waist.js     the stent device (bare stretch, graft, gold band) and the waist's words
//   surgical-shunts.js                the Treat table of the five surgical shunts
//   ease.js, num.js                   the curves and `lerp`
//   anatomy.copied.js   the two outlines the tamponade tube is fitted to (stomach, the oesophagus and stomach seam), read from anatomy.js
// Usage: node scripts/copy-b5-data.mjs --from <2D checkout> [--check]    (--check writes nothing and fails when a file would change)
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { pathToFileURL } from 'node:url';

const args = process.argv.slice(2);
const flag = (n) => { const i = args.indexOf(n); return i >= 0 ? args[i + 1] : null; };
const from = flag('--from') ?? process.env.PPS_2D_REPO;
const check = args.includes('--check');
if (!from || !existsSync(`${from}/src/ui/proc-anim.js`)) { console.error('usage: copy-b5-data.mjs --from <2D checkout>'); process.exit(2); }
const out = (p) => new URL(`../${p}`, import.meta.url);
let commit = 'unknown';
try { commit = execFileSync('git', ['-C', from, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim(); } catch { /* not a checkout */ }
const changed = [];
function put(path, text) {
  const url = out(path);
  if (existsSync(url) && readFileSync(url, 'utf8') === text) return;
  changed.push(path);
  if (!check) { mkdirSync(new URL('.', url), { recursive: true }); writeFileSync(url, text); }
}
const HEAD = (file) => `// GENERATED by scripts/copy-b5-data.mjs from the 2D app at ${commit.slice(0, 8)} (src/ui/${file}). Do not edit; run the script again.\n`;

const FILES = ['proc-anim.js', 'hvpg-clock.js', 'proc-routes.js', 'part-names.js', 'procedure-names.js', 'cath-arrival.js', 'hvpg-balloon.js', 'balloon-eso.js', 'balloon-gas.js',
  'band-ring.js', 'band-ease.js', 'stent-mesh.js', 'stent-waist.js', 'surgical-shunts.js', 'ease.js', 'num.js'];
// the 2D modules this repo does not carry whole are answered by shims.js (frame clock, motion helpers, path flattening)
const SHIMMED = new Set(['frame.js', 'motion.js', 'shape-gl.js']);
const SAME = new Set([...FILES, 'anatomy.js'].map((f) => f));
function rewrite(file, text) {
  return text.replace(/^((?:import|export)\s[^;]*?from\s+)'([^']+)'/gm, (m, pre, spec) => {
    const base = spec.replace(/^\.\//, '');
    if (spec.startsWith('../engine/portal/')) return `${pre}'../../../engine/hales/portal/${spec.slice('../engine/portal/'.length)}'`;
    if (spec.startsWith('../engine/core/')) return `${pre}'../../../engine/hales/core/${spec.slice('../engine/core/'.length)}'`;
    if (SHIMMED.has(base)) return `${pre}'./shims.js'`;
    if (base === 'anatomy.js') return `${pre}'./anatomy.copied.js'`;
    if (spec.startsWith('./') && SAME.has(base)) return m;
    throw new Error(`${file}: an import this script does not know how to carry: ${spec}`);
  });
}
// ease.js and num.js are written once, by copy-chart-tokens.mjs, in src/ui/charts/looks2d/; here they re-export it
const ONE = { 'ease.js': '../../../ui/charts/looks2d/ease.js', 'num.js': '../../../ui/charts/looks2d/num.js' };
for (const f of FILES) put(`src/scene/procedures/copied/${f}`, HEAD(f) + (ONE[f] ? `export * from '${ONE[f]}';\n` : rewrite(f, readFileSync(`${from}/src/ui/${f}`, 'utf8'))));

// ---------- the outlines the tamponade tube is fitted to ----------
const A = await import(pathToFileURL(`${from}/src/ui/anatomy.js`).href);
const organ = (id) => { const o = A.ORGANS.find((x) => x.id === id); if (!o) throw new Error(`no organ ${id} in anatomy.js`); return o; };
put('src/scene/procedures/copied/anatomy.copied.js', `// GENERATED by scripts/copy-b5-data.mjs from the 2D app at ${commit.slice(0, 8)} (src/ui/anatomy.js ORGANS stomach and esophagus, SEAM_D). Do not edit; run the script again.
export const ORGANS = ${JSON.stringify([{ id: 'stomach', d: organ('stomach').d }, { id: 'esophagus', d: organ('esophagus').d }])};
export const SEAM_D = ${JSON.stringify(A.SEAM_D)};
`);


// ---------- the device materials, per look (--dev-* and the stent's tokens: theme-tokens.js and styles/tokens.css) ----------
const { tokensOfLook, LOOK_IDS } = await import(pathToFileURL(`${from}/src/ui/theme-tokens.js`).href);
const css = readFileSync(`${from}/styles/tokens.css`, 'utf8');
const fixedTok = (name) => { const m = new RegExp(`--${name}:\\s*([^;]+);`).exec(css); if (!m) throw new Error(`token --${name} not in styles/tokens.css`); return m[1].trim(); };
const DEV = ['dev-poly', 'dev-poly-edge', 'dev-latex', 'dev-latex-edge', 'dev-latex-a', 'dev-nylon', 'dev-steel', 'dev-platinum', 'dev-glue', 'dev-ptfe', 'dev-graft', 'dev-stent-wire', 'dev-stent-glint', 'dev-stent-gold', 'stent-metal', 'stent-marker', 'suture-thread', 'suture-edge', 'tr-wedge', 'tr-pv', 'tr-ivc', 'tr-scler', 'mon-free', 'mon-wedge', 'mon-alarm',
  // the probes' own materials: the endoscope's black polymer, its tip, face, hairline and port; the Doppler head's rim, ink line, face and glow
  'dev-scope', 'dev-scope-tip', 'dev-scope-face', 'dev-scope-edge', 'dev-port', 'dop-head-rim', 'dop-head-ink', 'dop-face', 'dop-glow'];
const dev = {};
for (const id of LOOK_IDS) {
  const t = tokensOfLook(id);
  dev[id] = Object.fromEntries(DEV.map((n) => [n.replace(/^dev-/, '').replace(/-([a-z])/g, (_, c) => c.toUpperCase()), (t[n] ?? fixedTok(n)).trim()]));
}
put('src/scene/procedures/copied/device-tokens.copied.ts', `// GENERATED by scripts/copy-b5-data.mjs from the 2D app at ${commit.slice(0, 8)} (theme-tokens.js, styles/tokens.css: the --dev-* device materials and the stent's tokens, per look). Do not edit; run the script again.
export type DeviceTokens = Record<'poly' | 'polyEdge' | 'latex' | 'latexEdge' | 'latexA' | 'nylon' | 'steel' | 'platinum' | 'glue' | 'ptfe' | 'graft' | 'stentWire' | 'stentGlint' | 'stentGold' | 'stentMetal' | 'stentMarker' | 'sutureThread' | 'sutureEdge' | 'trWedge' | 'trPv' | 'trIvc' | 'trScler' | 'monFree' | 'monWedge' | 'monAlarm' | 'scope' | 'scopeTip' | 'scopeFace' | 'scopeEdge' | 'port' | 'dopHeadRim' | 'dopHeadInk' | 'dopFace' | 'dopGlow', string>;
export const DEVICE_TOKENS: Record<'light' | 'soft' | 'dark' | 'navy' | 'black', DeviceTokens> = ${JSON.stringify(dev, null, 1).replace(/\n\s*/g, ' ')};
`);

if (check && changed.length) { console.error(`out of date (run scripts/copy-b5-data.mjs --from <2D checkout>): ${changed.join(', ')}`); process.exit(1); }
console.log(changed.length ? `wrote ${changed.join(', ')}` : 'already current');
