#!/usr/bin/env node
// Writes src/scene/disease/lumen-mask.generated.ts: where the stomach and esophagus mesh covers the screen (src/scene/disease/lumen-raster.ts), for the bleeding stream to stay inside.
// Run after the organs are re-placed (npm run bake first if the mesh changed): node scripts/gen-lumen-mask.mjs. tests/bleed-in-lumen.test.ts fails when the file and the mesh disagree.
import { readFileSync, writeFileSync } from 'node:fs';
globalThis.location = { search: '', pathname: '/', hostname: 'localhost' };
const root = new URL('../', import.meta.url);
const { organsReady, setOrganData, ORGAN_MESHES } = await import(new URL('src/scene/organs/meshes.ts', root));
const { x2d, y2d } = await import(new URL('src/scene/frame2d.ts', root));
const { rasterMask, rasterFront, FRONT_CELL, MASK_CELL, MASK_X0, MASK_Y0, MASK_W, MASK_H } = await import(new URL('src/scene/disease/lumen-raster.ts', root));
const b = readFileSync(new URL('public/anatomy/organs.bin', root));
setOrganData(b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength));
await organsReady;
const g = ORGAN_MESHES.stomach();
const rows = rasterMask(g.getAttribute('position'), g.getIndex(), x2d, y2d);
const front = rasterFront(g.getAttribute('position'), g.getIndex(), x2d, y2d);
const body = rows.map((r, i) => `  ${JSON.stringify(r)},   // y ${MASK_Y0 + i * MASK_CELL}`).join('\n');
writeFileSync(new URL('src/scene/disease/lumen-mask.generated.ts', root), `// GENERATED by scripts/gen-lumen-mask.mjs from the placed stomach mesh (organs.bin). Do not edit; run the script again.
// Rows of the stomach-and-esophagus mesh as the screen covers it: [first cell, last cell] runs, cell ${MASK_CELL} figure units, ${MASK_W} x ${MASK_H} cells from (${MASK_X0}, ${MASK_Y0}). See lumen-raster.ts.
import type { MaskRow } from './lumen-raster.ts';
export const LUMEN_MASK_ROWS: readonly MaskRow[] = [
${body}
];
// The front wall's depth (scene z) at each ${FRONT_CELL}-unit cell, two hex digits (round(z * 100) + 50; '..' where the mesh is not): the stream rides just in front of it (lumen.ts frontZ).
export const FRONT_Z_ROWS: readonly string[] = [
${front.map((r, i) => `  '${r}',   // y ${MASK_Y0 + i * FRONT_CELL}`).join('\n')}
];
`);
console.log('wrote', rows.length, 'rows');
