#!/usr/bin/env node
// Copies the 2D card gallery's specimens of the teaching card (family `teaching`), the visuals (`visual`) and the sheets and toasts (`sheet`) from src/ui/gallery/catalog.js and
// catalog-main.js into src/ui/cards/gallery/catalog.generated.ts as plain data. A teaching or visual specimen is one deck slide as the deck writes it (`visual`, `of`, `vignette`,
// `compare`, `whatIf` ...); a sheet specimen names what the 2D gallery opens (`open`: 'treat', 'toast-bad' ...). The parity claims of those cards (src/parity/b12x.ts) read it, so a
// specimen is claimed only while the 3D app has what that exact slide (or sheet) needs.
//
//   node scripts/copy-card-catalog.mjs --from <2D checkout at the pin> [--check]
//
// --check writes nothing and exits 1 when the file differs from what the 2D app would give.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { execFileSync } from 'node:child_process';

const here = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(here, '../src/ui/cards/gallery/catalog.generated.ts');
const arg = (n) => { const i = process.argv.indexOf(n); return i > 0 ? process.argv[i + 1] : null; };
const from = arg('--from');
if (!from) { console.error('usage: node scripts/copy-card-catalog.mjs --from <2D checkout at the pin> [--check]'); process.exit(2); }

let sha = 'b3058ef392';   // (the pin; a checkout with no .git, such as a `git archive`, is taken to be it)
try { sha = execFileSync('git', ['-C', from, 'rev-parse', '--short=10', 'HEAD'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim(); } catch { /* not a git checkout */ }

const FAMILIES = ['teaching', 'visual', 'sheet'];
const { CATALOG } = await import(pathToFileURL(join(from, 'src/ui/gallery/catalog.js')).href);
// (the gallery's own `carry: true` leaves the preset out so a specimen continues the one before: it is the gallery deck's builder's word, not a slide field, so it moves up to the specimen)
const rows = CATALOG.filter((e) => FAMILIES.includes(e.family)).map((e) => {
  const { carry, ...slide } = e.slide ?? {};
  return { id: e.id, family: e.family, kind: e.kind, title: e.title, ...(e.slide ? { slide } : {}), ...(carry ? { carry: true } : {}), ...(e.open ? { open: e.open } : {}), ...(e.params ? { params: e.params } : {}) };
});
const text = `// @generated by scripts/copy-card-catalog.mjs from the 2D app's src/ui/gallery/catalog.js at ${sha}. Do not edit; run the script again.
// The 2D card gallery's specimens of the teaching card, the visuals and the sheets: a slide as a 2D deck writes it, or what a sheet specimen opens (the gallery's id is the inventory's \`card:<id>\`).
export interface CardSpecimen { id: string; family: string; kind: string; title: string; slide?: Record<string, unknown>; /** the specimen continues the one before: the gallery deck gives it no patient of its own */ carry?: true; open?: string; params?: Record<string, unknown> }
export const CARD_CATALOG: readonly CardSpecimen[] = [
${rows.map((r) => `  ${JSON.stringify(r)},`).join('\n')}
];
`;
if (process.argv.includes('--check')) {
  if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== text) { console.error(`differs: ${OUT}`); process.exit(1); }
  console.log('catalog.generated.ts is current'); process.exit(0);
}
writeFileSync(OUT, text);
console.log(`wrote ${OUT} (${rows.length} specimens)`);
