#!/usr/bin/env node
// The Tests card's panes are the 2D app's own markup, styled by its stylesheets loaded whole (src/ui/css2d). One thing cannot be the same element: a 2D instrument draws on a <canvas> that is the
// child of its box (.chart-box, .hvpg-box, .fibroscan-box, .dop-box, .pt-box), and the 3D app's charts share one GPU canvas, so the box's child is a <div class="cv"> the chart is drawn into (Cv.tsx).
// This copies every 2D rule that places or dresses such a canvas, with `canvas` rewritten to `.cv` and nothing else changed, so the picture takes the same place in its box:
//   src/ui/tests/copied/cv-2d.copied.css
// Usage: node scripts/copy-b11-panes.mjs --from <2D checkout> [--check]    (--check writes nothing and fails when the file would change)
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { resolve, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { loadOrder } from './copy-2d-css.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(here, '../src/ui/tests/copied/cv-2d.copied.css');

/** A selector list cut at its top-level commas. */
export function splitTop(sel, ch = ',') {
  const out = []; let d = 0, a = 0;
  for (let i = 0; i < sel.length; i++) { const c = sel[i]; if (c === '(' || c === '[') d++; else if (c === ')' || c === ']') d--; else if (c === ch && d === 0) { out.push(sel.slice(a, i)); a = i + 1; } }
  out.push(sel.slice(a));
  return out.map((x) => x.trim()).filter(Boolean);
}
/** The rules of a stylesheet, [prelude, body] each, comments left out; an at-rule's body is its text (walk it again). */
export function rulesOf(text) {
  const rules = []; let i = 0;
  while (i < text.length) {
    if (text.startsWith('/*', i)) { const e = text.indexOf('*/', i); i = e < 0 ? text.length : e + 2; continue; }
    if (/\s/.test(text[i])) { i++; continue; }
    const b = text.indexOf('{', i), semi = text.indexOf(';', i);
    if (b < 0) break;
    if (semi >= 0 && semi < b && text[i] === '@') { i = semi + 1; continue; }   // (@import, @charset: no block)
    let d = 1, j = b + 1;
    while (j < text.length && d) { if (text.startsWith('/*', j)) { const e = text.indexOf('*/', j); j = e < 0 ? text.length : e + 2; continue; } if (text[j] === '{') d++; else if (text[j] === '}') d--; j++; }
    rules.push([text.slice(i, b).trim(), text.slice(b + 1, j - 1).trim()]);
    i = j;
  }
  return rules;
}
const GROUP = /^@(media|container|supports|layer)\b/;
const BOX = /\.(chart-box|hvpg-box|fibroscan-box|dop-box|pt-box)\b/, CANVAS = /(^|[\s>+~(,])canvas\b/, NOT_OURS = /\.pz\b|\.pz-|presenting/;
/** The canvas rules of one stylesheet, rewritten; at-rule wrappers kept. */
export function cvRules(text, file) {
  const out = [];
  for (const [sel, body] of rulesOf(text)) {
    if (sel.startsWith('@')) {
      if (!GROUP.test(sel)) continue;
      const inner = cvRules(body, file);
      if (inner.length) out.push(`${sel} {\n${inner.map((l) => `  ${l}`).join('\n')}\n}`);
      continue;
    }
    const parts = splitTop(sel).filter((p) => BOX.test(p) && CANVAS.test(p) && !NOT_OURS.test(p));
    if (parts.length) out.push(`${parts.map((p) => p.replace(/(^|[\s>+~(,])canvas\b/g, '$1.cv')).join(', ')} { ${body.replace(/\s*\/\*[\s\S]*?\*\//g, '').trim()} }   /* ${file} */`);
  }
  return out;
}

function main() {
  const args = process.argv.slice(2);
  const flag = (n) => { const i = args.indexOf(n); return i >= 0 ? args[i + 1] : null; };
  const from = flag('--from') ?? process.env.PPS_2D_REPO, check = args.includes('--check');
  if (!from || !existsSync(`${from}/index.html`)) { console.error('usage: copy-b11-panes.mjs --from <2D checkout> [--check]'); process.exit(2); }
  let commit = 'unknown';
  try { commit = execFileSync('git', ['-C', from, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim(); } catch { /* not a checkout */ }
  const lines = [];
  for (const f of loadOrder(readFileSync(`${from}/index.html`, 'utf8'))) lines.push(...cvRules(readFileSync(`${from}/styles/${f}`, 'utf8'), f));
  if (lines.length < 4) throw new Error(`only ${lines.length} canvas rules found in the 2D stylesheets`);
  const text = `/* GENERATED by scripts/copy-b11-panes.mjs from the 2D app at ${commit.slice(0, 8)} (styles/*.css: every rule for an instrument's canvas in its box, \`canvas\` rewritten to \`.cv\`, the div a 3D chart is drawn into). Do not edit; run the script again. */\n${lines.join('\n')}\n`;
  const strip = (t) => t.replace(/at [0-9a-f]{8} /, '');
  const now = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (strip(now) === strip(text)) { console.log('src/ui/tests/copied/cv-2d.copied.css is current'); return; }
  if (check) { console.error('would change: cv-2d.copied.css'); process.exit(1); }
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, text);
  console.log('wrote: cv-2d.copied.css');
}
if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) main();
