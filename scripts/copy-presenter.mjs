#!/usr/bin/env node
// Copies the 2D app's presenter logic that has no screen in it, so the 3D app's library, import and presenter's window behave exactly as the 2D app's do:
// the safe deck-file reader (deck-source.js), what an imported deck may carry (import-safety.js), the share-link reader (share-link.js) and the presenter's-window
// protocol (presenter-view.js). Each lands in src/ui/deck/from2d/ with a header and the one import line that differs rewritten; nothing else is changed.
//
//   node scripts/copy-presenter.mjs --from <2D checkout> [--check]
// --check writes nothing and exits 1 when a copy differs from the 2D file (tests/presenter-copy.test.ts runs it when a 2D checkout is at hand: P2D_CHECKOUT).

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(here, '../src/ui/deck/from2d');
export const FILES = ['import-safety.js', 'deck-source.js', 'share-link.js', 'presenter-view.js', 'table-marks.js', 'wake-lock.js'];
/** `caught` (the 2D app's counter of caught errors) is a small local file here: every error is still named by its tag, under ?perf. */
const REWRITE = [["import { caught } from './caught.js';", "import { caught } from './caught.js';"]];
/** table-marks.js reads the engine's cut-off tables: here they are the vendored copy (src/engine/hales/portal/, the same files). */
const ENGINE = [/from '\.\.\/engine\/portal\//g, "from '../../../engine/hales/portal/"];

export function render(src, name, commit) {
  let t = src;
  for (const [from, to] of REWRITE) t = t.replace(from, to);
  t = t.replace(ENGINE[0], ENGINE[1]);
  return `// @generated by scripts/copy-presenter.mjs from src/ui/${name} of qaddodi/portal-pressure-simulator at ${commit}. Do not edit: run the script again.\n// @ts-nocheck (the 2D app's own file, kept character for character)\n${t}`;
}

export function copyAll(from, check = false) {
  let commit = 'unknown';
  try { commit = execFileSync('git', ['-C', from, 'rev-parse', '--short=10', 'HEAD'], { encoding: 'utf8' }).trim(); } catch { /* not a git checkout */ }
  mkdirSync(OUT, { recursive: true });
  const bad = [];
  for (const name of FILES) {
    const out = render(readFileSync(resolve(from, 'src/ui', name), 'utf8'), name, commit);
    const file = resolve(OUT, name);
    if (check) {
      const body = (x) => x.split('\n').slice(1).join('\n');
      let now = ''; try { now = readFileSync(file, 'utf8'); } catch { /* missing */ }
      if (body(now) !== body(out)) bad.push(name);
    } else writeFileSync(file, out);
  }
  return bad;
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  const args = process.argv.slice(2), at = args.indexOf('--from');
  if (at < 0 || !args[at + 1]) { console.error('usage: node scripts/copy-presenter.mjs --from <2D checkout> [--check]'); process.exit(2); }
  const bad = copyAll(resolve(args[at + 1]), args.includes('--check'));
  if (bad.length) { console.error(`differs from the 2D app: ${bad.join(', ')}: run scripts/copy-presenter.mjs again`); process.exit(1); }
  console.log(args.includes('--check') ? 'presenter copies match the 2D app' : `wrote ${FILES.length} files to src/ui/deck/from2d/`);
}
