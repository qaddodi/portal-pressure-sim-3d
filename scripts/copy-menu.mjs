#!/usr/bin/env node
// Copies what the main menu needs from the 2D app, so no number or rule is retyped (owner, 19 Nov 2026: the 3D shell matches 2D 1:1).
//   src/ui/menu/snapshots.copied.js   2D snapshots.js: every patient's settled pressures along the path, HVPG, PPG, portal pressure and flow (the preview's curve and chips)
//   src/ui/menu/swipe.copied.js       2D swipe.js up to its wheel part: the paging rule (pageGo), the sideways-owner test (ownsSideways) and the swipe constants
// Usage: node scripts/copy-menu.mjs --from <2D checkout> [--check]    (--check writes nothing and fails when a file would change)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const args = process.argv.slice(2);
const flag = (n) => { const i = args.indexOf(n); return i >= 0 ? args[i + 1] : null; };
const from = flag('--from') ?? process.env.PPS_2D_REPO;
const check = args.includes('--check');
if (!from || !existsSync(`${from}/src/ui/menu.js`)) { console.error('usage: copy-menu.mjs --from <2D checkout> [--check]'); process.exit(2); }
let commit = 'unknown';
try { commit = execFileSync('git', ['-C', from, 'rev-parse', '--short=8', 'HEAD'], { encoding: 'utf8' }).trim(); } catch { /* not a checkout */ }
const head = (name) => `// GENERATED by scripts/copy-menu.mjs from the 2D app at ${commit} (${name}). Do not edit; run the script again.\n`;

/** swipe.js without its import and its wheel part (the wheel part reads the page between frames through rest-pass.js, which the 3D app does not have). */
export function swipeHead(src) {
  const at = src.indexOf('// A trackpad (or a wheel) works the slide');
  if (at < 0) throw new Error('swipe.js: the wheel part moved; update scripts/copy-menu.mjs');
  return src.slice(0, at).replace(/^import .*rest-pass\.js';\n\n?/m, '').trimEnd() + '\n';
}

const OUT = {
  'src/ui/menu/snapshots.copied.js': () => head('snapshots.js') + readFileSync(`${from}/src/ui/snapshots.js`, 'utf8').replace(/^\/\/ Generated by .*\n/, ''),
  'src/ui/menu/swipe.copied.js': () => head('swipe.js') + swipeHead(readFileSync(`${from}/src/ui/swipe.js`, 'utf8')),
};
let bad = 0;
for (const [file, make] of Object.entries(OUT)) {
  const want = make(), path = root + file, have = existsSync(path) ? readFileSync(path, 'utf8') : '';
  const strip = (t) => t.replace(/at [0-9a-f]+ \(/, 'at X (');
  if (check) { if (strip(have) !== strip(want)) { console.error(`${file} differs from the 2D app`); bad++; } }
  else writeFileSync(path, want);
}
if (check) { if (bad) process.exit(1); console.log('menu copies match the 2D app'); } else console.log('copied the menu files from the 2D app at ' + commit);
