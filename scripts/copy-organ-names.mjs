#!/usr/bin/env node
// Copies where an organ's name may stand from the 2D app: the organ outlines (anatomy.js ORGANS, the paths only) and organ-names.js (nameSpots: the other places
// a caption may stand on or beside its own organ, nearest its anchor first; the 2D numbers NEAR, REACH, STEP, APART, MOST), so the 3D figure names its organs
// where the 2D one does and keeps a name off the other organs. Never edited by hand.
//
//   node scripts/copy-organ-names.mjs --from <2D checkout> [--check]
//
// Writes src/scene/labels/organ2d/outlines.copied.js (ORGANS: id, d, ring) and organ-names.copied.js (organ-names.js with its two imports pointed at the copied outlines
// and at flatten.js, the 3D side's own flattening of a path of M, L, C and Z, which is what the organs' paths are made of).
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { pathToFileURL, fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';
import { execFileSync } from 'node:child_process';

const here = dirname(fileURLToPath(import.meta.url));
const arg = (n) => { const i = process.argv.indexOf(n); return i > 0 ? process.argv[i + 1] : null; };
const from = arg('--from'), check = process.argv.includes('--check');
if (!from) { console.error('usage: node scripts/copy-organ-names.mjs --from <2D checkout> [--check]'); process.exit(2); }
const src = (f) => resolve(from, f);
const out = (f) => resolve(here, '../src/scene/labels/organ2d', f);
const sha = (() => { try { return execFileSync('git', ['-C', from, 'rev-parse', '--short=10', 'HEAD'], { encoding: 'utf8' }).trim(); } catch { return 'unknown'; } })();
const head = (what) => `// @generated by scripts/copy-organ-names.mjs from ${what} of qaddodi/portal-pressure-simulator at ${sha}. Do not edit: run the script again.\n`;

const anat = await import(pathToFileURL(src('src/ui/anatomy.js')).href);
const want = new Set(['esophagus', 'heart', 'heart-ra', 'bowel', 'colon', 'kidney-l', 'spleen', 'stomach', 'liver']);
const organs = anat.ORGANS.filter((o) => want.has(o.id)).map((o) => ({ id: o.id, ...(o.ring ? { ring: o.ring } : { d: o.d }) }));
const outlines = head('src/ui/anatomy.js (ORGANS, ORGAN_LABELS)')
  + `export const ORGANS = ${JSON.stringify(organs, null, 1)};\nexport const ORGAN_LABELS = ${JSON.stringify(anat.ORGAN_LABELS)};\n`;

let names = readFileSync(src('src/ui/organ-names.js'), 'utf8');
const imports = "import { ORGANS, ORGAN_LABELS } from './anatomy.js';\nimport { flattenPath } from './shape-gl.js';";
if (!names.includes(imports)) throw new Error('organ-names.js no longer imports what it did: look at it');
names = names.replace(imports, "import { ORGANS, ORGAN_LABELS } from './outlines.copied.js';\nimport { flattenPath } from './flatten.js';");
const namesOut = head('src/ui/organ-names.js') + names;

const files = { 'outlines.copied.js': outlines, 'organ-names.copied.js': namesOut };
const strip = (t) => t.replace(/^\/\/ @generated.*\n/, '');
if (check) {
  for (const [f, t] of Object.entries(files)) if (!existsSync(out(f)) || strip(readFileSync(out(f), 'utf8')) !== strip(t)) { console.error(`src/scene/labels/organ2d/${f} differs from the 2D app: run scripts/copy-organ-names.mjs`); process.exit(1); }
  console.log('organ names: same as the 2D app');
} else {
  mkdirSync(dirname(out('x')), { recursive: true });
  for (const [f, t] of Object.entries(files)) writeFileSync(out(f), t);
  console.log(`wrote ${Object.keys(files).length} files (${organs.length} outlines, 2D at ${sha})`);
}
