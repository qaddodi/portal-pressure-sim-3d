#!/usr/bin/env node
// Copies the pure layout half of the 2D app's plane chart (src/ui/visual-plane.js: the planes a deck can name, conditions, fitAxis, the numbers and names placed on the plot,
// the cut-off lines, the diagonal, the lines of equal resistance, the points' names, the zones' words, the card's words, the trail's names) into
// src/ui/charts/plane/layout.generated.js, so the 3D plane places every word and line as the 2D plane does and nothing is retyped by hand.
//
//   node scripts/copy-chart-plane.mjs --from <2D checkout> [--check]
//
// What is copied is the text between the "// ── Conditions" marker and the "// ── Drawing ──" marker of the 2D file, word for word. Its imports are pointed at this app:
// the pressure cut-offs at the engine copy, the Baveno zones at src/ui/charts/criteria/zones.ts (the one geometry both charts share), and the three small helpers it
// asks of 2D's util.js and table-marks.js at src/ui/charts/plane/shim.ts. The drawing half (the svg tree, the dot's glide, the trail's walk) is not copied: it is the frame
// (plane/frame.ts), drawn by the shared GPU painter.
// --check writes nothing and exits 1 when the file differs from what the 2D app would give.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const here = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(here, '../src/ui/charts/plane/layout.generated.js');
const START = '// ── Conditions', END = '// ── Drawing ──';

/** The generated file's text for a 2D checkout. */
export function build(two) {
  const src = readFileSync(join(two, 'src/ui/visual-plane.js'), 'utf8');
  const a = src.indexOf(START), b = src.indexOf(END);
  if (a < 0 || b < a) throw new Error('visual-plane.js has no Conditions ... Drawing section any more: the script needs its markers updated');
  let sha = 'unknown';
  try { sha = execFileSync('git', ['-C', two, 'rev-parse', '--short=10', 'HEAD'], { encoding: 'utf8' }).trim(); } catch { /* not a git checkout */ }
  const head = [
    `// @generated by scripts/copy-chart-plane.mjs from the 2D app's src/ui/visual-plane.js (the layout half, from "${START}" to "${END}") at ${sha}. Do not edit; run the script again.`,
    '// @ts-nocheck',
    "import { HVPG_CUTS, PPG_CUTS, HVPG_WORDS } from '../../../engine/hales/portal/pressure-cuts.js';",
    "import { BAVENO, BAVENO_AXES, bavenoRects, bavenoHatch } from '../criteria/zones.ts';",
    "import { clamp, numName, tileShown } from './shim.ts';",
    '',
  ].join('\n');
  return head + src.slice(a, b).trimEnd() + '\n';
}

const arg = (n) => { const i = process.argv.indexOf(n); return i > 0 ? process.argv[i + 1] : null; };
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const from = arg('--from');
  if (!from) { console.error('usage: node scripts/copy-chart-plane.mjs --from <2D checkout> [--check]'); process.exit(2); }
  const text = build(from);
  if (process.argv.includes('--check')) {
    const same = existsSync(OUT) && readFileSync(OUT, 'utf8') === text;
    console.log(same ? 'plane layout: up to date' : 'plane layout: differs from the 2D app');
    process.exit(same ? 0 : 1);
  }
  writeFileSync(OUT, text);
  console.log(`wrote ${OUT}`);
}
