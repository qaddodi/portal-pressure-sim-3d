#!/usr/bin/env node
// Copies the 2D app's handout figures: one picture per slide, as the audience saw it (the figure with its labels and data card, or the slide's table or chart), which the printed
// speaker notes set beside the slide's words (2D handout.js; the pictures are made in the 2D repository by its scripts/handout-figures.mjs).
//   brand/handout/<deck>/<slide id>.webp  ->  public/brand/handout/<deck>/<slide id>.webp   (served as they are; never held offline: scripts/pwa.mjs leaves them out)
// and writes src/ui/deck/handout-figures.generated.ts, the list of the pictures there are, so the notes ask only for a picture that exists.
// They are the 2D app's pictures (its figure, not the 3D one) until new ones are taken of the 3D app on the Mac: docs/handouts.md.
//
//   node scripts/copy-handout.mjs --from <2D checkout> [--check]
// --check writes nothing and exits 1 when a picture or the list differs from the 2D checkout's.

import { readFileSync, writeFileSync, mkdirSync, readdirSync, existsSync, rmSync, statSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
export const OUT = resolve(here, '../public/brand/handout');
export const LIST = resolve(here, '../src/ui/deck/handout-figures.generated.ts');
const sha = (b) => createHash('sha256').update(b).digest('hex').slice(0, 12);

/** { deck: [slide id, …] } of the pictures under a brand/handout folder, both sorted. */
export function figuresIn(dir) {
  const out = {};
  if (!existsSync(dir)) return out;
  for (const deck of readdirSync(dir).sort()) {
    if (!statSync(resolve(dir, deck)).isDirectory()) continue;
    const ids = readdirSync(resolve(dir, deck)).filter((f) => f.endsWith('.webp')).map((f) => f.slice(0, -5)).sort();
    if (ids.length) out[deck] = ids;
  }
  return out;
}
/** One hash over every picture, in order: the list names it, so a changed picture shows as a changed list. */
export function hashOf(dir, figs) {
  const h = createHash('sha256');
  for (const [deck, ids] of Object.entries(figs)) for (const id of ids) h.update(`${deck}/${id}:${sha(readFileSync(resolve(dir, deck, `${id}.webp`)))}\n`);
  return h.digest('hex').slice(0, 16);
}
export function renderList(figs, commit, hash) {
  const n = Object.values(figs).reduce((a, b) => a + b.length, 0);
  return `// @generated by scripts/copy-handout.mjs from brand/handout of qaddodi/portal-pressure-simulator at ${commit}. Do not edit: run the script again.
// The slides that have a picture for the printed notes (public/brand/handout/<deck>/<slide id>.webp): ${n} pictures of ${Object.keys(figs).length} talks.
export const HANDOUT_HASH = '${hash}';
export const HANDOUT_FIGURES: Readonly<Record<string, readonly string[]>> = {
${Object.entries(figs).map(([d, ids]) => `  ${JSON.stringify(d)}: ${JSON.stringify(ids)},`).join('\n')}
};
`;
}

export function copyAll(from, check = false) {
  const src = resolve(from, 'brand/handout');
  let commit = 'unknown';
  try { commit = execFileSync('git', ['-C', from, 'rev-parse', '--short=10', 'HEAD'], { encoding: 'utf8' }).trim(); } catch { /* not a git checkout */ }
  const figs = figuresIn(src), hash = hashOf(src, figs), list = renderList(figs, commit, hash);
  if (check) {
    const bad = [];
    const mine = figuresIn(OUT);
    if (JSON.stringify(mine) !== JSON.stringify(figs)) bad.push('the pictures under public/brand/handout are not the 2D checkout\'s set');
    else if (hashOf(OUT, mine) !== hash) bad.push('a picture under public/brand/handout differs from the 2D checkout\'s');
    const body = (x) => x.split('\n').slice(1).join('\n');
    let now = ''; try { now = readFileSync(LIST, 'utf8'); } catch { /* missing */ }
    if (body(now) !== body(list)) bad.push('src/ui/deck/handout-figures.generated.ts is stale');
    return bad;
  }
  rmSync(OUT, { recursive: true, force: true });
  for (const [deck, ids] of Object.entries(figs)) {
    mkdirSync(resolve(OUT, deck), { recursive: true });
    for (const id of ids) writeFileSync(resolve(OUT, deck, `${id}.webp`), readFileSync(resolve(src, deck, `${id}.webp`)));
  }
  writeFileSync(LIST, list);
  return [];
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const i = process.argv.indexOf('--from'), from = i > 0 ? process.argv[i + 1] : '';
  if (!from) { console.error('usage: node scripts/copy-handout.mjs --from <2D checkout> [--check]'); process.exit(2); }
  const bad = copyAll(resolve(from), process.argv.includes('--check'));
  if (bad.length) { console.error(bad.join('\n')); process.exit(1); }
  console.log(`handout figures: ${Object.values(figuresIn(OUT)).reduce((a, b) => a + b.length, 0)} pictures`);
}
