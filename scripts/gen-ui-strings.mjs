#!/usr/bin/env node
// Writes src/ui/strings.generated.ts: the 2D app's interface words (top bar, view pills, play bar, Settings rows and hints, shortcut list, menus,
// search commands, lenses, patients, looks), taken from parity/inventory.json (which `npm run sync:inventory` copies from the 2D app). Components render
// from this table and never retype a word (parity plan section 2: "Words"). tests/ui-strings.test.ts fails when the committed file is not what this script gives.
//   node scripts/gen-ui-strings.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const inv = JSON.parse(readFileSync(resolve(here, '../parity/inventory.json'), 'utf8'));
const out = resolve(here, '../src/ui/strings.generated.ts');

export function render(inventory) {
  const { shell, presets, looks, lenses } = inventory;
  const data = {
    topbar: shell.topbar, views: shell.views, zoomGroup: shell.zoomGroup, playbar: shell.playbar,
    settings: shell.settings, helpPages: shell.helpPages, shortcuts: shell.shortcuts, menus: shell.menus,
    search: { placeholder: shell.palette.placeholder, emptyOrder: shell.palette.emptyOrder, groups: shell.palette.groups, commands: shell.palette.commands },
    platform: { pwa: shell.platform.pwa, deepLinks: shell.platform.deepLinks },
    presets, looks, lenses, treatTabs: inventory.treat.tabs, topics: inventory.topics,
    decks: inventory.decks.map((d) => ({ id: d.id, title: d.title, short: d.short, summary: d.summary, topic: d.topic, level: d.level, minutes: d.minutes, slides: d.slides.length })),
  };
  return `// GENERATED by scripts/gen-ui-strings.mjs from parity/inventory.json (2D app ${inventory.generatedFrom.commit.slice(0, 8)}). Do not edit: change the 2D app, then \`npm run sync:inventory\` and \`npm run gen:strings\`.\n`
    + `// The 2D app's interface words. Every control, row and hint in the shell renders from here, so the 3D app says what the 2D app says.\n\n`
    + `export const UI = ${JSON.stringify(data, null, 1)} as const;\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = render(inv);
  if (process.argv.includes('--check')) {
    let have = ''; try { have = readFileSync(out, 'utf8'); } catch { /* none */ }
    if (have !== text) { console.error('src/ui/strings.generated.ts is not what scripts/gen-ui-strings.mjs gives; run npm run gen:strings'); process.exit(1); }
    console.log('src/ui/strings.generated.ts is current');
  } else { writeFileSync(out, text); console.log(`wrote ${out} (${text.length} bytes)`); }
}
