#!/usr/bin/env node
// Writes the Advanced physiology panel's table and the 2D app's answers the 3D port is tested against, from a checkout of the 2D app (never retyped):
//   src/ui/settings/advanced.generated.ts   the four sections of chart.js advanced() in its order, each control of inspector.js CONTROLS it lists (label, range, step,
//                                           default, normal band, the ⓘ text, the 2D format function's own source, and where in the params its setter writes), and the
//                                           three action buttons with the engine action each sends
//   tests/fixtures/advanced-2d.json         for the slice patient: the 2D engine's readings after each control is put to each end of its range (a switch: flipped),
//                                           and what the 2D format prints at sample values
// Usage: node scripts/gen-advanced.mjs --from <2D checkout>
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const argv = process.argv.slice(2);
const from = resolve(argv[argv.indexOf('--from') + 1] || '../portal-pressure-simulator');
const at = (p) => pathToFileURL(resolve(from, p)).href;

await import(at('tests/dom-shim.js'));
const chartSrc = readFileSync(resolve(from, 'src/ui/chart.js'), 'utf8');
const { CONTROLS } = await import(at('src/ui/inspector.js'));
const { defaultParams } = await import(at('src/engine/portal/scenario.js'));
const { createCore } = await import(at('src/worker-core.js'));

// ── chart.js advanced(): the sections and the buttons, read from its source ──
const body = chartSrc.slice(chartSrc.indexOf('function advanced()'), chartSrc.indexOf('function render(ctl)'));
if (!body.includes("class: 'order-grid'")) throw new Error('chart.js advanced() no longer builds its buttons as .order-grid');
const sections = [...body.matchAll(/section\('(adv-[\w-]+)', '([^']+)', null, null, \.\.\.controls\(\[([^\]]+)\]\)(, acts)?\)/g)]
  .map((m) => ({ id: m[1], title: m[2], controls: [...m[3].matchAll(/'([\w:]+)'/g)].map((x) => x[1]), acts: !!m[4] }));
if (sections.length !== 4) throw new Error(`chart.js advanced() has ${sections.length} sections the generator can read, not 4`);
const acts = [...body.matchAll(/h\('button', \{ class: 'order-btn', onclick: \(\) => action\((\{[^}]*\})\) \}, h\('span', \{ class: 'ob-t' \}, '([^']+)', h\('small', \{\}, '([^']+)'\)\)\)/g)]
  .map((m) => ({ action: new Function(`return (${m[1]});`)(), label: m[2], sub: m[3] }));
if (acts.length !== 3) throw new Error(`chart.js advanced() has ${acts.length} buttons the generator can read, not 3`);

// ── inspector.js CONTROLS: each control the panel lists ──
/** Where a setter writes: the one leaf of the params it changes. */
function pathOf(c) {
  const a = defaultParams(), b = defaultParams();
  const v = c.type === 'toggle' ? !c.get(a) : (c.get(a) === c.max ? c.min : c.max);
  c.set(b, v);
  const walk = (x, y, p) => {
    if (x === y) return null;
    if (x && y && typeof x === 'object' && typeof y === 'object') { for (const k of new Set([...Object.keys(x), ...Object.keys(y)])) { const r = walk(x[k], y[k], [...p, k]); if (r) return r; } return null; }
    return p;
  };
  const p = walk(a, b, []);
  if (!p) throw new Error(`${c.label}: its setter changes nothing`);
  return p;
}
const ids = sections.flatMap((s) => s.controls);
const controls = {};
for (const id of ids) {
  const c = CONTROLS[id];
  if (!c) throw new Error(`inspector.js has no control "${id}"`);
  const path = pathOf(c);
  const o = { id, type: c.type, key: c.key, label: c.label, path, info: c.info ?? null, sub: c.sub ?? null };
  if (c.type === 'slider') Object.assign(o, { min: c.min, max: c.max, step: c.step, def: c.def ?? null, normal: c.normal ?? null, format: c.format.toString() });
  else { // (a switch whose leaf is absent: on or off? Gastrorenal shunt present reads "not false")
    const p = defaultParams(); let x = p; for (const k of path.slice(0, -1)) x = x[k]; delete x[path[path.length - 1]];
    o.absentOn = !!c.get(p); o.def = c.def ?? null;
  }
  controls[id] = o;
}

const ts = (v) => JSON.stringify(v);
const rows = ids.map((id) => {
  const c = controls[id];
  const f = c.type === 'slider' ? `, min: ${c.min}, max: ${c.max}, step: ${c.step}, def: ${ts(c.def)}, normal: ${ts(c.normal)}, format: ${c.format.replace(/^\((\w+)\)/, '($1: number)')}` : `, absentOn: ${c.absentOn}`;
  return `  ${ts(id)}: { id: ${ts(id)}, type: ${ts(c.type)}, key: ${ts(c.key)}, label: ${ts(c.label)}, path: ${ts(c.path)}, info: ${ts(c.info)}, sub: ${ts(c.sub)}${f} },`;
});
const out = `// GENERATED by scripts/gen-advanced.mjs from the 2D app (chart.js advanced(), inspector.js CONTROLS). Do not edit; run the script again.
export interface AdvSlider { id: string; type: 'slider'; key: string; label: string; path: readonly string[]; info: string | null; sub: string | null; min: number; max: number; step: number; def: number | null; normal: readonly [number, number] | null; format: (v: number) => string }
export interface AdvToggle { id: string; type: 'toggle'; key: string; label: string; path: readonly string[]; info: string | null; sub: string | null; absentOn: boolean }
export type AdvControl = AdvSlider | AdvToggle;
export const ADV_CONTROLS: Record<string, AdvControl> = {
${rows.join('\n')}
};
export const ADV_SECTIONS: readonly { id: string; title: string; controls: readonly string[]; acts: boolean }[] = ${ts(sections)};
export const ADV_ACTS: readonly { action: { kind: string; [k: string]: unknown }; label: string; sub: string }[] = ${ts(acts)};
`;
writeFileSync(resolve(root, 'src/ui/settings/advanced.generated.ts'), out);

// ── the 2D engine's answers ──
const KEYS = ['hvpg', 'whvp', 'fhvp', 'pv', 'ppg', 'ivc', 'ra', 'pvFlow', 'pvVel', 'map', 'co', 'hr', 'spleen', 'varix'];
/** One engine, the patient loaded once; each case is the patient's own settings with one control moved, settled, read (tests/advanced.test.ts runs the same sequence). */
async function run(edits) {
  const got = [];
  const core = createCore((m) => got.push(m));
  await core.handle({ type: 'init' });
  await core.handle({ type: 'run', running: false });
  await core.handle({ type: 'preset', id: 'csph', reqId: 1 });
  const base = got.find((m) => m.type === 'presetLoaded').params;
  const out = [];
  for (const [i, edit] of edits.entries()) {
    const params = structuredClone(base);
    edit(params);
    await core.handle({ type: 'setParams', params, settle: true });
    await core.handle({ type: 'metrics', reqId: 10 + i });
    const r = got.find((m) => m.type === 'metrics' && m.reqId === 10 + i).result;
    out.push(Object.fromEntries(KEYS.map((k) => [k, Math.round(r[k] * 1000) / 1000])));
  }
  core.dispose();
  return out;
}
const cases = [];
for (const id of ids) {
  const c = CONTROLS[id];
  for (const v of c.type === 'slider' ? [c.min, c.max] : [true, false]) cases.push({ id, value: v });
}
const answers = await run([() => {}, ...cases.map((k) => (p) => CONTROLS[k.id].set(p, k.value))]);
const base = answers.shift();
cases.forEach((k, i) => { k.readings = answers[i]; });
const formats = {};
for (const id of ids) { const c = CONTROLS[id]; if (c.type === 'slider') formats[id] = [c.min, c.def, (c.min + c.max) / 2, c.max, c.min + c.step].map((v) => [v, c.format(v)]); }
mkdirSync(resolve(root, 'tests/fixtures'), { recursive: true });
writeFileSync(resolve(root, 'tests/fixtures/advanced-2d.json'), `${JSON.stringify({ preset: 'csph', base, cases, formats })}\n`);
console.log(`advanced: ${ids.length} controls in ${sections.length} sections, ${acts.length} buttons, ${cases.length} engine cases`);
process.exit(0);
