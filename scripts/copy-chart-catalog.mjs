#!/usr/bin/env node
// Copies the 2D card gallery's specimens of the chart families (src/ui/gallery/catalog.js: the criteria, flow-time, path, curve, trial, profile, flows, lumen, plane, fluid, SAAG, shift,
// stent, forest, event-graph, course, menu and readout-tile cards) into src/ui/charts/gallery/catalog.generated.ts as plain data: each is one 2D deck slide as the deck writes it
// (`tool`, `data`, `tiles` ...). The parity claims of those cards (src/parity/b10.ts) read it, so a card is claimed only while the 3D app's own chart can be mounted
// for exactly that slide.
//
//   node scripts/copy-chart-catalog.mjs --from <2D checkout at the pin> [--check]
//
// --check writes nothing and exits 1 when the file differs from what the 2D app would give.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { uiTextEdits } from './source-edits.mjs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { execFileSync } from 'node:child_process';

const here = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(here, '../src/ui/charts/gallery/catalog.generated.ts');
const arg = (n) => { const i = process.argv.indexOf(n); return i > 0 ? process.argv[i + 1] : null; };
const from = arg('--from');
if (!from) { console.error('usage: node scripts/copy-chart-catalog.mjs --from <2D checkout at the pin> [--check]'); process.exit(2); }

let sha = 'b3058ef392';   // (the pin; a checkout with no .git, such as a `git archive`, is taken to be it)
try { sha = execFileSync('git', ['-C', from, 'rev-parse', '--short=10', 'HEAD'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim(); } catch { /* not a git checkout */ }

const FAMILIES = ['criteria', 'flowtime', 'path', 'curve', 'trial', 'profile', 'flows', 'lumen', 'plane', 'fluid', 'saag', 'shift', 'stent', 'forest', 'evgraph', 'course', 'menu', 'tiles'];
const { CATALOG } = await import(pathToFileURL(join(from, 'src/ui/gallery/catalog.js')).href);
const rows = CATALOG.filter((e) => FAMILIES.includes(e.family)).map((e) => ({ id: e.id, family: e.family, title: e.title, slide: e.slide, ...(e.deck ? { deck: e.deck } : {}) }));
const text0 = `// @generated by scripts/copy-chart-catalog.mjs from the 2D app's src/ui/gallery/catalog.js at ${sha}. Do not edit; run the script again.
// The 2D card gallery's specimens of the chart families: one deck slide each, as a 2D deck writes it (the gallery's id is the inventory's \`card:<id>\`).
export interface CatalogEntry { id: string; family: string; title: string; slide: Record<string, unknown>; deck?: string }
export const CATALOG: readonly CatalogEntry[] = [
${rows.map((r) => `  ${JSON.stringify(r)},`).join('\n')}
];
`;
const text = uiTextEdits(text0);
if (process.argv.includes('--check')) {
  if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== text) { console.error(`differs: ${OUT}`); process.exit(1); }
  console.log('catalog.generated.ts is current'); process.exit(0);
}
writeFileSync(OUT, text);
console.log(`wrote ${OUT} (${rows.length} specimens)`);
