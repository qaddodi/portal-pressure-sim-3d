#!/usr/bin/env node
// Copies the 2D app's lobule painter into the 3D app, line for line (WP5, the lobule as a plate: docs/atlas-look-plan.md §5):
//   src/ui/lobule-paint.js              -> src/scene/lobule/from2d/lobule-paint.generated.js   (the plates, zones, nutmeg, collagen, stellate cells)
//   src/ui/lobule-look.js               -> src/scene/lobule/from2d/lobule-look.generated.js    (cordTone, the bands' outline, the field's fade and blur numbers)
//   src/ui/lobule-zoom-field.js drawTile -> src/scene/lobule/from2d/field-tile.generated.js     (the neighbouring lobules' repeating tile)
//   styles/tokens.css (the lobule's look-independent --lz-* colours) -> src/scene/lobule/from2d/lz-tokens.generated.js
// Only the imports are pointed at this app's copies; drawTile is wrapped in a maker that is handed the few things its closure read (tk, cssRGB01, recordPaint).
//
//   node scripts/copy-lobule.mjs --from <2D checkout> [--check]       (or PPS_2D_REPO=<2D checkout>)
//
// --check writes nothing and exits 1 when a file differs from what the 2D app would give.

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const here = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(here, '../src/scene/lobule/from2d');
const arg = (n) => { const i = process.argv.indexOf(n); return i > 0 ? process.argv[i + 1] : null; };
const from = arg('--from') ?? process.env.PPS_2D_REPO;
if (!from) { console.error('usage: node scripts/copy-lobule.mjs --from <2D checkout> [--check]'); process.exit(2); }

let sha = 'unknown';
try { sha = execFileSync('git', ['-C', from, 'rev-parse', '--short=10', 'HEAD'], { encoding: 'utf8' }).trim(); } catch { /* not a git checkout */ }
const read = (rel) => readFileSync(join(from, rel), 'utf8');
const head = (rel, what = '') => `// @generated by scripts/copy-lobule.mjs from the 2D app's ${rel} at ${sha}. Do not edit; run the script again.\n// @ts-nocheck (the 2D app's own code, kept as it is${what})\n`;
const NUM = '../../../ui/charts/looks2d/num.js';

/** text with one exact line replaced (it must be there, once). */
function swap(text, a, b) {
  const i = text.indexOf(a);
  if (i < 0 || text.indexOf(a, i + 1) >= 0) throw new Error(`expected exactly one: ${a}`);
  return text.slice(0, i) + b + text.slice(i + a.length);
}

const paint = (() => {
  let t = read('src/ui/lobule-paint.js');
  t = swap(t, "import { clamp, lerp } from './num.js';", `import { clamp, lerp } from '${NUM}';`);
  t = swap(t, "import { cordToneInto, bandOutlineFlat } from './lobule-look.js';", "import { cordToneInto, bandOutlineFlat } from './lobule-look.generated.js';");
  return head('src/ui/lobule-paint.js') + t;
})();

const look = (() => {
  let t = read('src/ui/lobule-look.js');
  // (organ-dim.js pulls in the page; the one number the look reads from it is copied in its place)
  const m = /export const LENS_GREY = (\{[^}]*\});/.exec(read('src/ui/organ-dim.js'));
  if (!m) throw new Error('LENS_GREY not found in organ-dim.js');
  t = swap(t, "import { LENS_GREY } from './organ-dim.js';", `const LENS_GREY = ${m[1]};   // (organ-dim.js LENS_GREY, copied)`);
  return head('src/ui/lobule-look.js') + t;
})();

const tile = (() => {
  const t = read('src/ui/lobule-zoom-field.js');
  const a = t.indexOf('  function drawTile(t, { cell, gap, cvc, pvc, art, duct, dark, fs }) {');
  const z = t.indexOf('  // The surround fading into the page with distance from the lobule', a);
  if (a < 0 || z < 0) throw new Error('drawTile not found in lobule-zoom-field.js');
  const body = t.slice(a, z).trimEnd();
  return `${head('src/ui/lobule-zoom-field.js', ': drawTile alone, wrapped')}import { fibrousBand, fibrousCuff, fibrousTract, scarGrowth } from './lobule-paint.generated.js';
import { lerp } from '${NUM}';

const TAU = Math.PI * 2;
/** drawTile as the 2D field has it, made with what its closure read: tk(name, alpha?) a colour token's text, cssRGB01(name) its [r, g, b] (0 … 1),
 *  recordPaint(w, h, paint) a surface w × h painted by paint(context), which drawTile keeps as the tile's cv. */
export function makeDrawTile({ tk, cssRGB01, recordPaint }) {
  const live = { texVer: 0 };
  const gpuPicture = (rec) => rec;
${body}
  return drawTile;
}
`;
})();

const lz = (() => {
  const css = read('styles/tokens.css');
  const names = ['lz-shade', 'lz-congestion', 'lz-nutmeg', 'lz-zone-1', 'lz-zone-2', 'lz-zone-3', 'lz-hsc-body', 'lz-hsc-nucleus'];
  const root = css.slice(0, css.indexOf('}', css.indexOf(':root {')));
  const rows = names.map((n) => {
    const m = new RegExp(`--${n}:\\s*([^;]+);`).exec(root);
    if (!m) throw new Error(`--${n} not found in the :root block of styles/tokens.css`);
    return `  '${n}': '${m[1].trim()}',`;
  });
  return `${head('styles/tokens.css', ': the lobule\'s colours that are the same in every look')}export const LZ_TOKENS = {\n${rows.join('\n')}\n};\n`;
})();

const files = [['lobule-paint.generated.js', paint], ['lobule-look.generated.js', look], ['field-tile.generated.js', tile], ['lz-tokens.generated.js', lz]];
const check = process.argv.includes('--check');
const strip = (s) => s.replace(/ at [0-9a-f]{7,40}\. Do not edit/, ' at X. Do not edit');
let bad = 0;
if (!check && !existsSync(OUT)) mkdirSync(OUT, { recursive: true });
for (const [name, text] of files) {
  const p = join(OUT, name);
  if (check) {
    const now = existsSync(p) ? readFileSync(p, 'utf8') : '';
    if (strip(now) !== strip(text)) { console.error(`differs from the 2D app: src/scene/lobule/from2d/${name}`); bad++; }
  } else writeFileSync(p, text);
}
if (check && bad) process.exit(1);
console.log(check ? 'lobule copies match the 2D app' : `wrote ${files.length} files from ${sha}`);
