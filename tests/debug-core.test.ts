// The debug tools' shared core: the copied 2D files are never edited, the report format round-trips, a 2D paste is read by the 3D tools and the reverse, flags and limits are one table.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, readdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { buildRun as buildRunJs, renderRun, parseReport, validateRun, compareRuns, runBlock } from '../src/ui/debug/core/run.copied.js';
import { finding as findingJs } from '../src/ui/debug/core/finding.copied.js';
import { buildPacket, packetText, parsePacket } from '../src/ui/debug/core/packet.copied.js';
import { shortReport, fitMailto } from '../src/ui/debug/core/short.copied.js';
import { FLAGS, flagOn, flagValue, debugPage, knownFlags } from '../src/ui/debug/flags.ts';
import { isPreview } from '../src/ui/debug/gate.ts';
import { LIMITS, WORDS_MIN_PX, TITLE_RATIO } from '../src/ui/debug/limits.ts';

// The copied files are plain JS, so their defaults are typed narrowly; the tests pass the loose objects the tools pass.
const buildRun = buildRunJs as (o: Record<string, unknown>) => any; // eslint-disable-line @typescript-eslint/no-explicit-any
const finding = findingJs as (o: Record<string, unknown>) => any; // eslint-disable-line @typescript-eslint/no-explicit-any

const dir = new URL('../src/ui/debug/core/', import.meta.url);
const manifest = JSON.parse(readFileSync(new URL('MANIFEST.json', dir), 'utf8')) as { commit: string; files: Record<string, string> };

test('the copied 2D debug files are exactly what the manifest says (never edited here; change the 2D file and run copy-debug-core)', () => {
  const have = readdirSync(dir).filter((f) => f.endsWith('.copied.js')).sort();
  assert.deepEqual(have, Object.keys(manifest.files).sort());
  for (const f of have) assert.equal(createHash('sha256').update(readFileSync(new URL(f, dir), 'utf8')).digest('hex'), manifest.files[f], `${f} was edited by hand`);
  for (const f of have) assert.match(readFileSync(new URL(f, dir), 'utf8').split('\n')[0]!, /^\/\/ GENERATED by scripts\/copy-debug-core\.mjs/);
});

const sample = () => buildRun({ tool: 'check', build: { commit: 'abc123' }, device: { screen: '390x844' }, scope: { look: 'dark' }, started: '2026-11-19T21:00:00.000Z', ms: 1234,
  findings: [finding({ rule: 'fit-small', what: 'Card teach has lettering under 12 px', where: 'card teach at [0, 0, 10, 10]', owner: 'src/ui/DeckUi.tsx' }), { kind: 'edge-cutoff', text: 'a line runs past the card' }] });

test('one report format: a run builds, validates, prints with its JSON block and reads back whole', () => {
  const run = sample();
  assert.deepEqual(validateRun(run), { ok: true, errors: [] });
  const text = renderRun(run);
  assert.match(text, /PPS RUN REPORT v1 · check/);
  assert.match(text, /-----BEGIN REPORT JSON-----/);
  const back = parseReport(text);
  assert.ok(back.ok);
  assert.deepEqual(back.run, run);
  // chat wraps the JSON line and adds fences: still read
  const block = runBlock(run), wrapped = `\`\`\`\n${block.replace(/(.{60})/g, '$1\n')}\n\`\`\``;
  assert.ok(parseReport(wrapped).ok);
  // a block changed on its way is refused
  assert.equal(parseReport(runBlock(run).replace('fit-small', 'fit-smaLL')).ok, false);
});

test('a report the 2D app wrote is read here, whole, and compared with a 3D one (tests/fixtures/run-2d.txt, made by the 2D app\'s own report/run.js)', () => {
  const r = parseReport(readFileSync(new URL('./fixtures/run-2d.txt', import.meta.url), 'utf8'));
  assert.ok(r.ok, String(r.why));
  assert.equal(r.run.tool, 'phone-check');
  assert.deepEqual(r.run.findings.map((f: { rule: string }) => f.rule), ['fit-small', 'edge-cutoff']);
  assert.equal(compareRuns(r.run, sample()).verdict, 'partly');   // fit-small is still there in both; edge-cutoff was fixed
});

test('compare says what a fix changed: fixed, still and new', () => {
  const a = sample();
  const b = buildRun({ tool: 'check', findings: [finding({ rule: 'edge-cutoff', what: 'a line runs past the card' }), finding({ rule: 'label-overlap', what: 'two labels' })] });
  const c = compareRuns(a, b);
  assert.equal(c.verdict, 'partly');
  assert.deepEqual(c.fixed.map((f: { rule: string }) => f.rule), ['fit-small']);
  assert.deepEqual(c.introduced.map((f: { rule: string }) => f.rule), ['label-overlap']);
});

test('a bug packet round-trips and carries the check sum; a changed packet is refused', () => {
  const p = buildPacket({ state: { patient: 'csph' }, link: '/preview/?preset=csph', findings: [{ rule: 'fit-small', what: 'x', where: 'y' }], device: { screen: '390x844' } }, { note: 'the card is cut', now: () => new Date('2026-11-19T21:00:00Z') });
  const text = packetText(p);
  assert.ok(parsePacket(text).ok);
  assert.equal(parsePacket(text.replace('"csph"', '"cirr"')).ok, false);
  assert.match(shortReport(p), /1 finding/);
  assert.ok(encodeURIComponent(fitMailto('hello', 'x'.repeat(9000))).length <= 6000);
});

test('the flags are one table: the live site opens only the live ones; ?debug is the one name for the page and the old spellings hear it', () => {
  assert.ok(FLAGS.every((f) => /^[a-z]+$/.test(f.id)));
  assert.equal(new Set(FLAGS.map((f) => f.id)).size, FLAGS.length);
  const live = { pathname: '/portal-pressure-sim-3d/', hostname: 'qaddodi.github.io', search: '?debug&perf' };
  const prev = { pathname: '/portal-pressure-sim-3d/preview/', hostname: 'qaddodi.github.io', search: '?debug=check&watch' };
  assert.equal(isPreview(live), false); assert.equal(isPreview(prev), true);
  assert.equal(isPreview({ pathname: '/', hostname: 'localhost', search: '' }), true);
  assert.equal(flagOn('perf', live), true);          // ?perf works everywhere
  assert.equal(flagOn('debug', live), false);        // the debug page does not
  assert.equal(debugPage(live), null);
  assert.equal(debugPage(prev), 'check');
  assert.equal(flagOn('check', '?debug=check'), true); assert.equal(flagOn('gallery', '?debug'), true);
  assert.equal(debugPage({ ...prev, search: '?gallery=frame' }), 'frame'); assert.equal(debugPage({ ...prev, search: '?check=full' }), 'full');
  assert.equal(flagValue('only', '?only=a,b'), 'a,b');
  assert.equal(knownFlags().length, FLAGS.length);
});

test('the standing numbers are the app\'s own: text floor 12 px, title 1.4 times the words, and every limit has its date and words', () => {
  assert.equal(WORDS_MIN_PX, 12); assert.equal(TITLE_RATIO, 1.4);
  for (const l of LIMITS) { assert.ok(l.id && l.rule && l.since && l.exceptions, l.id); assert.ok(Number.isFinite(l.value)); }
});

test('no debug file reads the address itself: flags.ts is the one place', () => {
  const walk = (d: URL): string[] => readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(new URL(`${e.name}/`, d)) : [new URL(e.name, d).pathname]));
  for (const f of walk(new URL('../src/ui/debug/', import.meta.url)).filter((x) => /\.tsx?$/.test(x) && !/flags\.ts$|gate\.ts$/.test(x))) {
    assert.doesNotMatch(readFileSync(f, 'utf8').replace(/\/\/.*$/gm, ''), /location\.search|URLSearchParams\(/, `${f} reads the address: use flags.ts`);
  }
});
