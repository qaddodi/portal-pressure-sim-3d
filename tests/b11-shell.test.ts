// ── stand-in elements and touches ──
type Fn = (e: unknown) => void;
function el(extra: Record<string, unknown> = {}) {
  const on = new Map<string, Fn[]>(), style: Record<string, unknown> = { setProperty(k: string, v: string) { style[k] = v; }, removeProperty(k: string) { delete style[k]; } };
  return Object.assign({
    nodeType: 1, parentElement: null, scrollWidth: 0, clientWidth: 0, style, dataset: {}, matches: () => false, closest: () => null, classList: { add() {}, remove() {}, toggle() {}, contains: () => false },
    addEventListener(t: string, f: Fn) { (on.get(t) ?? on.set(t, []).get(t)!).push(f); }, removeEventListener(t: string, f: Fn) { on.set(t, (on.get(t) ?? []).filter((x) => x !== f)); },
    fire(t: string, e: Record<string, unknown> = {}) { for (const f of on.get(t) ?? []) f(e); },
  }, extra);
}
const touch = (el0: unknown, x: number, y: number) => ({ target: el0, touches: [{ clientX: x, clientY: y }], cancelable: true, preventDefault() {} });
const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

test('a sideways drag pages to the next tab and a short one springs back; nothing moves in a card with two instruments up', async () => {
  const body = el(), a = el(), b = el(), cur = { id: 'profile', peer: null as string | null, landed: null as string | null, begun: 0, finished: 0 };
  let enabled = true;
  const api: SwipeApi = {
    enabled: () => enabled, tabs: TABS, index: () => TABS.indexOf(cur.id as never), ready: () => true,
    peer: (id) => { cur.peer = id; }, active: () => a as unknown as HTMLElement, paneOf: () => b as unknown as HTMLElement,
    begin: () => { cur.begun++; }, finish: () => { cur.finished++; }, land: (id) => { cur.landed = id; },
  };
  const off = attachSwipe(body as unknown as HTMLElement, () => 400, api);
  // (a slow drag: the finger rests before it lifts, so only how far it went counts)
  const drag = async (to: number) => { body.fire('touchstart', touch(body, 300, 100)); body.fire('touchmove', touch(body, 300 - 20, 102)); await sleep(100); body.fire('touchmove', touch(body, 300 - to, 104)); await sleep(100); body.fire('touchend', {}); };
  await drag(260);   // 260 of 400 px: past a third
  assert.equal(cur.peer, 'profile' === cur.id ? TABS[1] : null, 'the next tab\'s pane is built beside the finger');
  await sleep(450);
  assert.equal(cur.landed, TABS[1], 'let go far out, it lands on the next tab');
  assert.equal(cur.finished, 1);
  cur.landed = null; cur.peer = null;
  await drag(60);   // a short drag, slow
  await sleep(450);
  assert.equal(cur.landed, null, 'a short drag springs back'); assert.equal(cur.peer, null, 'and takes the neighbour away');
  enabled = false; cur.begun = 0;
  await drag(260);
  assert.equal(cur.begun, 0, 'a card with two instruments does not page');
  off();
});

test('a vertical pull settles the sheet at Half or Full, or closes it; a pull that goes sideways is the swipe\'s', async () => {
  const card = el(), pos = el();
  const calls: string[] = [];
  let size: 0 | 1 | 2 = 0;
  const off = attachPull(card as unknown as HTMLElement, pos as unknown as HTMLElement, {
    enabled: () => true, heights: () => ({ h0: size === 1 ? 700 : size === 2 ? 72 : 520, half: 520, full: 700, peek: 72, size }), setSize: (n) => { size = n; calls.push(`size ${n}`); }, close: () => { calls.push('close'); },
  });
  // (slow pulls: the finger rests before it lifts, so only how far it went counts; a flick has its own case below)
  const ptr = (target: unknown, x: number, y: number) => ({ target, pointerId: 1, pointerType: 'touch', button: 0, buttons: 1, clientX: x, clientY: y });
  const pull = async (dy: number, dx = 0, flick = false) => {
    card.fire('pointerdown', ptr(card, 200, 400)); card.fire('pointermove', ptr(card, 200 + dx / 2, 400 + dy / 2)); if (!flick) await sleep(100);
    card.fire('pointermove', ptr(card, 200 + dx, 400 + dy)); if (!flick) await sleep(100); card.fire('pointerup', ptr(card, 200 + dx, 400 + dy));
  };
  await pull(-90); await sleep(450);
  assert.deepEqual(calls, ['size 1'], 'a pull up from Half goes to Full');
  await pull(80); await sleep(450);
  assert.deepEqual(calls, ['size 1', 'size 0'], 'a pull down from Full settles at Half, whatever its speed');
  calls.length = 0;
  await pull(-20); await sleep(450);
  assert.deepEqual(calls, [], 'a short pull up eases back');
  await pull(15, 200); await sleep(450);
  assert.deepEqual(calls, [], 'a sideways move is left to the swipe');
  await pull(200); await sleep(450);
  assert.deepEqual(calls, ['close'], 'a far pull down from Half closes the card in that one pull (2D; owner, 20 Nov: no stop at Peek)');
  assert.equal((pos as unknown as { dataset: Record<string, string> }).dataset.swiped, '', 'and it is marked as pulled shut: it is already out of sight, so it plays no leave of its own');
  size = 0; calls.length = 0;
  await pull(30, 0, true); await sleep(450);
  assert.deepEqual(calls, [], 'a short pull, even a quick one, is not a flick past 40 px: it eases back');
  const field = el({ closest: (sel: string) => (/input/.test(sel) ? field : null) });
  card.fire('pointerdown', ptr(field, 200, 400)); card.fire('pointermove', ptr(field, 200, 480)); card.fire('pointerup', ptr(field, 200, 480)); await sleep(30);
  assert.deepEqual(calls, [], 'a field keeps its own drag');
  off();
});

