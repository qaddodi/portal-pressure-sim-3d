import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { LS, fontPx } from '../src/scene/labels/type.ts';
import { PILL_GAP, TAG_AIR, tagType, cathVars, cathLook, tagSize, placePills, placeStack, sumLayout, leadersOf, swapOf, tightFor, sumFlow, SUM_MS, easeMove, easeArrive, bezier, type Reading } from '../src/scene/labels/cath.ts';
import { LOOK_IDS } from '../src/looks/looks.ts';

const measure = (t: string, size: number, weight: number, track = 0) => t.length * size * 0.56 * (weight >= 700 ? 1.05 : 1) + track * t.length;
const vp = { w: 1280, h: 800, safe: { top: 0, right: 0, bottom: 0, left: 0 } };
const phone = { w: 390, h: 844, safe: { top: 47, right: 0, bottom: 34, left: 0 } };
const F: Reading = { kicker: 'FHVP', value: '5.0', unit: 'mmHg', tone: 'free' };
const W: Reading = { kicker: 'WHVP', value: '17.5', unit: 'mmHg', tone: 'wedge' };
const H: Reading = { kicker: 'HVPG', value: '12.5', unit: 'mmHg', tone: 'danger' };
const band = { x0: 0, y0: 56, x1: 1280, y1: 800 };

test('the 2D card numbers are the copied ones, and the placing files are the 2D app\'s (PPS_2D_REPO compares)', () => {
  assert.equal(PILL_GAP, 18);
  assert.equal(LS.CATH.CARD.radius, 14); assert.equal(LS.CATH.MS.surface, 420);
  assert.match(readFileSync('src/scene/labels/cath2d/cath-pill.copied.js', 'utf8'), /^\/\/ @generated by scripts\/copy-label-names\.mjs/);
});

test('a tag is the station labels\' type: the same sizes, gaps and roles, no padding, radius or border of its own', () => {
  const t = tagType(vp), p = tagType(phone);
  assert.equal(t.name, fontPx(LS.NAME.size, vp)); assert.equal(t.num, fontPx(LS.VALUE.size, vp)); assert.equal(t.unit, fontPx(LS.UNIT.size, vp));
  assert.ok(t.num > p.num && t.name >= p.name && p.name >= 12, 'a phone sets the same roles smaller');
  assert.equal(t.gapVal, LS.NAME_TO_VALUE * LS.LABEL_K); assert.equal(t.air, TAG_AIR);
  const v = cathVars(vp);
  assert.equal(v['--cl-air'], '2px');
  for (const k of Object.keys(v)) assert.ok(!/pad|radius|border|^--cl-r$/.test(k), `${k}: a tag has no box to size`);
});

test('every look has the ink these tags read', () => {
  for (const l of LOOK_IDS) { const k = cathLook(l); for (const n of ['--cl-hv', '--cl-wedge', '--cl-surface', '--cl-text']) assert.ok(k[n], `${l} ${n}`); for (const n of ['--cl-rim', '--cl-fill', '--cl-edge']) assert.equal(k[n], undefined, `${l} ${n}: no rim, fill or edge to draw`); }
});

test('a reading is one line, name number unit: as wide as its words and the same for any digits', () => {
  const t = tagType(vp), a = tagSize(t, F, measure);
  assert.ok(a.h < 40 && a.h > t.num, `tag height ${a.h}`);
  assert.ok(a.w > measure('FHVP', t.name, LS.NAME.weight) + measure('mmHg', t.unit, LS.UNIT.weight), 'name, number and unit side by side');
  // the number counts every digit as one width: a value counting up keeps its box
  assert.deepEqual(tagSize(t, { ...W, value: '17.5' }, measure), tagSize(t, { ...W, value: '99.9' }, measure));
  // words alone (a caliper's) are the same tag without a number
  assert.ok(tagSize(t, { kicker: '7.3 mm', value: '', unit: '', tone: 'free' }, measure).w < a.w);
});

test('the two readings stand clear of a card, the free one above its point and the wedged one below, and keep their place while clear', () => {
  const t = tagType(vp), fs = tagSize(t, F, measure), ws = tagSize(t, W, measure);
  const items = [{ id: 'f', x: 600, y: 300, ...fs, prefer: true, was: null }, { id: 'w', x: 640, y: 380, ...ws, prefer: false, was: null }];
  const card = { x0: 560, y0: 120, x1: 760, y1: 260 };
  const out = placePills(items, band, [card]);
  assert.equal(out.length, 2);
  for (const o of out) assert.ok(!('dir' in o) && !('ax' in o), `${o.id}: no pointer side or lean on a placed tag`);
  for (const o of out) assert.ok(o.box.y1 <= card.y0 || o.box.y0 >= card.y1 || o.box.x1 <= card.x0 || o.box.x0 >= card.x1, `${o.id} clear of the card`);
  const again = placePills(items.map((i, n) => ({ ...i, was: out[n].side })), band, [card]);
  assert.deepEqual(again.map((o) => [o.x0, o.y0]), out.map((o) => [o.x0, o.y0]));
  assert.equal(placePills([], band, []).length, 0);
});

test('the stack: rows stretched to the widest, bracket joins the rows\' middles, the HVPG centred beside it; swap puts the lower point\'s reading lower', () => {
  const t = tagType(vp);
  const g = sumLayout(t, [W, F], H, measure, false, false), s = sumLayout(t, [W, F], H, measure, false, true);
  assert.equal(g.rows[0].w, g.rows[1].w);
  assert.ok(g.rows[0].y < g.rows[1].y && s.rows[0].y > s.rows[1].y, 'swap reverses the rows');
  const mid = g.rows[0].y + g.rows[0].h / 2;
  assert.match(g.brace.d, new RegExp(`^M${LS.CATH.BRACE.x0} ${+mid.toFixed(2)} H${LS.CATH.BRACE.x1} V`));
  assert.ok(Math.abs(g.calc.y + g.calc.h / 2 - g.h / 2) < 0.01 && g.calc.x > g.rows[0].w);
  assert.equal(swapOf(300, 380, false), true); assert.equal(swapOf(300, 303, true), true, 'a near tie keeps the order'); assert.equal(swapOf(300, 200, true), false);
  assert.equal(sumLayout(t, [W, F], H, measure, true, false).rows[0].h, g.rows[0].h, 'every reading is one line, tight or not');
  assert.equal(tightFor({ x0: 0, y0: 56, x1: 390, y1: 300 }), true); assert.equal(tightFor(band), false);
});

test('the stack stands clear of the vein between its points; each leader runs from its row to its point', () => {
  const t = tagType(vp), g = sumLayout(t, [W, F], H, measure, false, false);
  const tip: [number, number] = [500, 400], ahead: [number, number] = [540, 330];
  const at = placeStack(tip, ahead, g.w, g.h, band, []);
  const keep = { x0: 492, y0: 322, x1: 548, y1: 408 };
  assert.ok(at.x + g.w <= keep.x0 || at.x >= keep.x1 || at.y + g.h <= keep.y0 || at.y >= keep.y1, 'off the vein');
  const L = leadersOf([at.x, at.y], g, [ahead, tip], tip, ahead);
  assert.equal(L.d.length, 2); assert.ok(L.d[0].startsWith('M') && L.d[1].startsWith('M'));
  assert.deepEqual(L.dots[0], [ahead[0] - at.x, ahead[1] - at.y]);
});

test('the summary comes as the 2D app\'s: the readings travel, then the bracket and leaders, then the HVPG', () => {
  assert.deepEqual([SUM_MS.travel, SUM_MS.brace, SUM_MS.calc], [420, 650, 750]);
  const a = sumFlow(0, true), z = sumFlow(SUM_MS.total, true);
  assert.equal(a.flip, 1); assert.equal(a.lead, 0); assert.equal(a.calc, 0); assert.equal(z.flip, 0); assert.equal(z.lead, 1); assert.equal(z.calc, 1); assert.equal(z.calcRise, 0);
  assert.equal(sumFlow(300, true).lead, 0, 'the bracket waits'); assert.ok(sumFlow(800, true).lead > 0 && sumFlow(800, true).calc > 0 && sumFlow(800, true).calc < 1);
  assert.equal(sumFlow(0, false).rise, LS.CATH.RISE); assert.equal(sumFlow(0, true).rise, 0);
  assert.ok(easeMove(0.5) > 0.49 && easeMove(0.5) < 0.51); assert.ok(easeArrive(0.2) > 0.5, 'the arrive curve starts fast');
  assert.equal(bezier([0, 0, 1, 1])(0.3).toFixed(3), '0.300');
});
