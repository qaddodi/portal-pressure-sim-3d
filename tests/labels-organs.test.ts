// Where an organ's name stands: the 2D app's organ-names.js (copied), on the screen. A name keeps to its organ (or beside it, as the 2D app's NEAR says),
// steps to the next spot where a vessel runs under it, and keeps off the other organs where it can.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { silhouettes, onOtherOrgan, spotOffsets, organOfName } from '../src/scene/labels/organ-screen.ts';
import { solve, type Item } from '../src/scene/labels/solver.ts';
// @ts-ignore copied plain JS
import { nameSpots, NAME_ORGAN, NEAR } from '../src/scene/labels/organ2d/organ-names.copied.js';
// @ts-ignore copied plain JS
import { ORGAN_LABELS } from '../src/scene/labels/organ2d/outlines.copied.js';
import { LABEL_NAMES } from '../src/scene/labels/names.copied.ts';
import { STATIONS } from '../src/scene/labels/stations.ts';
import { placedAnchor } from '../src/scene/labels/organ2d/placed-spots.ts';

// the 2D plate itself as the screen: one canvas px a 2D unit, shifted
const to = (x: number, y: number): [number, number] => [x + 40, y + 60];

test('every organ the 2D plate names has a station, at the 2D place, and the copied outlines and spots are the 2D app\'s (the script compares)', () => {
  assert.deepEqual(ORGAN_LABELS, Object.entries(LABEL_NAMES.ORGAN_AT).map(([k, v]) => [k, ...v]), 'ORGAN_LABELS = the names file\'s ORGAN_AT');
  for (const [word] of ORGAN_LABELS) assert.ok(STATIONS.some((s) => s.kind === 'organ' && s.name === word && s.at2d), `${word} has its station`);
  for (const f of ['organ-names.copied.js', 'outlines.copied.js']) assert.match(readFileSync(`src/scene/labels/organ2d/${f}`, 'utf8'), /^\/\/ @generated by scripts\/copy-organ-names\.mjs/);
  assert.equal(NEAR, 28);
  assert.ok(nameSpots('Spleen').length > 5 && nameSpots('Liver').length > 5);
});

test('a name\'s other spots are offsets from its anchor on the screen, nearest first', () => {
  // (the spots are the placed organ's, round its placed name anchor, which is what a station hands in: stations.ts organStation `at2d`; the 2D plate's anchor, (1066, 250), is the old anatomy's)
  const o = spotOffsets('Spleen', placedAnchor('Spleen')!, to);
  assert.ok(o.length > 5);
  const d = o.map(([x, y]) => Math.hypot(x, y));
  assert.ok(d.every((v, i) => i === 0 || v >= d[i - 1] - 1e-9), 'nearest first');
});

test('a name keeps off the other organs: the atrium\'s box on the esophagus is on another organ, the esophagus\'s own is not', () => {
  const sil = silhouettes(to);
  const box = { x0: to(776, 120)[0], y0: to(776, 120)[1], x1: to(812, 140)[0], y1: to(812, 140)[1] };
  assert.equal(organOfName('Right atrium'), 'heart'); assert.equal((NAME_ORGAN as Record<string, string>)['Esophagus'], 'esophagus');
  assert.equal(onOtherOrgan('Right atrium', sil, box), true);
  assert.equal(onOtherOrgan('Esophagus', sil, box), false);
});

const form = { text: 'x', w: 80, h: 18 };
test('a name under a vessel steps to the nearest spot of its organ that no vessel touches; one with room stays where it is', () => {
  const base: Item = { id: 'organ:liver', ax: 400, ay: 300, au: 0.5, forms: [form], pri: 2, region: true, spots: [[0, 40], [60, 0], [-60, 0]] };
  const view = { x0: 0, y0: 0, x1: 800, y1: 600 };
  const free = solve({ items: [base], view, blockers: [] });
  assert.equal(free.placed[0].dy, -9, 'at its own place');
  const under = solve({ items: [base], view, blockers: [], lines: [[300, 300, 500, 300]] });
  assert.ok(Math.abs(under.placed[0].dy - (40 - 9)) < 1e-9 && under.placed[0].dx === -40, `moved to the first clear spot, not ${JSON.stringify(under.placed[0])}`);
});

test('a name keeps off another organ while any spot is clear, and is never left off for it', () => {
  const view = { x0: 0, y0: 0, x1: 800, y1: 600 };
  const on = (b: { x0: number; x1: number }) => b.x0 < 440 && b.x1 > 360;     // the other organ's column
  const it: Item = { id: 'organ:heart', ax: 400, ay: 300, au: 0.5, forms: [form], pri: 2, region: true, spots: [[0, 60], [200, 0]], onOther: (b) => on(b) };
  const p = solve({ items: [{ ...it, onOther: (b) => b.x0 < 440 && b.x1 > 360 }], view, blockers: [] }).placed[0];
  assert.equal(p.dx, 200 - 40, 'the clear spot, not the anchor');
  const never = solve({ items: [{ ...it, spots: [], onOther: () => true }], view, blockers: [] });
  assert.equal(never.placed.length, 1, 'never left off for it');
});

test('the last resort keeps a name on its own organ over a vessel before it leaves it for another organ (RIGHT ATRIUM sat on the liver edge below the atrium, phone, Variceal bleed 2)', () => {
  const view = { x0: 0, y0: 0, x1: 800, y1: 600 };
  const below = (b: { y0: number; y1: number }) => b.y0 >= 305 ? 1 : b.y1 > 305 ? (b.y1 - 305) / (b.y1 - b.y0) : 0;   // another organ lies below y 305, so no spot keeps off it; its own is above
  const it: Item = { id: 'organ:heart', ax: 400, ay: 300, au: 0.5, forms: [form], pri: 2, region: true, spots: [[0, 40], [0, 60]], onOther: (b) => below(b) > 0 };
  const lines: [number, number, number, number][] = [[300, 300, 500, 300]];   // the IVC across the atrium
  const was = solve({ items: [it], view, blockers: [], lines }).placed[0];
  assert.equal(was.dy, 40 - 9, 'priced by lines alone, it left its organ');
  const now = solve({ items: [{ ...it, otherShare: below }], view, blockers: [], lines }).placed[0];
  assert.equal(now.dy, -9, 'it stays on its own organ');
});
